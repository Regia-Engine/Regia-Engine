/// A glTF scatter mesh: one [`ScatterPart`] per material.
#[derive(Clone, Debug)]
pub struct ScatterModel {
    /// The parts.
    pub parts: Vec<ScatterPart>,
    /// Triangles of LOD 0 over every part.
    pub triangles_lod0: usize,
}

impl ScatterModel {
    /// Builds the drawable model from a loaded glTF: LOD levels concatenated per part, coarse levels generated by
    /// vertex clustering (`regia_terrain::coarse_lod`) when the file has only LOD 0.
    #[must_use]
    pub fn from_gltf(model: crate::gltf::Model) -> Self {
        let min = model.bounds_min;
        let max = model.bounds_max;
        let center = [0, 1, 2].map(|k| 0.5 * (min[k] + max[k]));
        let radius = 0.5
            * [0, 1, 2]
                .map(|k| (max[k] - min[k]).max(0.0))
                .iter()
                .map(|d| d * d)
                .sum::<f32>()
                .sqrt();
        let triangles_lod0 = model.triangles_lod0;
        // Parts that start below the finest level (a tree's far billboard) belong to the streamed field's chain
        // ([`scatter_asset`]); an entity draws its levels from the finest one.
        let finest = model
            .parts
            .iter()
            .filter_map(|p| p.lods.first())
            .map(|l| l.source_lod)
            .min();
        let parts = model
            .parts
            .into_iter()
            .filter(|part| part.lods.first().map(|l| l.source_lod) == finest)
            .filter_map(|part| {
                let mut lods: Vec<(Vec<LabVertex>, Vec<u32>)> = part
                    .lods
                    .into_iter()
                    .take(SCATTER_LOD_SCREEN_SIZES.len())
                    .map(|lod| (lod.vertices, lod.indices))
                    .collect();
                if lods.len() == 1 {
                    for cells in SCATTER_COARSE_LOD_CELLS {
                        let Some((vertices, indices)) = lods.last() else {
                            break;
                        };
                        let (v, i) = regia_terrain::coarse_lod(vertices, indices, cells);
                        if i.is_empty() || i.len() >= indices.len() {
                            break;
                        }
                        lods.push((v, i));
                    }
                }
                let mut vertices: Vec<LabVertex> = Vec::new();
                let mut levels: Vec<MeshLodLevel> = Vec::with_capacity(lods.len());
                for ((lod_vertices, lod_indices), screen_size) in
                    lods.into_iter().zip(SCATTER_LOD_SCREEN_SIZES)
                {
                    let base = vertices.len() as u32;
                    vertices.extend(lod_vertices);
                    levels.push(MeshLodLevel {
                        indices: Arc::new(lod_indices.iter().map(|i| i + base).collect()),
                        screen_size,
                    });
                }
                if let Some(last) = levels.last_mut() {
                    last.screen_size = 0.0;
                }
                let first = levels.first()?;
                if first.indices.is_empty() {
                    return None;
                }
                let mesh = Arc::new(CpuMesh {
                    vertices,
                    indices: first.indices.as_ref().clone(),
                });
                Some(ScatterPart {
                    mesh,
                    material: part.material,
                    lods: MeshLodChain {
                        levels,
                        bounds_center: center,
                        bounds_radius: radius,
                    },
                })
            })
            .collect();
        Self {
            parts,
            triangles_lod0,
        }
    }
}

/// The streamed scatter field's asset for a glTF scatter mesh ([`regia_terrain::ScatterField`], ADR-1415): every
/// material part aligned on the model's levels (a part missing a level is empty there, so a tree's bark and twigs
/// end where its billboard begins), the first part present at the finest level as the main mesh, the LOD switch
/// sizes from the file's `lod_screen_size` extras converted to the field's measure (bounding radius over distance,
/// against the view's half height) or [`SCATTER_LOD_SCREEN_SIZES`], coarse levels generated by vertex clustering
/// when the file has only one, and the file's `shadow_lod`. `None` when the model has no usable finest level.
#[must_use]
pub fn scatter_asset(model: &crate::gltf::Model) -> Option<ScatterMeshAsset> {
    let mut levels: Vec<u32> = model
        .parts
        .iter()
        .flat_map(|p| p.lods.iter().map(|l| l.source_lod))
        .collect();
    levels.sort_unstable();
    levels.dedup();
    levels.truncate(MAX_SCATTER_LODS);
    let finest = *levels.first()?;
    let main = model
        .parts
        .iter()
        .position(|p| p.lods.iter().any(|l| l.source_lod == finest))?;
    let lod_of = |part: &crate::gltf::ModelPart, level: u32| {
        part.lods.iter().find(|l| l.source_lod == level).map_or_else(
            || ScatterMeshLod {
                vertices: Vec::new(),
                indices: Vec::new(),
                screen_size: 0.0,
            },
            |l| ScatterMeshLod {
                vertices: l.vertices.clone(),
                indices: l.indices.clone(),
                screen_size: 0.0,
            },
        )
    };
    // The file's sizes are the tree's height over the view height; the field measures the bounding radius over
    // the view's half height.
    let (lo, hi) = (model.bounds_min, model.bounds_max);
    let height = (hi[1] - lo[1]).max(1e-3);
    let radius = 0.5
        * [0, 1, 2]
            .map(|k| (hi[k] - lo[k]).max(0.0).powi(2))
            .iter()
            .sum::<f32>()
            .sqrt();
    let to_field = 2.0 * radius.max(1e-3) / height;
    let mut lods: Vec<ScatterMeshLod> = levels
        .iter()
        .enumerate()
        .map(|(k, &level)| {
            let mut lod = lod_of(&model.parts[main], level);
            lod.screen_size = model
                .lod_screen_sizes
                .iter()
                .find(|(l, _)| *l == level)
                .map_or(SCATTER_LOD_SCREEN_SIZES[k], |(_, size)| size * to_field);
            lod
        })
        .collect();
    if let Some(last) = lods.last_mut() {
        last.screen_size = 0.0;
    }
    let parts = model
        .parts
        .iter()
        .enumerate()
        .filter(|(i, _)| *i != main)
        .map(|(_, part)| ScatterMeshPart {
            lods: levels.iter().map(|&level| lod_of(part, level)).collect(),
            material: part.material.clone(),
        })
        .filter(|part| part.lods.iter().any(|l| !l.indices.is_empty()))
        .collect();
    let shadow_lod = model
        .shadow_lod
        .and_then(|level| levels.iter().position(|&l| l >= level))
        .unwrap_or(0);
    let mut asset = ScatterMeshAsset {
        lods,
        material: model.parts[main].material.clone(),
        parts,
        shadow_lod: u8::try_from(shadow_lod).unwrap_or(0),
    };
    if levels.len() == 1 {
        for (cells, size) in SCATTER_COARSE_LOD_CELLS.into_iter().zip(SCATTER_LOD_SCREEN_SIZES) {
            asset = regia_terrain::with_coarse_lod(&asset, cells, size);
        }
    }
    asset.validate("scatter glTF").ok()?;
    Some(asset)
}

