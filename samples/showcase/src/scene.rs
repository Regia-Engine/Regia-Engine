/// Largest side of a glTF scatter mesh's texture maps, texels (a scatter instance is small on screen; Poly Haven's
/// 2K maps are halved on load).
pub const SCATTER_TEXTURE_MAX: u32 = 1024;

/// Minimum projected size of each LOD of a glTF scatter mesh (1 = the bounding diameter fills the view height),
/// finest first; the last level used is always 0.
pub const SCATTER_LOD_SCREEN_SIZES: [f32; 4] = [0.12, 0.035, 0.01, 0.0];

/// Vertex-clustering grids (cells per bounding-box side) of the coarse LODs generated for a glTF mesh that has
/// only one level.
pub const SCATTER_COARSE_LOD_CELLS: [u32; 2] = [28, 10];

/// One material of a glTF scatter mesh, ready to draw: a vertex buffer holding every LOD (LOD 0's triangles as
/// its index list) and the engine's LOD chain over it.
#[derive(Clone, Debug)]
pub struct ScatterPart {
    /// Vertices of every LOD; `indices` are LOD 0's.
    pub mesh: Arc<CpuMesh>,
    /// The part's material (the class tint is applied per class when the instances are spawned).
    pub material: CpuMaterial,
    /// LOD levels over `mesh`, finest first (`regia_render::MeshLodChain`).
    pub lods: MeshLodChain,
}

