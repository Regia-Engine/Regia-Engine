//! Scene directory loading.
//!
//! A scene directory holds `scene.ron` (the manifest) and the files it names:
//!
//! ```text
//! my_scene/
//!   scene.ron                  manifest (this module's [`Manifest`])
//!   heightfield.png            16-bit grayscale PNG, row 0 at -Z, column 0 at -X
//!   terrain.layers.ron         splat layers (regia_terrain `TerrainLayers`)
//!   scatter/rocks.scatter.ron  optional scatter set (format v2)
//!   sky.ron                    sky and weather state ([`crate::sky::SkyFile`])
//!   track.ron                  optional scripted track ([`crate::track::Track`])
//!   spawns.ron                 optional VFX and decal schedule ([`crate::spawns::SpawnFile`])
//!   vfx/                       optional `*.vfx.ron` and `*.decal.ron` the spawns may name
//! ```
//!
//! Loading never panics: every failure is a [`ShowcaseError`] with a stable [`ErrorCode`].
//! All paths in the manifest are relative to the scene directory and may not leave it.

