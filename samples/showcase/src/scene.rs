/// The procedural relief of the engine's photoreal terrain path (`regia_terrain::TerrainRelief`), as a scene
/// sets it.
///
/// The engine's own defaults are tuned for bare planetary ground: within about 30 m they add grain, pebbles and
/// their micro shadows, and from 12 to 250 m a rock-and-pit normal, over every layer that is not ice. Over
/// photographed layer textures (grass, leaf litter, mud) that procedural detail hides the texture's own
/// millimetre detail and reads as smeared blobs and ripples. The default here is the photo-texture preset: those
/// terms, the rock strata and the fractured-rock normal are off; the lighting terms (self-shadow, cavity, bounce,
/// glints on snow, geometric cliff relief) stay on.
#[derive(Clone, Copy, Debug, PartialEq, Serialize, Deserialize)]
#[serde(default, deny_unknown_fields)]
pub struct ReliefSpec {
    /// Near-field grain, pebbles and ice crust within ~30 m, `0..=2` (0 = off).
    pub near_detail: f32,
    /// Mid-range rock-and-pit relief, 12 to 250 m, `0..=2` (0 = off).
    pub mid_relief: f32,
    /// Altitude-banded rock strata on steep faces, `0..=1` (0 = off).
    pub strata: f32,
    /// Fractured-rock detail normal on steep faces, `0..=2` (0 = off).
    pub rock_detail: f32,
    /// Darker debris at the foot of faces, `0..=1`.
    pub talus: f32,
    /// Reach of the heightfield self-shadow toward the sun near the camera, metres (0 = off).
    pub self_shadow_reach_m: f32,
    /// Crust and concavity occlusion of the sky light, `0..=1`.
    pub cavity: f32,
    /// Sparkle on bright crystalline layers (snow, ice), `0..=4`.
    pub glints: f32,
    /// Sunlight bounced off the surrounding terrain, `0..=2` (1 = physical).
    pub bounce: f32,
    /// Geometric relief on steep faces, `0..=2`.
    pub cliff_relief: f32,
    /// Strength of the layers' ORM occlusion on the indirect light, `0..=1`.
    pub layer_occlusion: f32,
}

impl Default for ReliefSpec {
    fn default() -> Self {
        Self::photo()
    }
}

impl ReliefSpec {
    /// The photo-texture preset (the default): no procedural surface detail over the layer textures.
    #[must_use]
    pub fn photo() -> Self {
        let engine = TerrainRelief::default();
        Self {
            near_detail: 0.0,
            mid_relief: 0.0,
            strata: 0.0,
            rock_detail: 0.0,
            talus: engine.talus,
            self_shadow_reach_m: engine.self_shadow_reach_m,
            cavity: engine.cavity,
            glints: engine.glints,
            bounce: engine.bounce,
            cliff_relief: engine.cliff_relief,
            layer_occlusion: engine.layer_occlusion,
        }
    }

    /// The engine's defaults (tuned for bare planetary ground).
    #[must_use]
    pub fn engine() -> Self {
        let engine = TerrainRelief::default();
        Self {
            near_detail: engine.near_detail,
            mid_relief: engine.mid_relief,
            strata: engine.strata_strength,
            rock_detail: engine.rock_detail,
            talus: engine.talus,
            self_shadow_reach_m: engine.self_shadow_reach_m,
            cavity: engine.cavity,
            glints: engine.glints,
            bounce: engine.bounce,
            cliff_relief: engine.cliff_relief,
            layer_occlusion: engine.layer_occlusion,
        }
    }

    /// The engine value: these strengths over `TerrainRelief::default()` (strata geometry unchanged).
    #[must_use]
    pub fn to_engine(&self) -> TerrainRelief {
        TerrainRelief {
            strata_strength: self.strata,
            rock_detail: self.rock_detail,
            talus: self.talus,
            self_shadow_reach_m: self.self_shadow_reach_m,
            cavity: self.cavity,
            glints: self.glints,
            near_detail: self.near_detail,
            mid_relief: self.mid_relief,
            bounce: self.bounce,
            cliff_relief: self.cliff_relief,
            layer_occlusion: self.layer_occlusion,
            ..TerrainRelief::default()
        }
    }

    /// Every value finite and inside its range.
    fn check(&self) -> Result<(), String> {
        let ranges = [
            ("near_detail", self.near_detail, 2.0),
            ("mid_relief", self.mid_relief, 2.0),
            ("strata", self.strata, 1.0),
            ("rock_detail", self.rock_detail, 2.0),
            ("talus", self.talus, 1.0),
            ("self_shadow_reach_m", self.self_shadow_reach_m, 1000.0),
            ("cavity", self.cavity, 1.0),
            ("glints", self.glints, 4.0),
            ("bounce", self.bounce, 2.0),
            ("cliff_relief", self.cliff_relief, 2.0),
            ("layer_occlusion", self.layer_occlusion, 1.0),
        ];
        for (name, value, max) in ranges {
            if !value.is_finite() || !(0.0..=max).contains(&value) {
                return Err(format!("relief.{name} is {value}; it must be within 0..={max}"));
            }
        }
        Ok(())
    }
}

