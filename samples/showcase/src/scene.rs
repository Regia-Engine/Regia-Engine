impl std::fmt::Debug for SceneData {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("SceneData")
            .field("dir", &self.dir)
            .field("name", &self.manifest.name)
            .field("heightfield", &(self.map.width(), self.map.height()))
            .field("layers", &self.layers.layers.len())
            .field("scatter", &self.scatter.as_ref().map(|s| s.classes.len()))
            .field("track", &self.track.as_ref().map(|t| t.entity.as_str()))
            .field("events", &(self.spawns.effects.len() + self.spawns.decals.len()))
            .field("features", &self.features.names())
            .finish_non_exhaustive()
    }
}

/// Resolves `rel` inside `dir`, refusing absolute paths and `..`.
fn inside(dir: &Path, rel: &str, manifest: &Path) -> Result<PathBuf, ShowcaseError> {
    let rel_path = Path::new(rel);
    let escapes = rel.is_empty()
        || rel_path.is_absolute()
        || rel_path.components().any(|c| {
            matches!(
                c,
                Component::ParentDir | Component::RootDir | Component::Prefix(_)
            )
        });
    if escapes {
        return Err(ShowcaseError::new(
            ErrorCode::SceneManifestMalformed,
            manifest,
            format!("path '{rel}' must be relative and stay inside the scene directory"),
        ));
    }
    Ok(dir.join(rel_path))
}

fn read_text(path: &Path) -> Result<String, ShowcaseError> {
    std::fs::read_to_string(path).map_err(|e| {
        let code = if e.kind() == std::io::ErrorKind::NotFound {
            ErrorCode::SceneFileMissing
        } else {
            ErrorCode::SceneManifestMalformed
        };
        ShowcaseError::new(code, path, e.to_string())
    })
}

fn require_file(path: &Path) -> Result<(), ShowcaseError> {
    if path.is_file() {
        Ok(())
    } else {
        Err(ShowcaseError::new(
            ErrorCode::SceneFileMissing,
            path,
            "the manifest names this file but it does not exist",
        ))
    }
}

/// Decodes a grayscale PNG into `u16` samples (8-bit samples are widened by `v * 257`).
fn decode_gray(
    path: &Path,
    require_16: bool,
    code: ErrorCode,
) -> Result<(u32, u32, Vec<u16>), ShowcaseError> {
    let bad = |message: String| ShowcaseError::new(code, path, message);
    let file = std::fs::File::open(path).map_err(|e| {
        let code = if e.kind() == std::io::ErrorKind::NotFound {
            ErrorCode::SceneFileMissing
        } else {
            code
        };
        ShowcaseError::new(code, path, e.to_string())
    })?;
    let mut decoder = png::Decoder::new(std::io::BufReader::new(file));
    decoder.set_transformations(png::Transformations::IDENTITY);
    let mut reader = decoder.read_info().map_err(|e| bad(e.to_string()))?;
    let info = reader.info();
    let (w, h) = (info.width, info.height);
    let depth = info.bit_depth;
    if info.color_type != png::ColorType::Grayscale {
        return Err(bad(format!("expected grayscale, found {:?}", info.color_type)));
    }
    if require_16 && depth != png::BitDepth::Sixteen {
        return Err(bad(format!("expected 16-bit, found {depth:?}")));
    }
    if depth != png::BitDepth::Sixteen && depth != png::BitDepth::Eight {
        return Err(bad(format!("expected 8 or 16 bits, found {depth:?}")));
    }
    if w < 2 || h < 2 || w > MAX_HEIGHTFIELD_SIDE || h > MAX_HEIGHTFIELD_SIDE {
        return Err(bad(format!(
            "{w}x{h} samples (each side must be within 2..={MAX_HEIGHTFIELD_SIDE})"
        )));
    }
    let size = reader
        .output_buffer_size()
        .ok_or_else(|| bad("image too large".into()))?;
    let mut buf = vec![0u8; size];
    reader.next_frame(&mut buf).map_err(|e| bad(e.to_string()))?;
    let samples: Vec<u16> = if depth == png::BitDepth::Sixteen {
        buf.as_chunks::<2>()
            .0
            .iter()
            .map(|b| u16::from_be_bytes(*b))
            .collect()
    } else {
        buf.iter().map(|&v| u16::from(v) * 257).collect()
    };
    if samples.len() != (w as usize) * (h as usize) {
        return Err(bad("pixel count does not match the dimensions".into()));
    }
    Ok((w, h, samples))
}

/// Largest layer texture side, texels.
pub const MAX_LAYER_TEXTURE_SIDE: u32 = 4096;

/// Largest splat pack side, texels.
pub const MAX_SPLAT_SIDE: u32 = 8192;

/// Decodes an 8-bit-per-channel PNG (16-bit is reduced to 8) into RGBA8; errors carry `code`.
fn decode_rgba_as(
    path: &Path,
    max_side: u32,
    code: ErrorCode,
) -> Result<regia_terrain::Rgba8Image, ShowcaseError> {
    let bad = |message: String| ShowcaseError::new(code, path, message);
    let file = std::fs::File::open(path).map_err(|e| {
        let code = if e.kind() == std::io::ErrorKind::NotFound {
            ErrorCode::SceneFileMissing
        } else {
            code
        };
        ShowcaseError::new(code, path, e.to_string())
    })?;
    let mut decoder = png::Decoder::new(std::io::BufReader::new(file));
    decoder.set_transformations(png::Transformations::normalize_to_color8());
    let mut reader = decoder.read_info().map_err(|e| bad(e.to_string()))?;
    let (w, h) = (reader.info().width, reader.info().height);
    if w == 0 || h == 0 || w > max_side || h > max_side {
        return Err(bad(format!(
            "{w}x{h} texels (each side must be within 1..={max_side})"
        )));
    }
    let size = reader
        .output_buffer_size()
        .ok_or_else(|| bad("image too large".into()))?;
    let mut buf = vec![0u8; size];
    let frame = reader.next_frame(&mut buf).map_err(|e| bad(e.to_string()))?;
    let bytes = &buf[..frame.buffer_size()];
    let data: Vec<u8> = match frame.color_type {
        png::ColorType::Rgba => bytes.to_vec(),
        png::ColorType::Rgb => bytes
            .as_chunks::<3>()
            .0
            .iter()
            .flat_map(|p| [p[0], p[1], p[2], 255])
            .collect(),
        png::ColorType::Grayscale => bytes.iter().flat_map(|&v| [v, v, v, 255]).collect(),
        png::ColorType::GrayscaleAlpha => bytes
            .as_chunks::<2>()
            .0
            .iter()
            .flat_map(|p| [p[0], p[0], p[0], p[1]])
            .collect(),
        png::ColorType::Indexed => return Err(bad("indexed PNGs are not supported".into())),
    };
    Ok(regia_terrain::Rgba8Image {
        width: w,
        height: h,
        data,
    })
}

/// Decodes a layer texture ([`MAX_LAYER_TEXTURE_SIDE`]).
fn decode_rgba(path: &Path) -> Result<regia_terrain::Rgba8Image, ShowcaseError> {
    decode_rgba_as(path, MAX_LAYER_TEXTURE_SIDE, ErrorCode::MaterialsMalformed)
}

/// Decodes `paths` on up to eight threads, results in order. A scene's layer set is up to 32 PNGs of 4096²; one
/// at a time that is most of the load.
fn decode_all(paths: &[PathBuf]) -> Vec<Result<regia_terrain::Rgba8Image, ShowcaseError>> {
    let _span = tracing::info_span!("showcase_decode_layers", count = paths.len()).entered();
    let threads = std::thread::available_parallelism()
        .map_or(4, |n| n.get())
        .clamp(1, 8);
    let mut out: Vec<Option<Result<regia_terrain::Rgba8Image, ShowcaseError>>> = Vec::new();
    out.resize_with(paths.len(), || None);
    let per = paths.len().div_ceil(threads).max(1);
    std::thread::scope(|scope| {
        for (chunk_paths, chunk_out) in paths.chunks(per).zip(out.chunks_mut(per)) {
            scope.spawn(move || {
                for (path, slot) in chunk_paths.iter().zip(chunk_out.iter_mut()) {
                    *slot = Some(decode_rgba(path));
                }
            });
        }
    });
    out.into_iter()
        .zip(paths)
        .map(|(result, path)| {
            result.unwrap_or_else(|| {
                Err(ShowcaseError::new(
                    ErrorCode::MaterialsMalformed,
                    path,
                    "the decode thread did not finish",
                ))
            })
        })
        .collect()
}

fn layer_style(name: &str) -> Option<LayerStyle> {
    match name {
        "Grass" => Some(LayerStyle::Grass),
        "Rock" => Some(LayerStyle::Rock),
        "Dirt" => Some(LayerStyle::Dirt),
        "Snow" => Some(LayerStyle::Snow),
        "Sand" => Some(LayerStyle::Sand),
        "Ice" => Some(LayerStyle::Ice),
        _ => None,
    }
}

fn build_material(
    dir: &Path,
    manifest_path: &Path,
    set: &MaterialSet,
    layer_count: usize,
) -> Result<TerrainMaterial, ShowcaseError> {
    let bad = |message: String| ShowcaseError::new(ErrorCode::MaterialsMalformed, manifest_path, message);
    if set.layers.len() != layer_count {
        return Err(bad(format!(
            "material has {} layers but the layer stack has {layer_count}",
            set.layers.len()
        )));
    }
    if !set.macro_world_size.is_finite() || set.macro_world_size < 0.0 || !set.anti_tiling_cell.is_finite() {
        return Err(bad(
            "macro_world_size and anti_tiling_cell must be finite and >= 0".into(),
        ));
    }
    set.relief.check().map_err(bad)?;
    // Every PNG the layers name, decoded together.
    let mut paths: Vec<PathBuf> = Vec::new();
    for layer in &set.layers {
        if let LayerMaterial::Files {
            albedo,
            normal,
            height,
            orm,
        } = layer
        {
            for rel in std::iter::once(albedo).chain(normal).chain(height).chain(orm) {
                paths.push(inside(dir, rel, manifest_path)?);
            }
        }
    }
    let mut decoded = decode_all(&paths).into_iter();
    let mut next = || -> Result<regia_terrain::Rgba8Image, ShowcaseError> {
        decoded
            .next()
            .unwrap_or_else(|| Err(bad("a layer texture was not decoded".into())))
    };
    let mut layers = Vec::with_capacity(set.layers.len());
    for (index, layer) in set.layers.iter().enumerate() {
        match layer {
            LayerMaterial::Style { style, size, seed } => {
                let style = layer_style(style).ok_or_else(|| {
                    bad(format!(
                        "layer {index}: unknown style '{style}' (Grass, Rock, Dirt, Snow, Sand, Ice)"
                    ))
                })?;
                if !size.is_power_of_two() || !(64..=2048).contains(size) {
                    return Err(bad(format!(
                        "layer {index}: size {size} must be a power of two in 64..=2048"
                    )));
                }
                layers.push(Some(style.bake(*size, *seed)));
            }
            LayerMaterial::Files {
                normal, height, orm, ..
            } => {
                let albedo = next()?;
                let size = albedo.width;
                let normal = match normal {
                    Some(_) => next()?,
                    None => regia_terrain::Rgba8Image::neutral_normal(size),
                };
                let height = match height {
                    Some(_) => next()?,
                    None => regia_terrain::Rgba8Image::neutral_height(size),
                };
                let (orm, use_orm) = match orm {
                    Some(_) => (next()?, true),
                    None => (
                        regia_terrain::Rgba8Image::solid(size, size, [255, 200, 0, 255]),
                        false,
                    ),
                };
                layers.push(Some(LayerTextures {
                    albedo,
                    normal,
                    height,
                    orm,
                    use_orm,
                }));
            }
        }
    }
    let material = TerrainMaterial {
        layers,
        macro_set: None,
        params: MaterialParams {
            macro_world_size: set.macro_world_size,
            anti_tiling_cell: set.anti_tiling_cell,
            ..MaterialParams::default()
        },
    };
    material.validate().map_err(|e| bad(e.to_string()))?;
    Ok(material)
}

fn standin_asset(index: usize, stand_in: StandIn) -> ScatterMeshAsset {
    let seed = 0x0053_4857_0000_0000 ^ (index as u64 + 1).wrapping_mul(0x9e37_79b9);
    let c = |v: (f32, f32, f32)| [v.0, v.1, v.2];
    match stand_in {
        StandIn::Rock { color } => procedural_rock(seed, RockStyle::angular(c(color))),
        StandIn::Boulder { color } => procedural_rock(seed, RockStyle::rounded(c(color))),
        StandIn::Cone { color } => {
            let mesh = Cone {
                radius: 0.25,
                height: 1.0,
                resolution: 12,
                anchor: ConeAnchor::Base,
            }
            .build();
            let vertices: Vec<LabVertex> = mesh.vertices.clone();
            let mut material = LabMaterial::EMPTY;
            material.base_color = [color.0, color.1, color.2, 1.0];
            material.roughness = 0.85;
            ScatterMeshAsset {
                lods: vec![ScatterMeshLod {
                    vertices,
                    indices: mesh.indices.clone(),
                    screen_size: 0.0,
                }],
                material,
                parts: Vec::new(),
                shadow_lod: 0,
            }
        }
    }
}

/// Whether a scatter mesh name is a glTF file path.
fn is_gltf_name(name: &str) -> bool {
    let lower = name.to_ascii_lowercase();
    lower.ends_with(".gltf") || lower.ends_with(".glb")
}

/// Builds the meshes of `set`'s mesh names. A name bound in `bindings` gets that stand-in. Otherwise a `.gltf` or
/// `.glb` name is loaded from beside the `.scatter.ron` (`scatter_dir`), else from the scene directory; any other
/// name gets a grey stand-in rock.
fn build_library(
    dir: &Path,
    scatter_path: &Path,
    set: &ScatterSet,
    bindings: &[StandInBinding],
) -> Result<(ScatterLibrary, HashMap<String, Arc<ScatterModel>>), ShowcaseError> {
    let _span = tracing::info_span!("showcase_scatter_meshes").entered();
    let scatter_dir = scatter_path.parent().unwrap_or(dir);
    let mut library = ScatterLibrary::new();
    let mut models = HashMap::new();
    for (index, path) in set.mesh_paths().into_iter().enumerate() {
        let binding = bindings.iter().find(|b| b.mesh == path);
        if binding.is_none() && is_gltf_name(path) {
            let candidates = [
                inside(scatter_dir, path, scatter_path)?,
                inside(dir, path, scatter_path)?,
            ];
            let Some(file) = candidates.iter().find(|p| p.is_file()) else {
                return Err(ShowcaseError::new(
                    ErrorCode::ScatterMeshMissing,
                    &candidates[0],
                    format!(
                        "scatter mesh '{path}' is neither beside the .scatter.ron nor in the scene directory ({})",
                        candidates[1].display()
                    ),
                ));
            };
            let model = crate::gltf::load_model(file, SCATTER_TEXTURE_MAX)
                .map_err(|e| ShowcaseError::new(ErrorCode::ScatterMeshMalformed, file, e.0))?;
            // The streamed field draws the asset; the entity path (`--entity-scatter`) the model.
            if let Some(asset) = scatter_asset(&model) {
                library.insert(path.to_string(), asset);
            }
            let model = ScatterModel::from_gltf(model);
            if model.parts.is_empty() {
                return Err(ShowcaseError::new(
                    ErrorCode::ScatterMeshMalformed,
                    file,
                    "the glTF has no triangles",
                ));
            }
            models.insert(path.to_string(), Arc::new(model));
            continue;
        }
        let stand_in = binding.map_or(
            StandIn::Rock {
                color: (0.2, 0.19, 0.18),
            },
            |b| b.stand_in,
        );
        library.insert(path.to_string(), standin_asset(index, stand_in));
    }
    Ok((library, models))
}

/// Loads one glTF the track names, relative to the scene directory.
fn load_track_mesh(dir: &Path, rel: &str, track_path: &Path) -> Result<Arc<ScatterModel>, ShowcaseError> {
    let file = inside(dir, rel, track_path)?;
    if !file.is_file() {
        return Err(ShowcaseError::new(
            ErrorCode::TrackMeshMissing,
            &file,
            format!("the track's mesh '{rel}' is not a file in the scene directory"),
        ));
    }
    let model = crate::gltf::load_model(&file, SCATTER_TEXTURE_MAX)
        .map_err(|e| ShowcaseError::new(ErrorCode::TrackMeshMalformed, &file, e.0))?;
    let model = ScatterModel::from_gltf(model);
    if model.parts.is_empty() {
        return Err(ShowcaseError::new(
            ErrorCode::TrackMeshMalformed,
            &file,
            "the glTF has no triangles",
        ));
    }
    Ok(Arc::new(model))
}

fn load_vfx(
    dir: Option<&Path>,
    spawns: &SpawnFile,
    spawns_path: &Path,
) -> Result<(Vec<VfxSystemDef>, Option<PathBuf>), ShowcaseError> {
    let mut defs: Vec<VfxSystemDef> = Vec::new();
    let mut decals = DecalLibrary::builtin();
    let mut decal_dir = None;
    if let Some(dir) = dir {
        if !dir.is_dir() {
            return Err(ShowcaseError::new(
                ErrorCode::SceneFileMissing,
                dir,
                "the manifest names this vfx directory but it does not exist",
            ));
        }
        if let Ok(library) = regia_vfx::scene::VfxLibrary::load_dir(dir) {
            defs.extend(library.defs().iter().cloned());
        }
        decals
            .load_dir(dir)
            .map_err(|e| ShowcaseError::new(ErrorCode::SpawnsMalformed, dir, e.to_string()))?;
        decal_dir = Some(dir.to_path_buf());
    }
    let mut known: BTreeSet<String> = defs.iter().map(|d| d.name.clone()).collect();
    for def in regia_vfx::showcase_effects() {
        if known.insert(def.name.clone()) {
            defs.push(def);
        }
    }
    let medium = regia_vfx::VfxMedium::earth();
    let wanted: BTreeSet<&str> = spawns.effects.iter().map(|e| e.effect.as_str()).collect();
    for name in wanted {
        if known.contains(name) {
            continue;
        }
        match regia_vfx::atmos_presets::builtin_in(name, &medium) {
            Some(def) => {
                known.insert(def.name.clone());
                defs.push(def);
            }
            None => {
                return Err(ShowcaseError::new(
                    ErrorCode::SpawnUnknownEffect,
                    spawns_path,
                    format!("effect '{name}' is not built in and not in the scene's vfx directory"),
                ));
            }
        }
    }
    for decal in &spawns.decals {
        if let Some(prefab) = &decal.prefab
            && decals.get(prefab).is_none()
        {
            return Err(ShowcaseError::new(
                ErrorCode::SpawnUnknownDecal,
                spawns_path,
                format!(
                    "decal prefab '{prefab}' is unknown (known: {})",
                    decals.names().join(", ")
                ),
            ));
        }
    }
    Ok((defs, decal_dir))
}

/// Loads both splat packs of `spec` and checks they agree in size.
fn load_splat(
    dir: &Path,
    manifest_path: &Path,
    spec: &SplatSpec,
) -> Result<[regia_terrain::Rgba8Image; 2], ShowcaseError> {
    let _span = tracing::info_span!("showcase_load_splat").entered();
    let path0 = inside(dir, &spec.pack0, manifest_path)?;
    let path1 = inside(dir, &spec.pack1, manifest_path)?;
    require_file(&path0)?;
    require_file(&path1)?;
    let pack0 = decode_rgba_as(&path0, MAX_SPLAT_SIDE, ErrorCode::SplatMalformed)?;
    let pack1 = decode_rgba_as(&path1, MAX_SPLAT_SIDE, ErrorCode::SplatMalformed)?;
    if (pack0.width, pack0.height) != (pack1.width, pack1.height) {
        return Err(ShowcaseError::new(
            ErrorCode::SplatMalformed,
            &path1,
            format!(
                "{}x{} but pack0 is {}x{}; both packs must be the same size",
                pack1.width, pack1.height, pack0.width, pack0.height
            ),
        ));
    }
    Ok([pack0, pack1])
}

/// The manifest a cook-convention scene directory implies (`docs/formats/terrain.md` § 9), for a directory
/// without `scene.ron`:
///
/// ```text
/// <scene>/terrain/terrain.layers.ron   layers (v3); their *_texture paths are relative to terrain/
/// <scene>/terrain/heightfield.png      16-bit grayscale, any size up to 8192 a side
/// <scene>/terrain/heightfield.json     size_m -> world_width, min_m -> height_offset, max_m - min_m -> height_scale
/// <scene>/terrain/macro/pack0.png      optional splat packs (both or neither)
/// <scene>/terrain/macro/pack1.png
/// <scene>/scatter/*.scatter.ron        optional; the first by name
/// <scene>/sky.ron                      required
/// <scene>/track.ron, spawns.ron, vfx/  optional
/// ```
///
/// The map is centred on the world origin (`heightfield.json`'s `origin` is not read). Layers whose textures are
/// all named become the photoreal material (all layers or none); `macro_albedo.png` and `macro/{normal,ao}.png`
/// are not used yet.
///
/// # Errors
/// [`ErrorCode::SceneFileMissing`] for a missing required file, [`ErrorCode::HeightfieldMalformed`] for a bad
/// `heightfield.json`, [`ErrorCode::LayersMalformed`] and [`ErrorCode::MaterialsMalformed`] for the layers.
pub fn cook_manifest(dir: &Path) -> Result<Manifest, ShowcaseError> {
    let layers_path = dir.join(COOK_LAYERS);
    let layers = TerrainLayers::from_ron(&read_text(&layers_path)?)
        .map_err(|e| ShowcaseError::new(ErrorCode::LayersMalformed, &layers_path, e.to_string()))?;
    let json_path = dir.join("terrain/heightfield.json");
    require_file(&json_path)?;
    let extents = HeightfieldExtents::from_json(&read_text(&json_path)?)
        .map_err(|e| ShowcaseError::new(ErrorCode::HeightfieldMalformed, &json_path, e))?;
    let rel = |p: &str| format!("terrain/{p}");
    let named: Vec<bool> = layers.layers.iter().map(|l| l.albedo_texture.is_some()).collect();
    let material = if named.iter().all(|&n| n) && !named.is_empty() {
        Some(MaterialSet {
            layers: layers
                .layers
                .iter()
                .map(|l| LayerMaterial::Files {
                    albedo: rel(l.albedo_texture.as_deref().unwrap_or_default()),
                    normal: l.normal_texture.as_deref().map(rel),
                    height: l.height_texture.as_deref().map(rel),
                    orm: l.orm_texture.as_deref().map(rel),
                })
                .collect(),
            macro_world_size: 0.0,
            anti_tiling_cell: default_anti_tiling(),
            relief: ReliefSpec::photo(),
        })
    } else if named.iter().any(|&n| n) {
        return Err(ShowcaseError::new(
            ErrorCode::MaterialsMalformed,
            &layers_path,
            "either every layer names an albedo_texture or none does",
        ));
    } else {
        None
    };
    let pack = |name: &str| dir.join("terrain/macro").join(name).is_file();
    let splat = match (pack("pack0.png"), pack("pack1.png")) {
        (true, true) => Some(SplatSpec {
            pack0: "terrain/macro/pack0.png".into(),
            pack1: "terrain/macro/pack1.png".into(),
        }),
        (false, false) => None,
        (has0, _) => {
            let missing = if has0 { "pack1.png" } else { "pack0.png" };
            return Err(ShowcaseError::new(
                ErrorCode::SceneFileMissing,
                &dir.join("terrain/macro").join(missing),
                "the cook layout has one splat pack; it needs both or neither",
            ));
        }
    };
    let scatter = std::fs::read_dir(dir.join("scatter")).ok().and_then(|entries| {
        let mut names: Vec<String> = entries
            .filter_map(Result::ok)
            .filter_map(|e| e.file_name().into_string().ok())
            .filter(|n| n.ends_with(".scatter.ron"))
            .collect();
        names.sort();
        names.first().map(|n| format!("scatter/{n}"))
    });
    let optional = |name: &str| dir.join(name).is_file().then(|| name.to_string());
    Ok(Manifest {
        version: SCENE_VERSION,
        name: dir
            .file_name()
            .map(|n| n.to_string_lossy().into_owned())
            .unwrap_or_default(),
        heightfield: "terrain/heightfield.png".into(),
        world_width: extents.size_m,
        height_scale: extents.max_m - extents.min_m,
        height_offset: extents.min_m,
        layers: COOK_LAYERS.into(),
        material,
        splat,
        scatter,
        stand_ins: Vec::new(),
        max_scatter_instances: DEFAULT_MAX_SCATTER_INSTANCES,
        sky: "sky.ron".into(),
        track: optional("track.ron"),
        spawns: optional("spawns.ron"),
        vfx_dir: dir.join("vfx").is_dir().then(|| "vfx".to_string()),
        camera: CameraSpec::default(),
        lead_in_frames: 0,
        heightfield_size: extents.size,
    })
}

/// Loads and validates the scene in `dir`.
///
/// # Errors
/// A [`ShowcaseError`] whose [`ErrorCode`] says what is wrong; nothing panics.
pub fn load_scene(dir: &Path) -> Result<SceneData, ShowcaseError> {
    load_scene_with(dir, &crate::features::FeatureOptions::default())
}

/// [`load_scene`] with options that switch features on besides the scene's own files.
///
/// # Errors
/// A [`ShowcaseError`] whose [`ErrorCode`] says what is wrong; nothing panics.
pub fn load_scene_with(
    dir: &Path,
    feature_options: &crate::features::FeatureOptions,
) -> Result<SceneData, ShowcaseError> {
    if !dir.is_dir() {
        return Err(ShowcaseError::new(
            ErrorCode::SceneDirMissing,
            dir,
            "the scene path does not exist or is not a directory",
        ));
    }
    let _span = tracing::info_span!("showcase_load_scene").entered();
    let mut manifest_path = dir.join(MANIFEST_NAME);
    let (manifest, layout) = if manifest_path.is_file() {
        let text = read_text(&manifest_path)?;
        let manifest: Manifest = ron::from_str(&text).map_err(|e| {
            ShowcaseError::new(ErrorCode::SceneManifestMalformed, &manifest_path, e.to_string())
        })?;
        (manifest, SceneLayout::Manifest)
    } else if dir.join(COOK_LAYERS).is_file() {
        manifest_path = dir.join(COOK_LAYERS);
        (cook_manifest(dir)?, SceneLayout::Cook)
    } else {
        return Err(ShowcaseError::new(
            ErrorCode::SceneManifestMissing,
            &manifest_path,
            format!("the scene directory has neither a scene.ron nor a {COOK_LAYERS}"),
        ));
    };
    let bad_manifest =
        |message: String| ShowcaseError::new(ErrorCode::SceneManifestMalformed, &manifest_path, message);
    if manifest.version != SCENE_VERSION {
        return Err(bad_manifest(format!(
            "version {} (this build reads {SCENE_VERSION})",
            manifest.version
        )));
    }
    let numbers = [
        manifest.world_width,
        manifest.height_scale,
        manifest.height_offset,
    ];
    if numbers.iter().any(|v| !v.is_finite()) || manifest.world_width <= 0.0 || manifest.height_scale <= 0.0 {
        return Err(bad_manifest(
            "world_width and height_scale must be finite and > 0, height_offset finite".into(),
        ));
    }
    let cam = manifest.camera;
    let cam_numbers = [
        cam.position.0,
        cam.position.1,
        cam.position.2,
        cam.target.0,
        cam.target.1,
        cam.target.2,
        cam.fov_deg,
        cam.near,
        cam.far,
    ];
    if cam_numbers.iter().any(|v| !v.is_finite())
        || !(1.0..179.0).contains(&cam.fov_deg)
        || cam.near <= 0.0
        || cam.far <= cam.near
    {
        return Err(bad_manifest(
            "camera: fov_deg within 1..179, near > 0, far > near, all finite".into(),
        ));
    }
    if manifest.max_scatter_instances == 0 {
        return Err(bad_manifest("max_scatter_instances must be at least 1".into()));
    }

    // Heightfield.
    let hf_path = inside(dir, &manifest.heightfield, &manifest_path)?;
    require_file(&hf_path)?;
    let (w, h, samples) = {
        let _span = tracing::info_span!("showcase_decode_heightfield").entered();
        decode_gray(&hf_path, true, ErrorCode::HeightfieldMalformed)?
    };
    if let Some(side) = manifest.heightfield_size
        && (w, h) != (side, side)
    {
        return Err(ShowcaseError::new(
            ErrorCode::HeightfieldMalformed,
            &hf_path,
            format!("{w}x{h} samples but the scene says {side}x{side}"),
        ));
    }
    let heightfield = Heightfield {
        width: w,
        height: h,
        samples,
    };
    let map = TerrainMap::new(
        &heightfield,
        manifest.world_width,
        manifest.height_scale,
        manifest.height_offset,
    )
    .map_err(|e| ShowcaseError::new(ErrorCode::HeightfieldMalformed, &hf_path, e.to_string()))?;

    // Layers and photoreal material.
    let layers_path = inside(dir, &manifest.layers, &manifest_path)?;
    require_file(&layers_path)?;
    let layers = TerrainLayers::from_ron(&read_text(&layers_path)?)
        .map_err(|e| ShowcaseError::new(ErrorCode::LayersMalformed, &layers_path, e.to_string()))?;
    let material = match &manifest.material {
        Some(set) => Some(build_material(dir, &manifest_path, set, layers.layers.len())?),
        None => None,
    };
    let splat = match &manifest.splat {
        Some(spec) => Some(load_splat(dir, &manifest_path, spec)?),
        None => None,
    };

    // Scatter.
    let mut density_maps = DensityMaps::new();
    let (scatter, library, models) = match &manifest.scatter {
        Some(rel) => {
            let path = inside(dir, rel, &manifest_path)?;
            require_file(&path)?;
            let set = ScatterSet::from_ron(&read_text(&path)?, Some(&layers))
                .map_err(|e| ShowcaseError::new(ErrorCode::ScatterMalformed, &path, e.to_string()))?;
            for class in &set.classes {
                if let Some(map_rel) = &class.density_map
                    && !density_maps.contains_key(map_rel)
                {
                    // Beside the .scatter.ron first (the cook layout's scatter/maps/), then the scene directory.
                    let beside = inside(path.parent().unwrap_or(dir), map_rel, &path)?;
                    let map_path = if beside.is_file() {
                        beside
                    } else {
                        inside(dir, map_rel, &path)?
                    };
                    require_file(&map_path)?;
                    let (dw, dh, dsamples) = decode_gray(&map_path, false, ErrorCode::ScatterMalformed)?;
                    let density = DensityMap::from_heightfield(&Heightfield {
                        width: dw,
                        height: dh,
                        samples: dsamples,
                    })
                    .map_err(|e| ShowcaseError::new(ErrorCode::ScatterMalformed, &map_path, e.to_string()))?;
                    density_maps.insert(map_rel.clone(), density);
                }
            }
            let (library, models) = build_library(dir, &path, &set, &manifest.stand_ins)?;
            (Some(set), library, models)
        }
        None => (None, ScatterLibrary::new(), HashMap::new()),
    };

    // Sky.
    let sky_path = inside(dir, &manifest.sky, &manifest_path)?;
    require_file(&sky_path)?;
    let sky = SkyFile::from_ron(&read_text(&sky_path)?, &sky_path)?;

    // Track and spawns.
    let track = match &manifest.track {
        Some(rel) => {
            let path = inside(dir, rel, &manifest_path)?;
            require_file(&path)?;
            Some(Track::from_ron(&read_text(&path)?, &path)?)
        }
        None => None,
    };
    let mut track_meshes = TrackMeshes::default();
    if let (Some(track), Some(rel)) = (&track, &manifest.track) {
        let track_path = inside(dir, rel, &manifest_path)?;
        if let Some(mesh) = &track.mesh {
            track_meshes.base = Some(load_track_mesh(dir, mesh, &track_path)?);
        }
        if let Some(mesh) = &track.swap_mesh {
            track_meshes.swap = Some(load_track_mesh(dir, mesh, &track_path)?);
        }
    }
    let (spawns, spawns_path) = match &manifest.spawns {
        Some(rel) => {
            let path = inside(dir, rel, &manifest_path)?;
            require_file(&path)?;
            (
                SpawnFile::from_ron(&read_text(&path)?, &path, track.is_some())?,
                path,
            )
        }
        None => (
            SpawnFile {
                version: crate::spawns::SPAWNS_VERSION,
                ..SpawnFile::default()
            },
            manifest_path.clone(),
        ),
    };
    let vfx_path = match &manifest.vfx_dir {
        Some(rel) => Some(inside(dir, rel, &manifest_path)?),
        None => None,
    };
    let (vfx_defs, decal_dir) = load_vfx(vfx_path.as_deref(), &spawns, &spawns_path)?;

    let features = crate::features::load_features(
        &crate::features::FeatureInputs {
            dir,
            map: &map,
            layers: &layers,
            splat: splat.as_ref(),
            sky: &sky,
        },
        feature_options,
    )?;

    let relief = manifest
        .material
        .as_ref()
        .map_or_else(|| ReliefSpec::photo().to_engine(), |set| set.relief.to_engine());
    Ok(SceneData {
        dir: dir.to_path_buf(),
        manifest,
        map,
        layers,
        material,
        relief,
        splat,
        layout,
        scatter,
        density_maps,
        library,
        models,
        sky,
        track,
        track_meshes,
        spawns,
        vfx_defs,
        decal_dir,
        features,
    })
}
