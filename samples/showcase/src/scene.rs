/// The heightfield's extents beside it in the cook-convention layout (`terrain/heightfield.json`).
#[derive(Clone, Copy, Debug, PartialEq, Deserialize)]
pub struct HeightfieldExtents {
    /// Width (and depth) from the first to the last sample, metres: the manifest's `world_width`.
    pub size_m: f32,
    /// Height of sample value 0, metres: the manifest's `height_offset`.
    pub min_m: f32,
    /// Height of sample value 65535, metres: `height_offset + height_scale`.
    pub max_m: f32,
    /// Samples a side, when the file says (checked against the PNG).
    #[serde(default)]
    pub size: Option<u32>,
}

impl HeightfieldExtents {
    /// Parses `heightfield.json` (unknown fields are ignored) and checks the values.
    ///
    /// # Errors
    /// A message naming the bad field.
    pub fn from_json(text: &str) -> Result<Self, String> {
        let extents: HeightfieldExtents = serde_json::from_str(text).map_err(|e| e.to_string())?;
        if !extents.size_m.is_finite() || extents.size_m <= 0.0 {
            return Err(format!("size_m is {}; it must be finite and > 0", extents.size_m));
        }
        if !extents.min_m.is_finite() || !extents.max_m.is_finite() || extents.max_m <= extents.min_m {
            return Err(format!(
                "min_m {} and max_m {} must be finite with max_m > min_m",
                extents.min_m, extents.max_m
            ));
        }
        Ok(extents)
    }
}

/// The manifest (`scene.ron`).
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Manifest {
    /// Format version ([`SCENE_VERSION`]).
    pub version: u32,
    /// A label for reports.
    #[serde(default)]
    pub name: String,
    /// The 16-bit grayscale PNG heightfield.
    pub heightfield: String,
    /// World width (and depth) the heightfield covers, metres.
    pub world_width: f32,
    /// Height of sample value 65535 above `height_offset`, metres.
    pub height_scale: f32,
    /// Height of sample value 0, metres.
    #[serde(default)]
    pub height_offset: f32,
    /// Samples a side the heightfield must have (`heightfield.json`'s `size`). Absent: any size up to
    /// [`MAX_HEIGHTFIELD_SIDE`].
    #[serde(default)]
    pub heightfield_size: Option<u32>,
    /// The `.terrain.layers.ron`.
    pub layers: String,
    /// Photoreal layer textures. Absent: the layers' flat colours.
    #[serde(default)]
    pub material: Option<MaterialSet>,
    /// Splat weight packs over the whole map (the cook convention's `macro/pack0.png` and `macro/pack1.png`).
    /// Absent: the layers' slope and altitude bands alone.
    #[serde(default)]
    pub splat: Option<SplatSpec>,
    /// The `.scatter.ron`, if any.
    #[serde(default)]
    pub scatter: Option<String>,
    /// Stand-in meshes for the scatter's mesh names.
    #[serde(default)]
    pub stand_ins: Vec<StandInBinding>,
    /// Cap on scatter instances turned into entities (extra instances are thinned evenly).
    #[serde(default = "default_max_scatter")]
    pub max_scatter_instances: u32,
    /// The sky and weather file.
    pub sky: String,
    /// The scripted track, if any.
    #[serde(default)]
    pub track: Option<String>,
    /// The spawn schedule, if any.
    #[serde(default)]
    pub spawns: Option<String>,
    /// A directory of `*.vfx.ron` and `*.decal.ron` the spawns may name.
    #[serde(default)]
    pub vfx_dir: Option<String>,
    /// The starting camera.
    #[serde(default)]
    pub camera: CameraSpec,
    /// The scripted clock starts this many frames before frame 0, so a `render.out_start` with
    /// `warmup_frames` equal to this value starts its first delivered frame on track frame 0.
    #[serde(default)]
    pub lead_in_frames: u32,
}

fn default_max_scatter() -> u32 {
    DEFAULT_MAX_SCATTER_INSTANCES
}

