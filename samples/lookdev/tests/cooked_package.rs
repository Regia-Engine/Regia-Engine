//! `regia package --platform linux` with the cooked outpost, and its startup from the pak with
//! a cold page cache (lane cooked-runtime).
//!
//! A throwaway workspace member (`samples/cooked-outpost-<pid>`, picked up by the `samples/*`
//! glob) holds the fixture project of `tests/cooked_runtime.rs` plus a headless game binary. The
//! real CLI packages it (auto-cook, tarball); the extracted game evicts its paks and itself from
//! the page cache (`posix_fadvise(DONTNEED)`), mounts `content/*.fpak` next to its executable,
//! loads the outpost from the pak, creates a device and renders one frame, and prints each step's
//! time. Run twice: cold, then warm.
//!
//! Ignored by default (engine build + package, minutes); run with
//! `cargo test -p lookdev --test cooked_package -- --ignored --nocapture`.
//! The `regia` CLI is built on demand into this test's target dir when it is not already there.

use std::path::{Path, PathBuf};
use std::process::Command;

use lookdev::cooked_runtime::{self as cr, fixture};

/// The game: mount, load, device, first frame; one `startup:` line.
const MAIN_RS: &str = r#"//! Generated by lookdev's cooked_package test: a shipped game's startup from its pak.

use std::path::{Path, PathBuf};
use std::process::ExitCode;
use std::time::Instant;

use lookdev::cooked_runtime as cr;

/// Drops `path` from the page cache (clean pages only; the next read comes from the disk).
fn evict(path: &Path) {
    use std::os::fd::AsRawFd;
    if let Ok(file) = std::fs::File::open(path) {
        // SAFETY: a valid open descriptor; advice only, no memory is touched.
        unsafe {
            libc::posix_fadvise(file.as_raw_fd(), 0, 0, libc::POSIX_FADV_DONTNEED);
        }
    }
}

fn main() -> ExitCode {
    let started = Instant::now();
    let exe = std::env::current_exe().unwrap_or_default();
    let dir = exe.parent().map(Path::to_path_buf).unwrap_or_default();
    let content = dir.join("content");
    let paks: Vec<PathBuf> = cr::pak_files(&content).unwrap_or_default();
    if std::env::args().any(|a| a == "--cold") {
        for p in paks.iter().chain([&exe]) {
            evict(p);
        }
    }
    let pak_bytes: u64 = paks.iter().map(|p| std::fs::metadata(p).map_or(0, |m| m.len())).sum();
    let t0 = Instant::now();
    let mut server = match cr::mount_paks(&content, &dir.join("no-dev-cache"), "linux") {
        Ok(s) => s,
        Err(e) => {
            eprintln!("mount failed: {e}");
            return ExitCode::FAILURE;
        }
    };
    let mount = t0.elapsed();
    let t1 = Instant::now();
    let Some(id) = server.id_for_path("assets/hero/outpost.gltf") else {
        eprintln!("the pak does not name the outpost");
        return ExitCode::FAILURE;
    };
    let draws = match regia_render::cooked_model::load_cooked_model(&mut server, id) {
        Ok(d) => d,
        Err(e) => {
            eprintln!("model load failed: {e}");
            return ExitCode::FAILURE;
        }
    };
    let load = t1.elapsed();
    let from_pak = matches!(
        server.source_of(regia_render::cooked_model::model_id(id)),
        regia_asset::AssetSource::Pak(_)
    );
    let t2 = Instant::now();
    let device = match regia_render::RenderDevice::headless() {
        Ok(d) => d,
        Err(e) => {
            eprintln!("device failed: {e}");
            return ExitCode::FAILURE;
        }
    };
    let device_time = t2.elapsed();
    let (lo, hi) = cr::bounds(&draws.meshes);
    let view = cr::View::of_bounds(lo, hi, regia_core::glam::Vec3::new(0.6, 0.35, -0.75), 0.9);
    let t3 = Instant::now();
    let frame = match cr::render_model(&device, &draws.meshes, draws.materials, view, 640, 360) {
        Ok(f) => f,
        Err(e) => {
            eprintln!("frame failed: {e}");
            return ExitCode::FAILURE;
        }
    };
    let first_frame = t3.elapsed();
    if let Some(out) = std::env::args().skip_while(|a| a != "--png").nth(1) {
        let _ = cr::save(&frame, Path::new(&out));
    }
    let lit = frame.pixels.chunks(4).filter(|p| p[0] > 40 || p[1] > 40).count();
    println!(
        "startup: from_pak={from_pak} paks={} KiB mount={:.1}ms model_load={:.1}ms device={:.1}ms \
         first_frame={:.1}ms total={:.1}ms lit_pixels={lit} texture_kib={}",
        pak_bytes / 1024,
        mount.as_secs_f64() * 1e3,
        load.as_secs_f64() * 1e3,
        device_time.as_secs_f64() * 1e3,
        first_frame.as_secs_f64() * 1e3,
        started.elapsed().as_secs_f64() * 1e3,
        draws.texture_bytes / 1024,
    );
    if from_pak { ExitCode::SUCCESS } else { ExitCode::FAILURE }
}
"#;

struct Cleanup(PathBuf);
impl Drop for Cleanup {
    fn drop(&mut self) {
        let _ = std::fs::remove_dir_all(&self.0);
    }
}

fn repo_root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../..")
        .canonicalize()
        .expect("repo root")
}

fn run_game(binary: &Path, dir: &Path, args: &[&str]) -> String {
    let out = Command::new(binary)
        .args(args)
        .current_dir(dir)
        .output()
        .expect("run the packaged game");
    let log = format!(
        "{}{}",
        String::from_utf8_lossy(&out.stdout),
        String::from_utf8_lossy(&out.stderr)
    );
    assert!(
        out.status.success(),
        "packaged game failed ({:?}):\n{log}",
        out.status.code()
    );
    log.lines()
        .find(|l| l.starts_with("startup:"))
        .unwrap_or_else(|| panic!("no startup line:\n{log}"))
        .to_string()
}

#[test]
#[ignore = "engine build + regia package + packaged run; invoke with -- --ignored"]
fn packaged_outpost_starts_from_its_pak_cold() {
    let cli = cr::regia_cli();
    assert!(cli.is_file(), "build the CLI first (missing {})", cli.display());
    let root = repo_root();
    let name = format!("cooked-outpost-{}", std::process::id());
    let project = root.join("samples").join(&name);
    let _project = Cleanup(project.clone());
    let out = std::env::temp_dir().join(format!("regia-cooked-package-{}", std::process::id()));
    let _out = Cleanup(out.clone());
    fixture::write_project(
        &project,
        include_str!("../../../crates/regia_templates/templates/blank/assets/levels/main.level.ron"),
    )
    .expect("fixture");
    std::fs::create_dir_all(project.join("src")).expect("src");
    std::fs::write(project.join("src/main.rs"), MAIN_RS).expect("main.rs");
    std::fs::write(
        project.join("Cargo.toml"),
        format!(
            "[package]\nname = \"{name}\"\nversion = \"0.1.0\"\nedition = \"2024\"\npublish = false\n\n\
             [dependencies]\nlookdev = {{ path = \"../lookdev\" }}\n\
             regia_asset = {{ path = \"../../crates/regia_asset\" }}\n\
             regia_core = {{ path = \"../../crates/regia_core\" }}\n\
             regia_render = {{ path = \"../../crates/regia_render\" }}\nlibc = \"0.2\"\n"
        ),
    )
    .expect("Cargo.toml");

    let started = std::time::Instant::now();
    let package = Command::new(&cli)
        .args([
            "package",
            "--platform",
            "linux",
            "--format",
            "tar",
            "--profile",
            "dev",
            "--project",
        ])
        .arg(&project)
        .arg("--out")
        .arg(&out)
        .output()
        .expect("regia package");
    let log = format!(
        "{}{}",
        String::from_utf8_lossy(&package.stdout),
        String::from_utf8_lossy(&package.stderr)
    );
    assert!(package.status.success(), "regia package failed:\n{log}");
    eprintln!("regia package: {:.1} s", started.elapsed().as_secs_f64());
    let tarball = log
        .lines()
        .rev()
        .find(|l| l.ends_with(".tar.gz"))
        .map(PathBuf::from)
        .expect("tarball path printed");
    let extract = out.join("extracted");
    std::fs::create_dir_all(&extract).expect("extract");
    let tar = Command::new("tar")
        .arg("-xzf")
        .arg(&tarball)
        .arg("-C")
        .arg(&extract)
        .status()
        .expect("tar");
    assert!(tar.success());
    let game = std::fs::read_dir(&extract)
        .expect("extracted")
        .filter_map(Result::ok)
        .map(|e| e.path())
        .find(|p| p.is_dir())
        .expect("game dir");
    assert!(!cr::pak_files(&game.join("content")).expect("content").is_empty());
    assert!(
        game.join("assets/levels/outpost.level.ron").is_file(),
        "the level ships as a raw asset beside the paks"
    );
    let binary = game.join(&name);
    let png = out.join("first_frame.png");
    let cold = run_game(&binary, &game, &["--cold", "--png", &png.to_string_lossy()]);
    let warm = run_game(&binary, &game, &[]);
    eprintln!("cold {cold}\nwarm {warm}");
    assert!(cold.contains("from_pak=true"));
    let lit: usize = cold
        .split_whitespace()
        .find_map(|kv| kv.strip_prefix("lit_pixels="))
        .and_then(|v| v.parse().ok())
        .unwrap_or(0);
    assert!(
        lit > 10_000,
        "the first frame shows the outpost ({lit} lit pixels)"
    );
    if let Some(dir) = std::env::var_os("REGIA_COOKED_RUNTIME_OUT") {
        let _ = std::fs::copy(&png, PathBuf::from(dir).join("packaged_first_frame.png"));
    }
}
