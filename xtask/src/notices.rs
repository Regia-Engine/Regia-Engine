    /// ADR-5802: a source export (`git archive`, a release tarball, the merge gate's staged tree)
    /// has no `.git`; its files are all tracked, so the asset list comes from a walk of the tree,
    /// which skips `target` and `.git` as `rename_brand`'s walk does. The v048 gate's xtask step
    /// failed `notices --check` with "git ls-files failed: not a git repository".
    #[test]
    fn a_tree_without_git_lists_its_assets_by_walking() {
        let root = regia_test_utils::unique_temp_dir("notices-export-tree");
        let write = |rel: &str, bytes: &[u8]| {
            let path = root.join(rel);
            std::fs::create_dir_all(path.parent().expect("parent")).expect("dir");
            std::fs::write(path, bytes).expect("write");
        };
        write("assets/a.png", b"png");
        write("samples/s/fonts/b.ttf", b"ttf");
        write("fuzz/finding", b"\0binary");
        write("crates/c/src/lib.rs", b"// text");
        write("docs/d.png", b"excluded by ASSET_EXCLUDED");
        write("target/debug/e.png", b"build output");
        write("crates/c/target/f.png", b"build output");
        // A project cache that a test or a sample's own start-up wrote into the exported tree
        // (third_person cooks into samples/third_person/.regia/; ADR-7386, the M5 run).
        write("samples/s/.regia/assetdb/cook-inputs-macos.bin", b"\0cache");
        write(".regia/test-assets/g.png", b"downloaded test asset");
        // The same cache under the former name: the merge gate's tree had 91 downloaded glTF
        // textures in `.ferrite/test-assets/khronos-gltf/` (v050rc1b, ADR-7419).
        write(
            ".ferrite/test-assets/khronos-gltf/1.jpg",
            b"downloaded test asset",
        );
        let files = tracked_assets(&root).expect("a tree with no .git lists its assets");
        assert_eq!(
            files,
            ["assets/a.png", "fuzz/finding", "samples/s/fonts/b.ttf"],
            "the walk lists the assets and skips docs/, target/, .regia/ and .ferrite/"
        );
        let _ = std::fs::remove_dir_all(&root);
    }

    /// ADR-7570: the v050rc3 (and v050rc1b) gate's staged tree has no `.git`, and its tests had
    /// cooked `samples/{arena,sim_bridge,third_person}/build/paks/linux/*` and fetched
    /// `samples/third_person/assets/Fox.glb` into it. Both are ignored by the repository's
    /// `.gitignore` files, so the walk must not list them (`notices --check` failed with "no row").
    #[test]
    fn a_tree_without_git_skips_what_its_gitignore_files_ignore() {
        let root = regia_test_utils::unique_temp_dir("notices-export-ignored");
        let write = |rel: &str, bytes: &[u8]| {
            let path = root.join(rel);
            std::fs::create_dir_all(path.parent().expect("parent")).expect("dir");
            std::fs::write(path, bytes).expect("write");
        };
        // The repository's own rules, read from the files the gate tree carries.
        write(".gitignore", include_bytes!("../../.gitignore"));
        write(
            "samples/third_person/.gitignore",
            include_bytes!("../../samples/third_person/.gitignore"),
        );
        write("samples/third_person/assets/textures/kept.png", b"png");
        write(
            "samples/third_person/assets/Fox.glb",
            b"glTF fetched at first run",
        );
        for sample in ["arena", "sim_bridge", "third_person"] {
            write(&format!("samples/{sample}/build/paks/linux/game.fpak"), b"\0pak");
            write(
                &format!("samples/{sample}/build/paks/linux/manifest.bin"),
                b"\0bin",
            );
        }
        write("samples/arena/dist/arena.zip.bin", b"\0packaged");
        write("crates/c/target/golden-fail.png", b"test output");
        write("app/release.keystore", b"\0key");
        write("crates/c/assets/build.png", b"a file named like the ignored dir");
        write(".regia/test-assets/g.png", b"downloaded test asset");
        let files = tracked_assets(&root).expect("a tree with no .git lists its assets");
        assert_eq!(
            files,
            [
                "crates/c/assets/build.png",
                "samples/third_person/assets/textures/kept.png"
            ],
            "build/, dist/, crate target/ output, the fetched Fox and .regia/ are not listed"
        );
        let _ = std::fs::remove_dir_all(&root);
    }

    /// The walk cannot see a file that is tracked although a `.gitignore` matches it (force-added).
    /// Such a file must never be a binary asset, or an exported tree would miss its licence row.
    /// Only a checkout can tell (it needs `git ls-files`); an exported tree skips this test.
    #[test]
    fn ignored_tracked_files_are_not_assets() {
        let root = Path::new(env!("CARGO_MANIFEST_DIR"))
            .parent()
            .expect("workspace root");
        if !root.join(".git").exists() {
            eprintln!("skipped: {} has no .git", root.display());
            return;
        }
        let Ok(out) = std::process::Command::new("git")
            .current_dir(root)
            .args(["ls-files", "-z", "--cached", "--ignored", "--exclude-standard"])
            .output()
        else {
            eprintln!("skipped: git is not runnable");
            return;
        };
        assert!(out.status.success(), "{}", String::from_utf8_lossy(&out.stderr));
        let text = String::from_utf8_lossy(&out.stdout);
        let assets: Vec<&str> = text
            .split('\0')
            .filter(|p| {
                !p.is_empty()
                    && (is_asset(p)
                        || (!p.rsplit_once('.').is_some_and(|(_, ext)| !ext.is_empty())
                            && looks_binary(&root.join(p))))
            })
            .collect();
        assert!(
            assets.is_empty(),
            "tracked yet ignored binary assets (an exported tree's walk would miss them): {assets:?}; \
             un-ignore them in their .gitignore"
        );
    }

    /// The notices step writes the file and its `regia_cli` mirror. Both are replaced atomically; a second
    /// write that fails leaves the first file as it was (it was two plain `fs::write` calls before).
    #[test]
    fn the_notices_pair_is_written_atomically() {
        let dir = regia_test_utils::unique_temp_dir("notices-pair");
        let (first, second) = (dir.join("THIRD_PARTY_NOTICES.md"), dir.join("mirror.md"));
        write_pair_atomic(&first, &second, "one").expect("fresh pair");
        assert_eq!(std::fs::read_to_string(&first).expect("first"), "one");
        assert_eq!(std::fs::read_to_string(&second).expect("second"), "one");
        write_pair_atomic(&first, &second, "two").expect("replacing pair");
        assert_eq!(std::fs::read_to_string(&first).expect("first"), "two");
        assert_eq!(std::fs::read_to_string(&second).expect("second"), "two");
        let leftovers: Vec<_> = std::fs::read_dir(&dir)
            .expect("dir")
            .filter_map(|e| e.ok()?.file_name().into_string().ok())
            .filter(|n| n.contains(".tmp"))
            .collect();
        assert!(leftovers.is_empty(), "staging files left behind: {leftovers:?}");
    }

