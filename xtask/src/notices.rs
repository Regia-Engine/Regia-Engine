/// One upstream project (at one commit) whose source was ported into Regia Engine.
#[derive(Debug, Clone, PartialEq, Eq, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct PortedSource {
    /// Upstream project name, e.g. `Fyrox`.
    pub project: String,
    /// Upstream repository URL.
    pub url: String,
    /// SPDX licence expression of the upstream files, e.g. `MIT` or `MIT OR Apache-2.0`.
    pub licence: String,
    /// The upstream copyright notice, e.g. `Copyright (c) Bevy contributors`.
    pub copyright: String,
    /// Upstream commit the files were taken from.
    pub commit: String,
    /// Upstream paths of the ported files.
    pub files_from: Vec<String>,
    /// Repository-relative Regia Engine paths that contain the ported code.
    pub files_to: Vec<String>,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct PortedFile {
    #[serde(default)]
    source: Vec<PortedSource>,
    // Code from the owner's own game (ADR-8012): read and checked by `crate::do27_ports`, not
    // rendered into the notices.
    #[serde(default, rename = "do27")]
    _do27: Vec<toml::Value>,
    /// Owner-approved absorb rows. Not a redistributed licence, so [`parse_ported`] leaves them out.
    #[serde(default)]
    absorb: Vec<AbsorbSource>,
}

/// One behavior rewritten under the owner-approved absorb exception. Not a `[[source]]` port:
/// those rows must carry a permissive licence, and this attribution does not.
#[derive(Debug, Clone, PartialEq, Eq, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct AbsorbSource {
    /// Project the behavior was read from. Attribution only.
    pub project: String,
    /// Path of the source file inside that project.
    pub path: String,
    /// Inclusive line range, for example `1-1096`.
    pub lines: String,
    /// Commit prefix cited in the Regia header. `d6ed37677` for pin `regia-absorb-1`,
    /// or `c9513623f` for pin `regia-absorb-4`.
    pub sha: String,
    /// Pin name. `regia-absorb-1` or `regia-absorb-4`.
    pub pin: String,
    /// `as-is`, `adapt` or `requirements`.
    pub mark: String,
    /// Provenance class, for example `standard`.
    pub class: String,
    /// Repository-relative files that carry the rewrite.
    pub files_to: Vec<String>,
}

/// Parses `docs/ported-sources.toml` text. Returns only `[[source]]` rows.
pub fn parse_ported(text: &str) -> Result<Vec<PortedSource>> {
    let file: PortedFile = toml::from_str(text).with_context(|| format!("parsing {PORTED_SOURCES}"))?;
    Ok(file.source)
}

/// Loads absorb rows from `docs/ported-sources.toml`. A missing file means none.
pub fn load_absorb(root: &Path) -> Result<Vec<AbsorbSource>> {
    let path = root.join(PORTED_SOURCES);
    match std::fs::read_to_string(&path) {
        Ok(text) => {
            let file: PortedFile =
                toml::from_str(&text).with_context(|| format!("parsing {PORTED_SOURCES}"))?;
            Ok(file.absorb)
        }
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(Vec::new()),
        Err(e) => Err(e).with_context(|| format!("reading {}", path.display())),
    }
}

/// Problems with absorb rows: required fields, the pin, and a header citation.
///
/// `regia-absorb-1` cites `d6ed37677`. `regia-absorb-4` cites `c9513623f`. The header of each
/// `files_to` path must contain that row's own 9-character sha prefix.
pub fn validate_absorb(root: &Path, rows: &[AbsorbSource]) -> Vec<String> {
    const MARKS: &[&str] = &["as-is", "adapt", "requirements"];
    let mut problems = Vec::new();
    for (i, row) in rows.iter().enumerate() {
        let name = if row.path.trim().is_empty() {
            format!("absorb {}", i + 1)
        } else {
            row.path.clone()
        };
        for (field, value) in [
            ("project", &row.project),
            ("path", &row.path),
            ("lines", &row.lines),
            ("sha", &row.sha),
            ("pin", &row.pin),
            ("mark", &row.mark),
            ("class", &row.class),
        ] {
            if value.trim().is_empty() {
                problems.push(format!("{name}: `{field}` is empty"));
            }
        }
        if !absorb_sha_ok(&row.sha) {
            problems.push(format!(
                "{name}: `sha` must cite d6ed37677 (regia-absorb-1) or c9513623f (regia-absorb-4)"
            ));
        }
        if !absorb_pin_ok(&row.pin) {
            problems.push(format!("{name}: `pin` must be regia-absorb-1 or regia-absorb-4"));
        }
        if absorb_sha_ok(&row.sha) && absorb_pin_ok(&row.pin) && !absorb_pin_matches(&row.sha, &row.pin) {
            let pin = &row.pin;
            let sha = &row.sha;
            problems.push(format!("{name}: `pin` {pin} does not match `sha` {sha}"));
        }
        if !MARKS.contains(&row.mark.as_str()) {
            problems.push(format!("{name}: `mark` must be as-is, adapt or requirements"));
        }
        if row.files_to.is_empty() {
            problems.push(format!("{name}: `files_to` must list files"));
        }
        let prefix = absorb_sha_prefix(&row.sha);
        for to in &row.files_to {
            let path = root.join(to);
            let Ok(text) = std::fs::read_to_string(&path) else {
                problems.push(format!("{name}: `{to}` does not exist or is not readable"));
                continue;
            };
            let head = text.lines().take(HEADER_LINES).collect::<Vec<_>>().join("\n");
            if prefix.is_empty() || !head.contains(prefix) {
                problems.push(format!(
                    "{name}: `{to}` does not cite {prefix} in its first {HEADER_LINES} lines"
                ));
            }
        }
    }
    problems
}

fn absorb_sha_ok(sha: &str) -> bool {
    sha == "d6ed37677"
        || sha.starts_with("d6ed3767703b1cabb12348cb3deb97ac27ac4fcb")
        || sha == "c9513623f"
        || sha.starts_with("c9513623fe278ce58a3df3bd707d6fe91796e50a")
}

fn absorb_pin_ok(pin: &str) -> bool {
    pin == "regia-absorb-1" || pin == "regia-absorb-4"
}

fn absorb_pin_matches(sha: &str, pin: &str) -> bool {
    let absorb_1 = sha == "d6ed37677" || sha.starts_with("d6ed3767703b1cabb12348cb3deb97ac27ac4fcb");
    let absorb_4 = sha == "c9513623f" || sha.starts_with("c9513623fe278ce58a3df3bd707d6fe91796e50a");
    (absorb_1 && pin == "regia-absorb-1") || (absorb_4 && pin == "regia-absorb-4")
}

fn absorb_sha_prefix(sha: &str) -> &str {
    if sha.len() >= 9 { &sha[..9] } else { sha }
}

/// Loads the ported-source list from the workspace root; a missing file means nothing was ported.
pub fn load_ported(root: &Path) -> Result<Vec<PortedSource>> {
    let path = root.join(PORTED_SOURCES);
    match std::fs::read_to_string(&path) {
        Ok(text) => parse_ported(&text),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(Vec::new()),
        Err(e) => Err(e).with_context(|| format!("reading {}", path.display())),
    }
}

/// The licence identifiers of an SPDX expression (`A OR (B AND C)` → `A`, `B`, `C`).
fn licence_ids(expr: &str) -> impl Iterator<Item = &str> {
    expr.split(|c: char| c.is_whitespace() || c == '(' || c == ')' || c == '/')
        .filter(|t| !t.is_empty() && !matches!(*t, "OR" | "AND"))
}

/// Problems with the entries themselves (empty fields, non-permissive licences), one message each.
pub fn validate_ported(ported: &[PortedSource]) -> Vec<String> {
    let mut problems = Vec::new();
    for (i, s) in ported.iter().enumerate() {
        let name = if s.project.trim().is_empty() {
            format!("entry {}", i + 1)
        } else {
            s.project.clone()
        };
        for (field, value) in [
            ("project", &s.project),
            ("url", &s.url),
            ("licence", &s.licence),
            ("copyright", &s.copyright),
            ("commit", &s.commit),
        ] {
            if value.trim().is_empty() {
                problems.push(format!("{name}: `{field}` is empty"));
            }
        }
        if s.files_from.is_empty() || s.files_to.is_empty() {
            problems.push(format!(
                "{name}: `files_from` and `files_to` must both list files"
            ));
        }
        for id in licence_ids(&s.licence) {
            if !PERMISSIVE.contains(&id) {
                problems.push(format!(
                    "{name}: licence `{id}` is not permissive; only {} may be ported",
                    PERMISSIVE.join(", ")
                ));
            }
        }
    }
    problems
}

/// Problems with the ported files on disk: every `files_to` path exists under `root` and names the
/// project's URL and the words "ported from" in its first lines.
pub fn check_ported_files(root: &Path, ported: &[PortedSource]) -> Vec<String> {
    let mut problems = Vec::new();
    for s in ported {
        for to in &s.files_to {
            let path = root.join(to);
            let Ok(text) = std::fs::read_to_string(&path) else {
                problems.push(format!("{}: `{to}` does not exist or is not readable", s.project));
                continue;
            };
            let head = text.lines().take(HEADER_LINES).collect::<Vec<_>>().join("\n");
            if !head.to_lowercase().contains("ported from") || !head.contains(s.url.trim_end_matches('/')) {
                problems.push(format!(
                    "{}: `{to}` lacks its attribution header (\"Portions ported from {} ({}, commit ...)\" \
                     plus the copyright and licence text, within its first {HEADER_LINES} lines)",
                    s.project, s.project, s.url
                ));
            }
        }
    }
    problems
}

