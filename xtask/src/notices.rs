//! `notices`: generates `THIRD_PARTY_NOTICES.md` from the resolved dependency graph.
//!
//! The file lists every third-party crate that can be compiled into a Regia Engine binary (engine, editor
//! and tools), with its licence and source. Full licence texts are bundled with packaged builds
//! (`docs/specs/21-tooling-and-packaging.md`).
//!
//! Source files ported from permissively licensed projects are listed by hand in
//! `docs/ported-sources.toml` and rendered as the file's "Ported source code" section (ADR-086).

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::path::Path;

use anyhow::{Context, Result};
use serde::Deserialize;

use crate::graph::Graph;
use crate::layers::{Layer, layer_of};

/// The copy of `THIRD_PARTY_NOTICES.md` that `regia_cli` compiles in (`include_str!` cannot leave
/// the crate folder, ADR-1485); `cargo xtask notices` writes and checks both.
pub const CLI_MIRROR: &str = "crates/regia_cli/assets/THIRD_PARTY_NOTICES.md";

/// Whether a workspace crate is compiled into something Regia Engine ships (engine, editor, CLI).
pub fn shipped(name: &str) -> bool {
    layer_of(name).is_some_and(|l| !matches!(l, Layer::TestOnly | Layer::Automation | Layer::Sample))
}

/// The `cargo tree` feature arguments of a shipped crate's notices tree: every optional feature
/// (ADR-5556), including the umbrella's optional codecs and x86 AV1 assembly. A game's package ships
/// these notices (ADR-1379), so a crate behind an off-by-default feature (`regia/accesskit`,
/// `regia/net-quic`, `regia_steam/steamworks`, ...) must be listed too; this is the set `deny.toml`
/// checks (`all-features = true`). The SBOM's `game` profile resolves its own, narrower set
/// (`crate::sbom::game_tree_args`, ADR-5903).
pub const SHIPPING_FEATURE_ARGS: &[&str] = &["--all-features"];

/// Resolves a shipped crate with [`SHIPPING_FEATURE_ARGS`]. Cargo resolves build dependencies
/// without running native build scripts, and is asked offline first (`Graph::tree_offline_first`).
pub fn shipping_tree(root: &Path, package: &str) -> Result<Graph> {
    Graph::tree_offline_first(root, package, SHIPPING_FEATURE_ARGS)
}

/// The resolved third-party crates: (name, version) -> (licence, repository).
pub type CrateTable = BTreeMap<(String, String), (String, String)>;

/// Every third-party crate reachable from the roots of `trees`: (name, version) -> (licence,
/// repository). Shared by the notices file and the SBOM so both list the same set.
pub fn third_party(trees: &[Graph]) -> CrateTable {
    let mut crates = CrateTable::new();
    for graph in trees {
        for reached in graph.reachable(0, |_, _| false).into_keys() {
            let dep = &graph.packages[reached];
            if dep.workspace {
                continue;
            }
            crates
                .entry((dep.name.clone(), dep.version.clone()))
                .or_insert_with(|| {
                    (
                        dep.license
                            .clone()
                            .unwrap_or_else(|| "UNKNOWN (see crate)".into()),
                        dep.repository.clone().unwrap_or_default(),
                    )
                });
        }
    }
    crates
}

/// Renders the notices file from the resolved trees of the shipped crates, without a seal.
/// Deterministic: same lockfile, same output.
pub fn render(trees: &[Graph], ported: &[PortedSource]) -> String {
    render_crates(&third_party(trees), ported, &[], None)
}

/// Renders the notices file from a crate table. With `inputs`, the header carries the seal that
/// binds the table to the inputs it was resolved from ([`sealed_crates`], ADR-5903).
pub fn render_crates(
    crates: &CrateTable,
    ported: &[PortedSource],
    assets: &[ResolvedNotice],
    inputs: Option<&ResolveInputs>,
) -> String {
    let licences: BTreeSet<&str> = crates.values().map(|(l, _)| l.as_str()).collect();
    let table = table_text(crates);
    let mut out = String::new();
    out.push_str("# Third-party notices\n\n");
    out.push_str(
        "<!-- Generated by `cargo xtask notices`. Do not edit by hand; CI checks it is up to date. -->\n",
    );
    if let Some(inputs) = inputs {
        let _ = writeln!(out, "{SEAL_START}{}{SEAL_END}", seal(inputs, &table));
    }
    out.push('\n');
    out.push_str(
        "Regia Engine is licensed under the Mozilla Public License 2.0 (`LICENSE`). It is built with the open-source crates below,\n\
         each used under the licence shown. Where a crate offers a choice of licences (`A OR B`), Regia Engine\n\
         uses it under any one of them. Packaged builds include the full licence texts and copyright\n\
         notices of these crates (`docs/specs/21-tooling-and-packaging.md`).\n\n\
         Fonts: egui's default fonts (`epaint_default_fonts`, editor only) include fonts under the Ubuntu\n\
         Font Licence 1.0 and the SIL Open Font License 1.1.",
    );
    if assets.is_empty() {
        out.push_str("\n\n");
    } else {
        out.push_str(
            " The fonts Regia Engine bundles itself (the runtime UI's,\n\
             the editor's and the manual's) and its other bundled third-party files are listed with their\n\
             copyright lines and licence texts under \"Bundled fonts and assets\" below; their licence files\n\
             also ship beside them.\n\n",
        );
    }
    let _ = writeln!(
        out,
        "{} crates under {} licence expressions.\n",
        crates.len(),
        licences.len()
    );
    out.push_str(TABLE_HEADER);
    out.push_str(&table);
    render_ported(&mut out, ported);
    render_asset_notices(&mut out, assets);
    out.push_str(CLDR_NOTICE);
    out.push_str(XESS_NOTICE);
    out
}

/// The header of the crate table.
const TABLE_HEADER: &str = "| Crate | Version | Licence | Source |\n|---|---|---|---|\n";

/// The seal line: `SEAL_START`, 64 hex digits, `SEAL_END`.
const SEAL_START: &str = "<!-- Resolve seal ";
const SEAL_END: &str = ": binds the crate table to the inputs it was resolved from (Cargo.lock, the dependency \
     and feature tables of every manifest, the generator); `cargo xtask notices --check` reads the table without \
     resolving while they are unchanged (ADR-5903). -->";

/// The rows of the crate table, one line per crate.
fn table_text(crates: &CrateTable) -> String {
    let mut out = String::new();
    for ((name, version), (licence, repo)) in crates {
        let _ = writeln!(out, "| {name} | {version} | {licence} | {repo} |");
    }
    out
}

/// A digest of everything the crate table is resolved from (ADR-5903): the generator's own source
/// (this module and `crate::graph`), every shipped crate with its `cargo tree` feature arguments,
/// `Cargo.lock`, `.cargo/config.toml`, and the dependency, feature, patch and workspace tables of the
/// root manifest, every workspace member and every path dependency (comments, lints, test targets
/// and dev-dependencies do not count: `cargo tree -e normal,build` resolves without them). With
/// `--locked` the resolve is a function of these, so while they are unchanged the committed table
/// is still the resolve. Not included: the cargo version (resolution of a fixed lockfile is stable
/// across releases) and the crates' published manifests (immutable per version on crates.io).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ResolveInputs(String);

impl ResolveInputs {
    /// Hashes named input parts (name, bytes) in order.
    pub fn from_parts(parts: &[(String, Vec<u8>)]) -> Self {
        let mut hasher = blake3::Hasher::new();
        hasher.update(b"regia-notices-resolve-inputs-v1\n");
        for (name, bytes) in parts {
            hasher.update(&(name.len() as u64).to_le_bytes());
            hasher.update(name.as_bytes());
            hasher.update(&(bytes.len() as u64).to_le_bytes());
            hasher.update(bytes);
        }
        Self(hasher.finalize().to_hex().to_string())
    }
}

/// The input parts of [`ResolveInputs`] for the repository at `root` and the shipped crates
/// `shipped`, in a stable order. Reads `cargo metadata --no-deps --offline` and local files only,
/// so it needs neither the network nor any downloaded crate. Paths are relative to the workspace
/// root with `/` separators and line endings are normalized, so every host computes the same parts.
pub fn resolve_input_parts(root: &Path, shipped: &[String]) -> Result<Vec<(String, Vec<u8>)>> {
    let mut parts: Vec<(String, Vec<u8>)> = vec![
        (
            "generator:notices.rs".into(),
            include_str!("notices.rs").as_bytes().to_vec(),
        ),
        (
            "generator:graph.rs".into(),
            include_str!("graph.rs").as_bytes().to_vec(),
        ),
    ];
    let mut names: Vec<&String> = shipped.iter().collect();
    names.sort();
    names.dedup();
    let trees: Vec<String> = names
        .iter()
        .map(|n| format!("{n} {}", SHIPPING_FEATURE_ARGS.join(" ")))
        .collect();
    parts.push(("shipped".into(), trees.join("\n").into_bytes()));
    for file in ["Cargo.lock", ".cargo/config.toml"] {
        let bytes = match std::fs::read(root.join(file)) {
            Ok(bytes) => normalize_newlines(&bytes),
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => Vec::new(),
            Err(e) => return Err(e).with_context(|| format!("reading {file}")),
        };
        parts.push((file.into(), bytes));
    }
    for rel in crate::graph::manifest_paths(root)? {
        let text = std::fs::read_to_string(root.join(&rel)).with_context(|| format!("reading {rel}"))?;
        parts.push((rel, canonical_manifest(&text).into_bytes()));
    }
    Ok(parts)
}

/// [`ResolveInputs`] of the repository at `root` (see [`resolve_input_parts`]).
pub fn resolve_inputs(root: &Path, shipped: &[String]) -> Result<ResolveInputs> {
    Ok(ResolveInputs::from_parts(&resolve_input_parts(root, shipped)?))
}

fn normalize_newlines(bytes: &[u8]) -> Vec<u8> {
    let mut out = Vec::with_capacity(bytes.len());
    for (i, &b) in bytes.iter().enumerate() {
        if b == b'\r' && bytes.get(i + 1) == Some(&b'\n') {
            continue;
        }
        out.push(b);
    }
    out
}

/// The parts of a `Cargo.toml` that can change a `cargo tree -e normal,build` resolve, as canonical
/// text (sorted keys): `package.name`/`links`, `dependencies`, `build-dependencies`, `features`,
/// `target.<cfg>.{dependencies,build-dependencies}`, `patch`, `replace` and
/// `workspace.{members,exclude,resolver,dependencies}`. A manifest that does not parse counts with
/// its whole text.
pub fn canonical_manifest(text: &str) -> String {
    let Ok(table) = toml::from_str::<toml::Table>(text) else {
        return String::from_utf8_lossy(&normalize_newlines(text.as_bytes())).into_owned();
    };
    let pick = |from: &toml::Table, keys: &[&str]| -> toml::Table {
        keys.iter()
            .filter_map(|k| from.get(*k).map(|v| ((*k).to_string(), v.clone())))
            .collect()
    };
    const DEPS: &[&str] = &["dependencies", "build-dependencies"];
    let mut kept = pick(
        &table,
        &[
            "dependencies",
            "build-dependencies",
            "features",
            "patch",
            "replace",
        ],
    );
    if let Some(package) = table.get("package").and_then(toml::Value::as_table) {
        kept.insert(
            "package".into(),
            toml::Value::Table(pick(package, &["name", "links"])),
        );
    }
    if let Some(targets) = table.get("target").and_then(toml::Value::as_table) {
        let narrowed: toml::Table = targets
            .iter()
            .filter_map(|(cfg, v)| {
                let deps = pick(v.as_table()?, DEPS);
                (!deps.is_empty()).then(|| (cfg.clone(), toml::Value::Table(deps)))
            })
            .collect();
        if !narrowed.is_empty() {
            kept.insert("target".into(), toml::Value::Table(narrowed));
        }
    }
    if let Some(workspace) = table.get("workspace").and_then(toml::Value::as_table) {
        kept.insert(
            "workspace".into(),
            toml::Value::Table(pick(
                workspace,
                &["members", "exclude", "resolver", "dependencies"],
            )),
        );
    }
    let mut out = String::new();
    canonical_value(&toml::Value::Table(kept), &mut out);
    out
}

fn canonical_value(value: &toml::Value, out: &mut String) {
    match value {
        toml::Value::Table(table) => {
            let mut entries: Vec<(&String, &toml::Value)> = table.iter().collect();
            entries.sort_unstable_by_key(|(key, _)| *key);
            out.push('{');
            for (key, item) in entries {
                let _ = write!(out, "{key:?}=");
                canonical_value(item, out);
                out.push(',');
            }
            out.push('}');
        }
        toml::Value::Array(items) => {
            out.push('[');
            for item in items {
                canonical_value(item, out);
                out.push(',');
            }
            out.push(']');
        }
        toml::Value::String(s) => {
            let _ = write!(out, "{s:?}");
        }
        other => {
            let _ = write!(out, "{other}");
        }
    }
}

/// The seal of a crate table resolved from `inputs`: 64 hex digits.
fn seal(inputs: &ResolveInputs, table: &str) -> String {
    let mut hasher = blake3::Hasher::new();
    hasher.update(b"regia-notices-seal-v1\n");
    hasher.update(inputs.0.as_bytes());
    hasher.update(b"\n");
    hasher.update(table.as_bytes());
    hasher.finalize().to_hex().to_string()
}

/// The crate table of a rendered notices file, when its seal matches `inputs`: the table was
/// resolved from exactly these inputs, so it is still the resolve and no `cargo tree` is needed.
/// `None` when there is no seal, the inputs changed, or the table was edited after sealing.
pub fn sealed_crates(text: &str, inputs: &ResolveInputs) -> Option<CrateTable> {
    let recorded = text
        .lines()
        .find_map(|l| l.strip_prefix(SEAL_START)?.strip_suffix(SEAL_END))?;
    let start = text.find(TABLE_HEADER)? + TABLE_HEADER.len();
    let mut table = String::new();
    for line in text[start..].lines().take_while(|l| l.starts_with("| ")) {
        table.push_str(line);
        table.push('\n');
    }
    if seal(inputs, &table) != recorded {
        return None;
    }
    let mut crates = CrateTable::new();
    for line in table.lines() {
        let inner = line.strip_prefix("| ")?.strip_suffix(" |")?;
        let mut cells = inner.splitn(4, " | ");
        let (name, version, licence) = (cells.next()?, cells.next()?, cells.next()?);
        let repo = cells.next().unwrap_or_default().trim_end();
        crates.insert(
            (name.to_string(), version.to_string()),
            (licence.to_string(), repo.to_string()),
        );
    }
    Some(crates)
}

/// `text` without its seal line, to tell a stale seal from a stale table.
pub fn without_seal(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    for line in text.split_inclusive('\n') {
        if !line.starts_with(SEAL_START) {
            out.push_str(line);
        }
    }
    out
}

/// The workspace crates whose trees the notices cover (`shipped`), from `cargo metadata --no-deps`.
pub fn shipped_crates() -> Result<Vec<String>> {
    Ok(Graph::declared()?
        .packages
        .iter()
        .filter(|p| p.workspace && shipped(&p.name))
        .map(|p| p.name.clone())
        .collect())
}

/// Whether `THIRD_PARTY_NOTICES.md` at `root` carries a seal that matches the repository's current
/// resolve inputs, so `cargo xtask notices --check` needs no `cargo tree` (ADR-5903).
pub fn seal_is_fresh(root: &Path) -> Result<bool> {
    let inputs = resolve_inputs(root, &shipped_crates()?)?;
    let text = std::fs::read_to_string(root.join("THIRD_PARTY_NOTICES.md"))
        .context("reading THIRD_PARTY_NOTICES.md")?;
    Ok(sealed_crates(&text, &inputs).is_some())
}

