    fn be_u16(bytes: &[u8], at: usize) -> u16 {
        u16::from_be_bytes([bytes[at], bytes[at + 1]])
    }

    fn be_u32(bytes: &[u8], at: usize) -> u32 {
        u32::from_be_bytes([bytes[at], bytes[at + 1], bytes[at + 2], bytes[at + 3]])
    }

    /// UTF-16BE text from an OpenType name record (platform 0 or 3).
    fn utf16_be(raw: &[u8]) -> Result<String, String> {
        if !raw.len().is_multiple_of(2) {
            return Err("UTF-16 copyright has an odd length".into());
        }
        let units: Vec<u16> = raw
            .as_chunks::<2>()
            .0
            .iter()
            .map(|pair| u16::from_be_bytes(*pair))
            .collect();
        String::from_utf16(&units).map_err(|err| err.to_string())
    }

    /// Copyright notice of a TrueType/OpenType font: name ID 0. Windows Unicode (platform 3)
    /// wins when the font has more than one.
    fn font_name_copyright(bytes: &[u8]) -> Result<String, String> {
        if bytes.len() < 12 {
            return Err("too small for an sfnt header".into());
        }
        let num_tables = usize::from(be_u16(bytes, 4));
        let dir_end = 12 + num_tables * 16;
        if bytes.len() < dir_end {
            return Err("table directory is truncated".into());
        }
        let mut name_at = None;
        for rec in (12..dir_end).step_by(16) {
            if &bytes[rec..rec + 4] == b"name" {
                let off = be_u32(bytes, rec + 8) as usize;
                let len = be_u32(bytes, rec + 12) as usize;
                name_at = Some((off, len));
                break;
            }
        }
        let Some((off, len)) = name_at else {
            return Err("no name table".into());
        };
        let Some(end) = off.checked_add(len) else {
            return Err("name table offset overflows".into());
        };
        if end > bytes.len() || len < 6 {
            return Err("name table is truncated".into());
        }
        let table = &bytes[off..end];
        let count = usize::from(be_u16(table, 2));
        let storage = usize::from(be_u16(table, 4));
        if 6 + count * 12 > table.len() {
            return Err("name records are truncated".into());
        }
        let mut chosen: Option<(u16, String)> = None;
        for index in 0..count {
            let base = 6 + index * 12;
            let platform = be_u16(table, base);
            if be_u16(table, base + 6) != 0 {
                continue;
            }
            let nlen = usize::from(be_u16(table, base + 8));
            let noff = usize::from(be_u16(table, base + 10));
            let Some(start) = storage.checked_add(noff) else {
                return Err("copyright offset overflows".into());
            };
            let Some(stop) = start.checked_add(nlen) else {
                return Err("copyright length overflows".into());
            };
            if stop > table.len() {
                return Err("copyright string is truncated".into());
            }
            let raw = &table[start..stop];
            let text = if platform == 0 || platform == 3 {
                utf16_be(raw)?
            } else {
                String::from_utf8_lossy(raw).into_owned()
            };
            let replace = chosen
                .as_ref()
                .is_none_or(|(kept, _)| platform == 3 && *kept != 3);
            if replace {
                chosen = Some((platform, text));
            }
        }
        chosen.map(|(_, text)| text).ok_or_else(|| "no name ID 0".into())
    }

