/// The SIL Open Font License 1.1 text (preamble to disclaimer), copied from the licence files
/// beside the bundled fonts; the notices carry it once for every OFL-1.1 entry.
const OFL_TEXT: &str = include_str!("notices/ofl-1.1.txt");

/// A `[[notice]]` row with its copyright lines read and its globs expanded: what
/// [`render_crates`] writes.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ResolvedNotice {
    /// Display name.
    pub name: String,
    /// SPDX identifier.
    pub licence: String,
    /// The copyright lines: each covered font's own record (OpenType name ID 0), then the other
    /// lines of the licence file (or the ported-source entry), verbatim (ADR-10066).
    pub copyright: Vec<String>,
    /// The tracked files covered, sorted.
    pub files: Vec<String>,
    /// The licence file beside the files, or `None` for a ported-source entry.
    pub licence_file: Option<String>,
    /// The ported-source project that carries the licence, if any.
    pub ported: Option<String>,
}

/// The copyright notice of a licence file: the lines (trimmed) that start with `Copyright` in its
/// header, before the licence text itself begins (a line with `licensed under`, `SIL OPEN FONT
/// LICENSE` or a `---` rule), so the OFL's own "Copyright Holder" clauses are not taken.
///
/// ADR-10066: a line starting with `(c)`, `(C)` or `©` counts too, the form some fonts' own
/// copyright record uses (Noto Sans KR/SC: `(c) 2014-2021 Adobe ...`).
pub fn copyright_lines(text: &str) -> Vec<String> {
    text.lines()
        .map(str::trim)
        .take_while(|l| {
            !(l.contains("licensed under") || l.starts_with("SIL OPEN FONT LICENSE") || l.starts_with("---"))
        })
        .filter(|l| ["Copyright", "(c)", "(C)", "©"].iter().any(|p| l.starts_with(p)))
        .map(str::to_string)
        .collect()
}

/// Whether `file` is a TrueType/OpenType font whose `name` table [`font_copyright`] can read
/// (`.ttf`, `.otf`; WOFF2 is Brotli-compressed and is not read).
fn is_sfnt_font(file: &str) -> bool {
    let lower = file.to_ascii_lowercase();
    lower.ends_with(".ttf") || lower.ends_with(".otf")
}

/// Big-endian `u16` at `at`, `None` past the end.
fn read_u16(bytes: &[u8], at: usize) -> Option<u16> {
    Some(u16::from_be_bytes([
        *bytes.get(at)?,
        *bytes.get(at.checked_add(1)?)?,
    ]))
}

/// Big-endian `u32` at `at`, `None` past the end.
fn read_u32(bytes: &[u8], at: usize) -> Option<u32> {
    let end = at.checked_add(4)?;
    let b = bytes.get(at..end)?;
    Some(u32::from_be_bytes([b[0], b[1], b[2], b[3]]))
}

/// The copyright notice a TrueType/OpenType font carries itself: the `name` table's name ID 0,
/// trimmed, with the Windows Unicode record (platform 3) preferred over the others (ADR-10066;
/// OpenType spec, `name` table). `Ok(None)` when the font has no `name` table or no name ID 0;
/// `Err` when the table directory or the record points past the file.
///
/// # Errors
///
/// A message naming the truncated or undecodable structure.
pub fn font_copyright(bytes: &[u8]) -> std::result::Result<Option<String>, String> {
    let truncated = |what: &str| format!("{what} is truncated");
    let num_tables = usize::from(read_u16(bytes, 4).ok_or_else(|| truncated("the sfnt header"))?);
    let mut name_at = None;
    for index in 0..num_tables {
        let rec = 12 + index * 16;
        let tag = bytes
            .get(rec..rec + 4)
            .ok_or_else(|| truncated("the table directory"))?;
        if tag == b"name" {
            let off = read_u32(bytes, rec + 8).ok_or_else(|| truncated("the table directory"))?;
            let len = read_u32(bytes, rec + 12).ok_or_else(|| truncated("the table directory"))?;
            name_at = Some((off as usize, len as usize));
            break;
        }
    }
    let Some((off, len)) = name_at else {
        return Ok(None);
    };
    let table = off
        .checked_add(len)
        .and_then(|end| bytes.get(off..end))
        .ok_or_else(|| truncated("the name table"))?;
    let count = usize::from(read_u16(table, 2).ok_or_else(|| truncated("the name table"))?);
    let storage = usize::from(read_u16(table, 4).ok_or_else(|| truncated("the name table"))?);
    let mut chosen: Option<(u16, String)> = None;
    for index in 0..count {
        let base = 6 + index * 12;
        let field = |at: usize| read_u16(table, base + at).ok_or_else(|| truncated("the name records"));
        let platform = field(0)?;
        if field(6)? != 0 {
            continue;
        }
        let start = storage + usize::from(field(10)?);
        let raw = table
            .get(start..start + usize::from(field(8)?))
            .ok_or_else(|| truncated("the copyright string"))?;
        let text = if platform == 0 || platform == 3 {
            let (pairs, rest) = raw.as_chunks::<2>();
            if !rest.is_empty() {
                return Err("the UTF-16 copyright has an odd length".into());
            }
            let units: Vec<u16> = pairs.iter().map(|p| u16::from_be_bytes(*p)).collect();
            String::from_utf16(&units).map_err(|e| e.to_string())?
        } else {
            String::from_utf8_lossy(raw).into_owned()
        };
        if chosen
            .as_ref()
            .is_none_or(|(kept, _)| platform == 3 && *kept != 3)
        {
            chosen = Some((platform, text.trim().to_string()));
        }
    }
    Ok(chosen.map(|(_, text)| text).filter(|t| !t.is_empty()))
}

/// The copyright records of the covered font files, in file order without repeats, for a notice
/// whose licence file `licence_lines` came from: every font's own line is checked against the
/// licence file (a problem when it is missing there, so the sidecar that ships beside the font
/// stays true) and returned so the notices bullet it either way (ADR-10066).
fn font_copyrights(
    root: &Path,
    label: &str,
    licence_file: Option<&str>,
    licence_lines: &[String],
    covered: &[String],
    problems: &mut Vec<String>,
) -> Vec<String> {
    let mut own: Vec<String> = Vec::new();
    for file in covered.iter().filter(|f| is_sfnt_font(f)) {
        let Ok(bytes) = std::fs::read(root.join(file)) else {
            problems.push(format!("{label}: `{file}` is not readable"));
            continue;
        };
        match font_copyright(&bytes) {
            Ok(Some(line)) => {
                if let Some(sidecar) = licence_file
                    && !licence_lines.contains(&line)
                {
                    problems.push(format!(
                        "{label}: the copyright record of `{file}` (OpenType name ID 0) is `{line}`, \
                         which is not a copyright line of `{sidecar}`; make the licence file's header \
                         line match the font"
                    ));
                }
                if !own.contains(&line) {
                    own.push(line);
                }
            }
            Ok(None) => {}
            Err(e) => problems.push(format!("{label}: `{file}`: {e}")),
        }
    }
    own
}

/// Resolves the `[[notice]]` rows against the tracked asset `files` and the files under `root`,
/// and checks that every shipping third-party asset has an entry (ADR-8888). Returns the resolved
/// entries (sorted by name) and the problems, one message each; any problem fails `--check`.
pub fn resolve_asset_notices(
    root: &Path,
    rows: &[AssetRow],
    notices: &[AssetNotice],
    ported: &[PortedSource],
    files: &[String],
) -> (Vec<ResolvedNotice>, Vec<String>) {
    let mut problems = Vec::new();
    let mut resolved = Vec::new();
    for n in notices {
        let label = if n.name.trim().is_empty() {
            "[[notice]] with an empty name".to_string()
        } else {
            format!("[[notice]] {}", n.name)
        };
        if n.name.trim().is_empty() || n.licence.trim().is_empty() || n.files.is_empty() {
            problems.push(format!("{label}: `name`, `licence` and `files` must be set"));
        }
        let mut covered: Vec<String> = Vec::new();
        for glob in &n.files {
            let matched: Vec<&String> = files.iter().filter(|f| glob_match(glob, f)).collect();
            if matched.is_empty() {
                problems.push(format!("{label}: `{glob}` matches no tracked binary file"));
            }
            covered.extend(matched.into_iter().cloned());
        }
        covered.sort();
        covered.dedup();
        let copyright = match (&n.licence_file, &n.ported) {
            (Some(file), None) => match std::fs::read_to_string(root.join(file)) {
                Ok(text) => {
                    if n.licence.trim() == "OFL-1.1" && !text.contains("SIL OPEN FONT LICENSE Version 1.1") {
                        problems.push(format!(
                            "{label}: `{file}` does not contain the SIL Open Font License 1.1 text"
                        ));
                    }
                    let lines = copyright_lines(&text);
                    if lines.is_empty() {
                        problems.push(format!("{label}: `{file}` has no line starting with `Copyright`"));
                    }
                    lines
                }
                Err(_) => {
                    problems.push(format!(
                        "{label}: licence file `{file}` does not exist or is not readable"
                    ));
                    Vec::new()
                }
            },
            (None, Some(project)) => match ported.iter().find(|s| s.project == *project) {
                Some(s) => vec![s.copyright.clone()],
                None => {
                    problems.push(format!(
                        "{label}: `ported = \"{project}\"` names no [[source]] in {PORTED_SOURCES}"
                    ));
                    Vec::new()
                }
            },
            _ => {
                problems.push(format!(
                    "{label}: set exactly one of `licence_file` (the licence text beside the files) or `ported`"
                ));
                Vec::new()
            }
        };
        // ADR-10066: each covered font's own copyright record leads the bullets, so a shipped
        // notice never states another year or holder than the font file it names.
        let own = font_copyrights(
            root,
            &label,
            n.licence_file.as_deref(),
            &copyright,
            &covered,
            &mut problems,
        );
        let copyright: Vec<String> = own
            .iter()
            .cloned()
            .chain(copyright.into_iter().filter(|line| !own.contains(line)))
            .collect();
        resolved.push(ResolvedNotice {
            name: n.name.clone(),
            licence: n.licence.clone(),
            copyright,
            files: covered,
            licence_file: n.licence_file.clone(),
            ported: n.ported.clone(),
        });
    }
    for file in files {
        let Some(row) = asset_row(rows, file) else {
            continue;
        };
        if row.origin != "third_party" || !row.ships {
            continue;
        }
        if !notices
            .iter()
            .any(|n| n.files.iter().any(|glob| glob_match(glob, file)))
        {
            problems.push(format!(
                "{file}: a shipping third-party asset ({}) with no notices entry; add a [[notice]] to \
                 {ASSET_LICENCES} naming it, its licence file and its licence, then run `cargo xtask notices`",
                row.licence
            ));
        }
    }
    resolved.sort_by(|a, b| a.name.cmp(&b.name));
    (resolved, problems)
}

/// The "Bundled fonts and assets" section for `notices` (empty when there are none), for the
/// demo's notices (`crate::demo_legal`).
pub fn render_asset_notices_section(notices: &[ResolvedNotice]) -> String {
    let mut out = String::new();
    render_asset_notices(&mut out, notices);
    out
}

/// Appends the "Bundled fonts and assets" section for `notices` (nothing when empty).
fn render_asset_notices(out: &mut String, notices: &[ResolvedNotice]) {
    if notices.is_empty() {
        return;
    }
    let _ = write!(
        out,
        "## Bundled fonts and assets\n\n\
         Third-party files compiled into Regia Engine binaries, embedded in the manual or copied into\n\
         packages, from the `[[notice]]` rows of `{ASSET_LICENCES}`. The copyright lines are each font\n\
         file's own copyright record (OpenType name ID 0) and the header of the licence file that ships\n\
         beside the files in the source.\n\n"
    );
    for n in notices {
        let _ = writeln!(out, "### {}\n", n.name);
        let _ = writeln!(out, "- Licence: {}", n.licence);
        for line in &n.copyright {
            let _ = writeln!(out, "- {line}");
        }
        match (&n.licence_file, &n.ported) {
            (Some(file), _) => {
                let _ = writeln!(out, "- Licence file: `{file}`");
            }
            (None, Some(project)) => {
                let _ = writeln!(out, "- Ported with: {project} (see \"Ported source code\")");
            }
            (None, None) => {}
        }
        out.push_str("- Files:\n");
        for file in &n.files {
            let _ = writeln!(out, "  - `{file}`");
        }
        out.push('\n');
    }
    if notices.iter().any(|n| n.licence == "OFL-1.1") {
        out.push_str(
            "### SIL Open Font License 1.1\n\n\
             Applies to the OFL-1.1 entries above, with each entry's copyright notice:\n\n",
        );
        for line in OFL_TEXT.lines().map(str::trim_end) {
            if line.is_empty() {
                out.push_str(">\n");
            } else {
                let _ = writeln!(out, "> {line}");
            }
        }
        out.push('\n');
    }
}

