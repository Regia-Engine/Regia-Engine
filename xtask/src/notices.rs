/// Matches a repository-relative path against a glob: `*` matches any run of characters except `/`,
/// `**` matches any run including `/`, every other character matches itself.
pub fn glob_match(pattern: &str, path: &str) -> bool {
    fn go(p: &[u8], s: &[u8]) -> bool {
        match p.first() {
            None => s.is_empty(),
            Some(b'*') if p.get(1) == Some(&b'*') => {
                let rest = &p[2..];
                (0..=s.len()).any(|i| go(rest, &s[i..]))
            }
            Some(b'*') => {
                let rest = &p[1..];
                let mut i = 0;
                loop {
                    if go(rest, &s[i..]) {
                        return true;
                    }
                    if i >= s.len() || s[i] == b'/' {
                        return false;
                    }
                    i += 1;
                }
            }
            Some(&c) => s.first() == Some(&c) && go(&p[1..], &s[1..]),
        }
    }
    go(pattern.as_bytes(), path.as_bytes())
}

/// Whether a tracked path is a binary asset that needs a licence row.
pub fn is_asset(path: &str) -> bool {
    if ASSET_EXCLUDED.iter().any(|d| path.starts_with(d)) {
        return false;
    }
    path.rsplit_once('.')
        .is_some_and(|(_, ext)| ASSET_EXTENSIONS.contains(&ext.to_ascii_lowercase().as_str()))
}

/// Extensionless tracked files can still be binary (a fuzz finding saved without a name): a NUL
/// byte in the first chunk says "binary" more honestly than an extension list does.
fn looks_binary(path: &Path) -> bool {
    let Ok(mut file) = std::fs::File::open(path) else {
        return false;
    };
    use std::io::Read as _;
    let mut chunk = [0u8; 8192];
    let Ok(n) = file.read(&mut chunk) else {
        return false;
    };
    chunk[..n].contains(&0)
}

/// The tracked files (from `git ls-files`, or a walk of an exported tree) that need a licence row, sorted. Besides the
/// extension list, extensionless files with binary content are included (fuzz findings and
/// similar), so a tracked binary cannot escape the record by omitting its extension.
pub fn tracked_assets(root: &Path) -> Result<Vec<String>> {
    let mut files: Vec<String> = repository_files(root)?
        .into_iter()
        .filter(|p| {
            is_asset(p)
                || (!p.rsplit_once('.').is_some_and(|(_, ext)| !ext.is_empty())
                    && looks_binary(&root.join(p)))
        })
        .collect();
    files.sort();
    Ok(files)
}

/// The repository's files, relative and `/`-separated: `git ls-files` in a checkout; in a tree
/// with no `.git` (a source export: `git archive`, a release tarball, the merge gate's staged
/// tree, where every file is tracked) a walk that skips `.git`, `target`, `.regia` and `.ferrite`
/// (ADR-5802). `.regia/` is a project's local cache (asset database, cook stamps, agent endpoint),
/// ignored by `.gitignore` everywhere (`**/.regia/`), so it is never a tracked file: a sample that
/// cooks into its own `.regia/` (third_person) must not add a cache file to the export's list
/// (ADR-7386). `.ferrite/` is the same cache under the engine's former name (`**/.ferrite/`); the
/// merge gate's staged tree carries a `.ferrite/test-assets/` download cache (ADR-7419).
///
/// The walk also honours the tree's `.gitignore` files (ADR-7570): tests and sample cooks write
/// untracked output into the gate's tree (`samples/*/build/paks/`, the fetched
/// `samples/third_person/assets/Fox.glb`), which a checkout's `git ls-files` never lists. A file
/// that is tracked although a `.gitignore` matches it (force-added) is not seen by the walk; the
/// unit test `ignored_tracked_files_are_not_assets` keeps every such file out of the asset list.
fn repository_files(root: &Path) -> Result<Vec<String>> {
    if !root.join(".git").exists() {
        let mut files = Vec::new();
        let mut ignores = Vec::new();
        walk_tree(root, root, &mut ignores, &mut files)?;
        return Ok(files);
    }
    let output = std::process::Command::new("git")
        .current_dir(root)
        .args(["ls-files", "-z"])
        .output()
        .context("running git ls-files")?;
    if !output.status.success() {
        anyhow::bail!(
            "git ls-files failed:\n{}",
            String::from_utf8_lossy(&output.stderr)
        );
    }
    let text = String::from_utf8(output.stdout).context("git ls-files printed invalid UTF-8")?;
    Ok(text
        .split('\0')
        .filter(|p| !p.is_empty())
        .map(str::to_string)
        .collect())
}

/// `.gitignore` reader for the walk below.
mod gitignore;

/// Walks `dir` (under `root`), skipping what `ignores` (the `.gitignore` files of `dir`'s
/// ancestors, root first) and `dir`'s own `.gitignore` ignore.
fn walk_tree(
    root: &Path,
    dir: &Path,
    ignores: &mut Vec<gitignore::IgnoreFile>,
    files: &mut Vec<String>,
) -> Result<()> {
    let rel_of = |path: &Path| {
        path.strip_prefix(root)
            .unwrap_or(path)
            .to_string_lossy()
            .replace('\\', "/")
    };
    let own = gitignore::IgnoreFile::read(dir, &rel_of(dir));
    let pushed = own.is_some();
    ignores.extend(own);
    let result = walk_entries(root, dir, ignores, files, &rel_of);
    if pushed {
        ignores.pop();
    }
    result
}

fn walk_entries(
    root: &Path,
    dir: &Path,
    ignores: &mut Vec<gitignore::IgnoreFile>,
    files: &mut Vec<String>,
    rel_of: &dyn Fn(&Path) -> String,
) -> Result<()> {
    let entries = std::fs::read_dir(dir).with_context(|| format!("reading {}", dir.display()))?;
    for entry in entries {
        let entry = entry.with_context(|| format!("reading {}", dir.display()))?;
        let kind = entry.file_type()?;
        let path = entry.path();
        let rel = rel_of(&path);
        if kind.is_dir() {
            if [".git", "target", ".regia", ".ferrite"]
                .iter()
                .any(|skip| entry.file_name() == *skip)
                || gitignore::is_ignored(ignores, &rel, true)
            {
                continue;
            }
            walk_tree(root, &path, ignores, files)?;
        } else if (kind.is_file() || kind.is_symlink()) && !gitignore::is_ignored(ignores, &rel, false) {
            files.push(rel);
        }
    }
    Ok(())
}

/// The row that covers `path`: the first row whose glob matches.
pub fn asset_row<'a>(rows: &'a [AssetRow], path: &str) -> Option<&'a AssetRow> {
    rows.iter().find(|r| glob_match(&r.path, path))
}

/// Result of checking the asset record: `problems` fail the check, `warnings` fail only `--strict`.
#[derive(Debug, Default, PartialEq, Eq)]
pub struct AssetReport {
    /// Unlisted files, incomplete rows, rows that match nothing.
    pub problems: Vec<String>,
    /// Files whose licence is `unknown`.
    pub warnings: Vec<String>,
}

/// Checks `rows` against the tracked `files`.
pub fn check_assets(rows: &[AssetRow], files: &[String]) -> AssetReport {
    let mut report = AssetReport::default();
    for row in rows {
        for (field, value) in [
            ("path", &row.path),
            ("source", &row.source),
            ("licence", &row.licence),
        ] {
            if value.trim().is_empty() {
                report.problems.push(format!("{}: `{field}` is empty", row.path));
            }
        }
        if !matches!(row.origin.as_str(), "authored" | "generated" | "third_party") {
            report.problems.push(format!(
                "{}: `origin` is `{}`; use authored, generated or third_party",
                row.path, row.origin
            ));
        }
        if !files.iter().any(|f| glob_match(&row.path, f)) {
            report
                .problems
                .push(format!("{}: matches no tracked binary file", row.path));
        }
    }
    for file in files {
        match asset_row(rows, file) {
            None => report.problems.push(format!(
                "{file}: no row in {ASSET_LICENCES} (add path, origin, source, licence, ships)"
            )),
            Some(row) if row.licence.trim() == UNKNOWN_LICENCE => {
                report
                    .warnings
                    .push(format!("{file}: licence is unknown ({})", row.path));
            }
            Some(_) => {}
        }
    }
    report
}

/// Writes `text` to `path` through a sibling temporary file and a rename, so a reader never sees half a file.
fn write_atomic(path: &Path, text: &[u8]) -> Result<()> {
    let tmp = staging_path(path);
    std::fs::write(&tmp, text).with_context(|| format!("writing {}", tmp.display()))?;
    std::fs::rename(&tmp, path).map_err(|e| {
        let _ = std::fs::remove_file(&tmp);
        anyhow::Error::new(e).context(format!("replacing {}", path.display()))
    })
}

/// The temporary sibling of `path` that `write_atomic` and `write_pair_atomic` stage into.
fn staging_path(path: &Path) -> std::path::PathBuf {
    let mut name = path.file_name().unwrap_or_default().to_os_string();
    name.push(format!(".tmp{}", std::process::id()));
    path.with_file_name(name)
}

/// Writes `text` to both `first` (`THIRD_PARTY_NOTICES.md`) and `second` (its `regia_cli` mirror), each one
/// atomically, and leaves `first` as it was when `second` cannot be written.
///
/// Both files are staged as temporary siblings before either is replaced, so a full disk or a missing
/// directory on the second one changes nothing. If the second rename still fails after the first has
/// replaced its file, the first file's old content is put back (best effort: that restore is itself an
/// atomic write, and its failure is reported with the original error).
pub fn write_pair_atomic(first: &Path, second: &Path, text: &str) -> Result<()> {
    let (tmp_first, tmp_second) = (staging_path(first), staging_path(second));
    let cleanup = || {
        let _ = std::fs::remove_file(&tmp_first);
        let _ = std::fs::remove_file(&tmp_second);
    };
    for (tmp, name) in [(&tmp_first, first), (&tmp_second, second)] {
        if let Err(e) = std::fs::write(tmp, text) {
            cleanup();
            return Err(anyhow::Error::new(e).context(format!("writing {}", name.display())));
        }
    }
    let old_first = std::fs::read(first).ok();
    if let Err(e) = std::fs::rename(&tmp_first, first) {
        cleanup();
        return Err(anyhow::Error::new(e).context(format!("replacing {}", first.display())));
    }
    if let Err(e) = std::fs::rename(&tmp_second, second) {
        cleanup();
        let restored = match &old_first {
            Some(old) => write_atomic(first, old),
            None => std::fs::remove_file(first).context("removing the new first file"),
        };
        let mut err = anyhow::Error::new(e).context(format!("replacing {}", second.display()));
        if let Err(r) = restored {
            err = err.context(format!("{} could not be restored: {r:#}", first.display()));
        }
        return Err(err);
    }
    Ok(())
}

/// The "Ported source code" section as text (the demo notices reuse it for the sources in their tree).
pub fn render_ported_section(ported: &[PortedSource]) -> String {
    let mut out = String::new();
    render_ported(&mut out, ported);
    out
}

/// Appends the "Ported source code" section.
fn render_ported(out: &mut String, ported: &[PortedSource]) {
    out.push_str("\n## Ported source code\n\n");
    let _ = write!(
        out,
        "Source files ported from permissively licensed projects, from `{PORTED_SOURCES}`. Each ported\n\
         file keeps the original copyright and licence notice in its header.\n\n"
    );
    if ported.is_empty() {
        out.push_str("No source files have been ported.\n");
        return;
    }
    let mut sorted: Vec<&PortedSource> = ported.iter().collect();
    sorted.sort_by(|a, b| (&a.project, &a.commit).cmp(&(&b.project, &b.commit)));
    for s in &sorted {
        let _ = writeln!(out, "### {} ({})\n", s.project, s.commit);
        let _ = writeln!(out, "- Source: {} at commit `{}`", s.url, s.commit);
        let _ = writeln!(out, "- Licence: {}", s.licence);
        let _ = writeln!(out, "- {}", s.copyright);
        out.push_str("- Files:\n");
        for from in &s.files_from {
            let _ = writeln!(out, "  - from `{from}`");
        }
        for to in &s.files_to {
            let _ = writeln!(out, "  - into `{to}`");
        }
        out.push('\n');
    }
    if sorted
        .iter()
        .any(|s| licence_ids(&s.licence).any(|id| id == "MIT"))
    {
        out.push_str(
            "### MIT licence\n\n\
             Applies to the MIT-licensed entries above (and to `MIT OR …` entries, used under MIT), with\n\
             each entry's copyright notice:\n\n",
        );
        for line in MIT_TEXT.lines() {
            if line.is_empty() {
                out.push_str(">\n");
            } else {
                let _ = writeln!(out, "> {line}");
            }
        }
        out.push('\n');
    }
    let others: BTreeSet<&str> = sorted
        .iter()
        .filter(|s| !licence_ids(&s.licence).any(|id| id == "MIT"))
        .flat_map(|s| licence_ids(&s.licence))
        .collect();
    for id in others {
        let _ = writeln!(
            out,
            "Licence text of {id}: https://spdx.org/licenses/{id}.html (also kept in the ported files' headers).\n"
        );
    }
}

