/// covered by one of these, or `cargo xtask notices --check` fails.
#[derive(Debug, Clone, PartialEq, Eq, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct AssetNotice {
    /// Display name, e.g. `JetBrains Mono`.
    pub name: String,
    /// SPDX identifier the files are used under, e.g. `OFL-1.1`.
    pub licence: String,
    /// Repository-relative paths or globs of the files this entry covers.
    pub files: Vec<String>,
    /// The licence file that ships beside the files; the notices copy its `Copyright` lines, after
    /// each covered font's own copyright record, which the licence file must also carry (ADR-10066).
    #[serde(default)]
    pub licence_file: Option<String>,
    /// Instead of a licence file: the `project` of the `docs/ported-sources.toml` entry that
    /// already carries the copyright and licence (the files were ported with that source).
    #[serde(default)]
    pub ported: Option<String>,
}

