//! Soak input scripts: a small RON timeline of press/hold/look patterns, expanded into timed
//! `play.inject_input` calls (`specs/23` § 3.5).
//!
//! File format (all times in seconds, cursor positions in logical window pixels):
//!
//! ```ron
//! (
//!     // Restart the timeline from the beginning after its last step, until the soak ends.
//!     loop: true,
//!     steps: [
//!         // Tap a key (pressed now, released 50 ms later).
//!         (at: 0.0, action: Press(key: "KeyW")),
//!         // Hold a key from `at` to `until`.
//!         (at: 1.0, action: Hold(key: "KeyS", until: 2.5)),
//!         // Drag the cursor from `from` by `delta` over `for_secs` (~30 Hz moves).
//!         (at: 3.0, action: Look(from: (400.0, 300.0), delta: (120.0, 40.0), for_secs: 0.5)),
//!         // Raw protocol events at `at` (same schema as `play.inject_input`).
//!         (at: 4.0, action: Raw([(type: "wheel", dy: -1.0)])),
//!     ],
//! )
//! ```

use anyhow::{Result, bail};
use serde::Deserialize;
use serde_json::{Value, json};

/// How long a `Press` keeps the key down before the release is injected.
const PRESS_SECS: f64 = 0.05;
/// Cursor moves per second generated by a `Look`.
const LOOK_HZ: f64 = 30.0;

/// A parsed input script (see the module docs for the file format).
#[derive(Debug, Clone, Deserialize)]
pub struct InputScript {
    /// Restart the timeline from the beginning after its last step, until the soak ends.
    #[serde(default)]
    pub r#loop: bool,
    /// Timeline steps; they may appear in any order and are expanded in time order.
    pub steps: Vec<Step>,
}

/// One timed action.
#[derive(Debug, Clone, Deserialize)]
pub struct Step {
    /// Offset into the timeline when the action starts.
    pub at: f64,
    /// What to inject.
    pub action: Action,
}

/// The supported patterns.
#[derive(Debug, Clone, Deserialize)]
pub enum Action {
    /// Tap a key: pressed at `at`, released `PRESS_SECS` later. `key` is a physical key name
    /// (`"KeyW"`, `"Space"`, `"F1"`, ...), matching the app's input config.
    Press {
        /// Physical key name.
        key: String,
    },
    /// Hold a key: pressed at `at`, released at `until` (which must be later than `at`).
    Hold {
        /// Physical key name.
        key: String,
        /// Release time on the timeline.
        until: f64,
    },
    /// Drag the cursor from `from` by `delta` over `for_secs` at ~30 Hz.
    Look {
        /// Start position `[x, y]`.
        from: [f64; 2],
        /// Total move `[dx, dy]`.
        delta: [f64; 2],
        /// Drag duration; `0` jumps straight to the destination.
        for_secs: f64,
    },
    /// Raw `play.inject_input` events injected at `at`.
    Raw(
        /// Event objects (`type`, and the fields that type needs).
        Vec<Value>,
    ),
}

/// One timed action, expanded: `events` go out once the session has run for `at` seconds (the
/// runner delivers each entry on the sampling tick that contains `at`).
#[derive(Debug, Clone, PartialEq)]
pub struct Scheduled {
    /// Seconds into the session.
    pub at: f64,
    /// Raw event objects for `play.inject_input`.
    pub events: Vec<Value>,
}

/// Expands `script` over a session of `duration_secs` into a time-sorted schedule of
/// `play.inject_input` calls. Entries at the same time are coalesced into one call.
pub fn expand(script: &InputScript, duration_secs: f64) -> Result<Vec<Scheduled>> {
    if !duration_secs.is_finite() || duration_secs < 0.0 {
        bail!("soak duration must be a finite number of seconds, got {duration_secs}");
    }
    validate(script)?;
    let timeline_len = script
        .steps
        .iter()
        .map(|s| match &s.action {
            Action::Press { .. } => s.at + PRESS_SECS,
            Action::Hold { until, .. } => *until,
            Action::Look { for_secs, .. } => s.at + *for_secs,
            Action::Raw(_) => s.at,
        })
        .fold(0.0_f64, f64::max);
    let mut out = Vec::new();
    if script.steps.is_empty() {
        return Ok(out);
    }
    // A looping timeline must advance, or repetitions never end (all-zero steps).
    let looping = script.r#loop && timeline_len > 0.0;
    let mut rep_start = 0.0;
    while rep_start < duration_secs {
        for step in &script.steps {
            let at = rep_start + step.at;
            match &step.action {
                Action::Press { key } => {
                    push(&mut out, at, key_event(key, "pressed"));
                    push(&mut out, at + PRESS_SECS, key_event(key, "released"));
                }
                Action::Hold { key, until } => {
                    push(&mut out, at, key_event(key, "pressed"));
                    push(&mut out, rep_start + *until, key_event(key, "released"));
                }
                Action::Look {
                    from,
                    delta,
                    for_secs,
                } => {
                    let points = if *for_secs <= 0.0 {
                        1
                    } else {
                        ((*for_secs * LOOK_HZ).ceil() as usize).max(2)
                    };
                    for i in 0..points {
                        let t = if points == 1 || *for_secs <= 0.0 {
                            at
                        } else {
                            at + for_secs * (i as f64) / ((points - 1) as f64)
                        };
                        let frac = if points == 1 || *for_secs <= 0.0 {
                            1.0
                        } else {
                            i as f64 / (points - 1) as f64
                        };
                        let (x, y) = (from[0] + delta[0] * frac, from[1] + delta[1] * frac);
                        push(&mut out, t, vec![json!({ "type": "cursor", "x": x, "y": y })]);
                    }
                }
                Action::Raw(events) => {
                    push(&mut out, at, events.clone());
                }
            }
        }
        if !looping {
            break;
        }
        rep_start += timeline_len;
    }
    out.retain(|s| s.at < duration_secs);
    out.sort_by(|a, b| a.at.partial_cmp(&b.at).unwrap_or(std::cmp::Ordering::Equal));
    Ok(coalesce(out))
}

/// Validates the times in a script; `expand` calls this before scheduling.
fn validate(script: &InputScript) -> Result<()> {
    for (i, step) in script.steps.iter().enumerate() {
        if !step.at.is_finite() || step.at < 0.0 {
            bail!("step {i}: `at` must be a finite time >= 0, got {}", step.at);
        }
        match &step.action {
            Action::Press { key } if key.is_empty() => {
                bail!("step {i}: Press needs a key name");
            }
            // A `Press` with a non-empty key is fine (and makes the match exhaustive).
            Action::Press { .. } => {}
            Action::Hold { key, until } => {
                if key.is_empty() {
                    bail!("step {i}: Hold needs a key name");
                }
                if !until.is_finite() || *until <= step.at {
                    bail!(
                        "step {i}: Hold `until` ({until}) must be later than `at` ({})",
                        step.at
                    );
                }
            }
            Action::Look {
                from,
                delta,
                for_secs,
            } => {
                let finite = from.iter().chain(delta).all(|v| v.is_finite());
                if !finite || !for_secs.is_finite() || *for_secs < 0.0 {
                    bail!("step {i}: Look needs finite positions and `for_secs` >= 0");
                }
            }
            Action::Raw(_) => {}
        }
    }
    Ok(())
}

fn key_event(key: &str, state: &str) -> Vec<Value> {
    vec![json!({ "type": "key", "key": key, "state": state })]
}

fn push(out: &mut Vec<Scheduled>, at: f64, events: Vec<Value>) {
    out.push(Scheduled { at, events });
}

/// Merges entries with the same time into one call (fewer protocol round trips).
fn coalesce(mut sorted: Vec<Scheduled>) -> Vec<Scheduled> {
    let mut out: Vec<Scheduled> = Vec::with_capacity(sorted.len());
    for entry in sorted.drain(..) {
        match out.last_mut() {
            Some(last) if last.at == entry.at => last.events.extend(entry.events),
            _ => out.push(entry),
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    fn parse(text: &str) -> InputScript {
        ron::from_str(text).expect("script parses")
    }

    #[test]
    fn parses_the_documented_format() {
        let script = parse(
            r#"(
                loop: true,
                steps: [
                    (at: 0.0, action: Press(key: "KeyW")),
                    (at: 1.0, action: Hold(key: "KeyS", until: 2.5)),
                    (at: 3.0, action: Look(from: (400.0, 300.0), delta: (120.0, 40.0), for_secs: 0.5)),
                    (at: 4.0, action: Raw([(type: "wheel", dy: -1.0)])),
                ],
            )"#,
        );
        assert!(script.r#loop);
        assert_eq!(script.steps.len(), 4);
    }

    #[test]
    fn press_releases_after_the_gap() {
        let script = parse("(steps: [(at: 2.0, action: Press(key: \"KeyW\"))])");
        let schedule = expand(&script, 10.0).expect("expands");
        assert_eq!(schedule.len(), 2);
        assert_eq!(schedule[0].at, 2.0);
        assert_eq!(schedule[0].events[0]["state"], "pressed");
        assert_eq!(schedule[1].at, 2.0 + PRESS_SECS);
        assert_eq!(schedule[1].events[0]["state"], "released");
    }

    #[test]
    fn hold_spans_until() {
        let script = parse("(steps: [(at: 1.0, action: Hold(key: \"KeyS\", until: 2.5))])");
        let schedule = expand(&script, 10.0).expect("expands");
        assert_eq!(schedule[0].at, 1.0);
        assert_eq!(schedule[1].at, 2.5);
        assert_eq!(schedule[1].events[0]["state"], "released");
    }

    #[test]
    fn look_moves_monotonically_to_the_destination() {
        let script = parse(
            "(steps: [(at: 3.0, action: Look(from: (400.0, 300.0), delta: (120.0, 40.0), for_secs: 0.5))])",
        );
        let schedule = expand(&script, 10.0).expect("expands");
        // 0.5 s at 30 Hz → at least 15 moves.
        assert!(schedule.len() >= 15, "got {} moves", schedule.len());
        let first = &schedule[0];
        assert_eq!(first.events[0]["x"], json!(400.0));
        let last = schedule.last().expect("non-empty");
        assert_eq!(last.events[0]["x"], json!(520.0));
        assert_eq!(last.events[0]["y"], json!(340.0));
        let mut prev = first.at;
        for entry in &schedule {
            assert!(entry.at >= prev, "times must not go backwards");
            prev = entry.at;
        }
    }

    #[test]
    fn look_with_zero_duration_jumps() {
        let script =
            parse("(steps: [(at: 1.0, action: Look(from: (0.0, 0.0), delta: (50.0, 50.0), for_secs: 0.0))])");
        let schedule = expand(&script, 10.0).expect("expands");
        assert_eq!(schedule.len(), 1);
        assert_eq!(schedule[0].events[0]["x"], json!(50.0));
    }

    #[test]
    fn raw_events_pass_through_at_their_time() {
        let script = parse("(steps: [(at: 4.0, action: Raw([(type: \"wheel\", dy: -1.0)]))])");
        let schedule = expand(&script, 10.0).expect("expands");
        assert_eq!(schedule.len(), 1);
        assert_eq!(schedule[0].events[0]["type"], "wheel");
        assert_eq!(schedule[0].events[0]["dy"], json!(-1.0));
    }

    #[test]
    fn looping_repeats_the_timeline_until_the_duration() {
        let script = parse("(loop: true, steps: [(at: 0.5, action: Press(key: \"KeyA\"))])");
        // Timeline length: the press ends at 0.55, so repeats start at 0, 0.55, 1.10 ...
        let schedule = expand(&script, 1.5).expect("expands");
        let times: Vec<f64> = schedule.iter().map(|s| s.at).collect();
        assert_eq!(
            times.len(),
            4,
            "press/release at 0.5/0.55 and 1.05/1.10; {times:?}"
        );
        let presses: Vec<f64> = schedule
            .iter()
            .filter(|s| s.events[0]["state"] == "pressed")
            .map(|s| s.at)
            .collect();
        assert_eq!(presses.len(), 2);
        assert!((presses[0] - 0.5).abs() < 1e-9);
        assert!((presses[1] - 1.05).abs() < 1e-9);
    }

    #[test]
    fn entries_beyond_the_duration_are_dropped() {
        let script = parse("(steps: [(at: 9.9, action: Press(key: \"KeyA\"))])");
        let schedule = expand(&script, 1.0).expect("expands");
        assert!(schedule.is_empty());
    }

    #[test]
    fn events_at_the_same_time_share_one_call() {
        let script = parse(
            "(steps: [(at: 1.0, action: Raw([(type: \"wheel\", dy: -1.0)])), \
             (at: 1.0, action: Raw([(type: \"wheel\", dy: 1.0)]))])",
        );
        let schedule = expand(&script, 10.0).expect("expands");
        assert_eq!(schedule.len(), 1, "same-time entries coalesce");
        assert_eq!(schedule[0].events.len(), 2);
    }

    #[test]
    fn hold_ending_before_its_start_is_rejected() {
        let script = parse("(steps: [(at: 2.0, action: Hold(key: \"KeyS\", until: 1.0))])");
        assert!(expand(&script, 10.0).is_err());
    }

    #[test]
    fn negative_start_is_rejected() {
        let script = parse("(steps: [(at: -1.0, action: Press(key: \"KeyA\"))])");
        assert!(expand(&script, 10.0).is_err());
    }

    #[test]
    fn empty_script_yields_an_empty_schedule() {
        let script = parse("(steps: [])");
        assert!(expand(&script, 10.0).expect("expands").is_empty());
    }
}
