//! Extensions (`specs/57`): manifest, resolver, discovery, the registry, `ExtensionContext`, the
//! ABI stamp of dynamic extensions, content mounts, feature packs and out-of-process tools.
//!
//! [`manifest`] parses and checks `regia-plugin.toml`; [`resolver`] turns discovered manifests
//! plus the project's enable lists into an ordered, hashed set with lowercase diagnostic codes
//! (both pure). [`project`] reads and edits the `[extensions]` table of `Regia.toml`;
//! [`discover`] scans the discovery roots. [`registry`] holds the resolved set and every
//! registration and builds the linked extensions through [`context::ExtensionContext`].
//! [`cooked`] is the resolved set a cook records next to the paks.
//! [`stamp`] is the fixed-layout record a dynamic extension exports (the editor's loader reads it
//! before any other symbol). [`tool`] runs `[[tool]]` helpers as child processes.
//!
//! In-process extension code is fully trusted native code. Capabilities are a declaration and
//! review aid, not a sandbox (spec § 2.7).

