/// Exports an extension type for static linking: `pub fn regia_extension()` returning it boxed and
/// `REGIA_EXTENSION_MANIFEST` holding the manifest text, for the generated `register_extensions!`
/// list. Under the extension crate's own
/// `dynamic-extension` feature it also exports the C symbols a dynamic load resolves:
/// `regia_extension_stamp` (the [`stamp::ExtensionStamp`] of this build, a `static` of the library;
/// the editor reads it before anything else), `REGIA_ABI_HASH`, and `regia_extension_entry` (a
/// boxed `Box<dyn RegiaExtension>` behind a thin pointer; a panic in the constructor is caught and
/// returns null).
///
/// `$manifest` is the manifest path relative to the crate root (default `regia-plugin.toml`); its
/// bytes are embedded so the stamp carries their hash.
#[macro_export]
macro_rules! extension {
    ($ty:ty) => {
        $crate::extension!($ty, "regia-plugin.toml");
    };
    ($ty:ty, $manifest:literal) => {
        /// This crate's extension, boxed (generated by `regia::extension!`).
        pub fn regia_extension() -> ::std::boxed::Box<dyn $crate::extension::RegiaExtension> {
            ::std::boxed::Box::new(<$ty as ::std::default::Default>::default())
        }

        /// This crate's manifest, for a packaged game with no manifest on disk (generated by
        /// `regia::extension!`).
        pub const REGIA_EXTENSION_MANIFEST: &str =
            include_str!(concat!(env!("CARGO_MANIFEST_DIR"), "/", $manifest));

        #[cfg(feature = "dynamic-extension")]
        #[doc(hidden)]
        pub mod __regia_extension_exports {
            const MANIFEST: &[u8] = include_bytes!(concat!(env!("CARGO_MANIFEST_DIR"), "/", $manifest));

            /// The stamp as an exported data symbol, so the host reads it from the file before the
            /// dynamic loader runs (`specs/57` § 2.8, ADR-2844).
            #[allow(unsafe_code)]
            // SAFETY: the name is the host's lookup key (`specs/57` § 2.8), so it stays unmangled. It
            // belongs to no system library, and a second definition in one library is a link error.
            #[unsafe(no_mangle)]
            #[used]
            pub static REGIA_EXTENSION_STAMP: $crate::extension::stamp::ExtensionStamp =
                $crate::extension::stamp::ExtensionStamp::for_build(
                    $crate::game::abi_hash_from(::core::option_env!("REGIA_ABI_HASH")),
                    $crate::extension::stamp::parse_u64(::core::option_env!("REGIA_ENGINE_FINGERPRINT")),
                    $crate::extension::stamp::manifest_hash(MANIFEST),
                );

            /// The address of [`REGIA_EXTENSION_STAMP`] (`specs/57` § 2.8).
            #[allow(unsafe_code)]
            // SAFETY: as for `REGIA_EXTENSION_STAMP`.
            #[unsafe(no_mangle)]
            pub extern "C" fn regia_extension_stamp() -> *const $crate::extension::stamp::ExtensionStamp {
                &REGIA_EXTENSION_STAMP
            }

            /// The extension as a thin pointer to a `Box<dyn RegiaExtension>`; null after a panic.
            #[allow(unsafe_code)]
            // SAFETY: as for `regia_extension_stamp`; a panic is caught here and never crosses the
            // `extern "C"` boundary.
            #[unsafe(no_mangle)]
            pub extern "C" fn regia_extension_entry() -> *mut ::std::ffi::c_void {
                match ::std::panic::catch_unwind(super::regia_extension) {
                    Ok(ext) => ::std::boxed::Box::into_raw(::std::boxed::Box::new(ext)).cast(),
                    Err(_) => ::std::ptr::null_mut(),
                }
            }

            /// The hot-reload ABI hash (`specs/20` § 2), also checked for extensions.
            #[allow(unsafe_code)]
            // SAFETY: as for `regia_extension_stamp`; the host reads it as a `u64`, which it is.
            #[unsafe(no_mangle)]
            #[used]
            pub static REGIA_ABI_HASH: u64 =
                $crate::game::abi_hash_from(::core::option_env!("REGIA_ABI_HASH"));
        }
    };
}

/// The generated list of statically linked extensions (`extensions_generated.rs`, written by
/// `regia plugin sync`). `register_extensions![dialogue, cheats]` expands to a
/// `fn linked_extensions() -> Vec<Arc<dyn RegiaExtension>>` calling each crate's
/// `regia_extension()`, and a `fn linked_extension_set() -> LinkedExtensions`. The form `regia
/// plugin sync` writes also embeds what a packaged game cannot read from disk: `config` is the
/// `[extensions]` table and `manifests` the manifest text of every resolved extension this list
/// does not link (content-only, editor-only).
#[macro_export]
macro_rules! register_extensions {
    (config = $config:expr, manifests = [$($manifest:expr),* $(,)?], crates = [$($krate:ident),* $(,)?] $(,)?) => {
        /// The statically linked extensions (generated by `regia plugin sync`).
        #[must_use]
        pub fn linked_extensions() -> ::std::vec::Vec<::std::sync::Arc<dyn $crate::extension::RegiaExtension>> {
            ::std::vec![$(::std::sync::Arc::from($krate::regia_extension())),*]
        }

        /// The linked extensions with their manifests, for `ExtensionPlugin::for_game` (generated
        /// by `regia plugin sync`).
        #[must_use]
        pub fn linked_extension_set() -> $crate::extension::LinkedExtensions {
            $crate::extension::LinkedExtensions {
                extensions: linked_extensions(),
                manifests: ::std::vec![$($krate::REGIA_EXTENSION_MANIFEST,)* $($manifest,)*],
                config: $config,
            }
        }
    };
    ($($krate:ident),* $(,)?) => {
        $crate::register_extensions!(config = "", manifests = [], crates = [$($krate),*]);
    };
}
