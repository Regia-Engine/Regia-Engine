//! [`TriBvh`]: a binary tree of axis-aligned boxes over a mesh's triangles.
//!
//! Changes from the upstream tree: one node array (children stored next to each other, leaves
//! point into a triangle order array) instead of the packed index list; the split axis is the
//! longest axis of the triangle centroids' box instead of `depth % 3`; every traversal uses an
//! explicit stack instead of recursion; tree/tree descent picks the larger box instead of
//! alternating by depth; and the triangle tests are the ones in [`super::triangle`].

use glam::{Affine3A, DVec3, Vec3};
use smallvec::SmallVec;

use super::triangle::{closest_point_d, overlaps_aabb_d, ray_hit_d, triangles_intersect_d};
use super::{MeshQueryError, TriMesh};
use crate::math::{Aabb, Ray, Sphere};

/// At most this many triangles in a leaf (the upstream default).
const LEAF_SIZE: usize = 4;

/// Traversal stack with room for a tree this deep before it spills to the heap.
type Stack<T> = SmallVec<[T; 64]>;

/// One tree node: a leaf holds `count > 0` triangles at `order[first..first + count]`; an internal
/// node (`count == 0`) has its two children at `first` and `first + 1`.
#[derive(Debug, Clone, Copy)]
pub(crate) struct Node {
    pub(crate) bounds: Aabb,
    pub(crate) first: u32,
    pub(crate) count: u32,
}

impl Node {
    pub(crate) fn is_leaf(&self) -> bool {
        self.count > 0
    }
}

/// The nearest ray hit found by [`TriBvh::ray_cast`].
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct RayHit {
    /// Index of the triangle hit.
    pub triangle: u32,
    /// Distance along the ray (the ray direction is unit length).
    pub distance: f32,
    /// The hit point.
    pub point: Vec3,
    /// Barycentric coordinates of the hit on the triangle's corners `(a, b, c)`.
    pub barycentric: Vec3,
}

/// The closest mesh point found by [`TriBvh::closest_point`].
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct ClosestPoint {
    /// Index of the triangle the point lies on.
    pub triangle: u32,
    /// The closest point.
    pub point: Vec3,
    /// Distance from the query point.
    pub distance: f32,
    /// Barycentric coordinates of the point on the triangle's corners `(a, b, c)`.
    pub barycentric: Vec3,
}

/// Work a counted query did ([`TriBvh::ray_cast_counted`], [`TriBvh::closest_point_counted`]):
/// tree nodes whose box was tested and triangles tested. Counts add up over calls, so one value
/// can total a whole bake. Deterministic for the same tree and queries (no clock).
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct QueryCounts {
    /// Node boxes tested against the query.
    pub nodes: u64,
    /// Triangles tested against the query.
    pub triangles: u64,
}

impl QueryCounts {
    /// The sum of two counts.
    #[must_use]
    pub fn plus(self, other: Self) -> Self {
        Self {
            nodes: self.nodes + other.nodes,
            triangles: self.triangles + other.triangles,
        }
    }
}

/// A bounding-box tree over the triangles of a [`TriMesh`] (which it owns). Built once; the mesh
/// cannot change afterwards (rebuild instead).
#[derive(Debug, Clone)]
pub struct TriBvh {
    mesh: TriMesh,
    nodes: Vec<Node>,
    order: Vec<u32>,
}

/// Squared distance from `p` to the box (0 inside).
fn box_distance_squared(b: &Aabb, p: DVec3) -> f64 {
    let lo = b.min.as_dvec3() - p;
    let hi = p - b.max.as_dvec3();
    lo.max(hi).max(DVec3::ZERO).length_squared()
}

/// Entry distance of the ray into the box (0 when the origin is inside), or `None` on a miss.
fn box_ray_entry(b: &Aabb, o: DVec3, d: DVec3, max_t: f64) -> Option<f64> {
    let (lo, hi) = (b.min.as_dvec3(), b.max.as_dvec3());
    let mut t0 = 0.0_f64;
    let mut t1 = max_t;
    for axis in 0..3 {
        if d[axis] == 0.0 {
            if o[axis] < lo[axis] || o[axis] > hi[axis] {
                return None;
            }
            continue;
        }
        let inv = 1.0 / d[axis];
        let (a, b) = ((lo[axis] - o[axis]) * inv, (hi[axis] - o[axis]) * inv);
        t0 = t0.max(a.min(b));
        t1 = t1.min(a.max(b));
        if t1 < t0 {
            return None;
        }
    }
    Some(t0)
}

impl TriBvh {
    /// Builds the tree. Fails with [`MeshQueryError::EmptyMesh`] for a mesh without triangles.
    pub fn build(mesh: TriMesh) -> Result<Self, MeshQueryError> {
        let _span = tracing::debug_span!("tri_bvh_build", triangles = mesh.triangle_count()).entered();
        if mesh.is_empty() {
            return Err(MeshQueryError::EmptyMesh);
        }
        let n = mesh.triangle_count();
        let mut centroids = Vec::with_capacity(n);
        let mut tri_bounds = Vec::with_capacity(n);
        for t in 0..n as u32 {
            let [a, b, c] = mesh.triangle(t);
            centroids.push((a + b + c) / 3.0);
            tri_bounds.push(Aabb::new(a.min(b).min(c), a.max(b).max(c)));
        }
        let mut order: Vec<u32> = (0..n as u32).collect();
        let unset = Node {
            bounds: Aabb::EMPTY,
            first: 0,
            count: 0,
        };
        let mut nodes = vec![unset];
        let mut work = vec![(0usize, 0usize, n)];
        while let Some((node, start, end)) = work.pop() {
            let count = end - start;
            if count <= LEAF_SIZE {
                nodes[node].first = start as u32;
                nodes[node].count = count as u32;
                continue;
            }
            let slice = &mut order[start..end];
            let mut cb = Aabb::EMPTY;
            for &t in slice.iter() {
                cb.extend(centroids[t as usize]);
            }
            let size = cb.size();
            let axis = if size.x >= size.y && size.x >= size.z {
                0
            } else if size.y >= size.z {
                1
            } else {
                2
            };
            // Midpoint split on the longest axis; half and half when the centroids coincide on
            // it or every centroid falls on one side.
            let mut left = 0;
            if size[axis] > 0.0 {
                let split = cb.center()[axis];
                let mut i = 0;
                while i < slice.len() {
                    if centroids[slice[i] as usize][axis] <= split {
                        slice.swap(i, left);
                        left += 1;
                    }
                    i += 1;
                }
            }
            if left == 0 || left == count {
                left = count / 2;
            }
            let child = nodes.len();
            nodes.push(unset);
            nodes.push(unset);
            nodes[node].first = child as u32;
            work.push((child, start, start + left));
            work.push((child + 1, start + left, end));
        }
        // Children always come after their parent, so a reverse sweep sets boxes bottom-up.
        for i in (0..nodes.len()).rev() {
            let node = nodes[i];
            let first = node.first as usize;
            nodes[i].bounds = if node.is_leaf() {
                order[first..first + node.count as usize]
                    .iter()
                    .fold(Aabb::EMPTY, |b, &t| b.union(&tri_bounds[t as usize]))
            } else {
                nodes[first].bounds.union(&nodes[first + 1].bounds)
            };
        }
        Ok(Self { mesh, nodes, order })
    }

    /// The mesh the tree was built over.
    pub fn mesh(&self) -> &TriMesh {
        &self.mesh
    }

    /// Gives the mesh back.
    pub fn into_mesh(self) -> TriMesh {
        self.mesh
    }

    /// The box around every triangle.
    pub fn bounds(&self) -> Aabb {
        self.nodes[0].bounds
    }

    /// Number of tree nodes (a measure of tree size; about `triangles / 2`).
    pub fn node_count(&self) -> usize {
        self.nodes.len()
    }

    pub(crate) fn nodes(&self) -> &[Node] {
        &self.nodes
    }

    pub(crate) fn leaf_triangles(&self, node: &Node) -> &[u32] {
        let first = node.first as usize;
        &self.order[first..first + node.count as usize]
    }

    fn tri_d(&self, t: u32) -> [DVec3; 3] {
        self.mesh.triangle(t).map(Vec3::as_dvec3)
    }

    /// The nearest triangle hit by `ray` no farther than `max_distance` (use `f32::INFINITY` for no
    /// limit). Both faces of a triangle count; degenerate triangles are never hit. A ray with a
    /// zero direction hits nothing.
    pub fn ray_cast(&self, ray: &Ray, max_distance: f32) -> Option<RayHit> {
        self.ray_cast_counted(ray, max_distance, &mut QueryCounts::default())
    }

    /// As [`TriBvh::ray_cast`], adding the nodes and triangles it tested to `counts`.
    pub fn ray_cast_counted(&self, ray: &Ray, max_distance: f32, counts: &mut QueryCounts) -> Option<RayHit> {
        if ray.direction == Vec3::ZERO || !ray.origin.is_finite() || !ray.direction.is_finite() {
            return None;
        }
        let o = ray.origin.as_dvec3();
        let d = ray.direction.as_dvec3();
        if max_distance.is_nan() {
            return None;
        }
        let mut best_t = f64::from(max_distance);
        let mut best: Option<(u32, f64, f64, f64)> = None;
        let mut stack: Stack<(u32, f64)> = SmallVec::new();
        counts.nodes += 1;
        if let Some(t) = box_ray_entry(&self.nodes[0].bounds, o, d, best_t) {
            stack.push((0, t));
        }
        while let Some((ni, entry)) = stack.pop() {
            if entry > best_t {
                continue;
            }
            let node = self.nodes[ni as usize];
            if node.is_leaf() {
                counts.triangles += u64::from(node.count);
                for &t in self.leaf_triangles(&node) {
                    let [a, b, c] = self.tri_d(t);
                    if let Some((dist, v, w)) = ray_hit_d(o, d, a, b, c)
                        && (dist < best_t || (best.is_none() && dist <= best_t))
                    {
                        best_t = dist;
                        best = Some((t, dist, v, w));
                    }
                }
                continue;
            }
            let c0 = node.first;
            let c1 = c0 + 1;
            counts.nodes += 2;
            let t0 = box_ray_entry(&self.nodes[c0 as usize].bounds, o, d, best_t);
            let t1 = box_ray_entry(&self.nodes[c1 as usize].bounds, o, d, best_t);
            // Push the farther child first so the nearer one is searched first.
            match (t0, t1) {
                (Some(a), Some(b)) if a <= b => {
                    stack.push((c1, b));
                    stack.push((c0, a));
                }
                (Some(a), Some(b)) => {
                    stack.push((c0, a));
                    stack.push((c1, b));
                }
                (Some(a), None) => stack.push((c0, a)),
                (None, Some(b)) => stack.push((c1, b)),
                (None, None) => {}
            }
        }
        best.map(|(t, dist, v, w)| RayHit {
            triangle: t,
            distance: dist as f32,
            point: (o + d * dist).as_vec3(),
            barycentric: Vec3::new((1.0 - v - w) as f32, v as f32, w as f32),
        })
    }

    /// The closest point on the mesh to `point`, if one lies within `max_distance` (use
    /// `f32::INFINITY` for no limit; then the result is `None` only for a non-finite `point`).
    pub fn closest_point(&self, point: Vec3, max_distance: f32) -> Option<ClosestPoint> {
        self.closest_point_counted(point, max_distance, &mut QueryCounts::default())
    }

    /// As [`TriBvh::closest_point`], adding the nodes and triangles it tested to `counts`.
    pub fn closest_point_counted(
        &self,
        point: Vec3,
        max_distance: f32,
        counts: &mut QueryCounts,
    ) -> Option<ClosestPoint> {
        if !point.is_finite() || max_distance.is_nan() || max_distance < 0.0 {
            return None;
        }
        let p = point.as_dvec3();
        let max = f64::from(max_distance);
        let mut best_d2 = max * max;
        let mut best: Option<(u32, DVec3, DVec3)> = None;
        let mut stack: Stack<(u32, f64)> = SmallVec::new();
        counts.nodes += 1;
        stack.push((0, box_distance_squared(&self.nodes[0].bounds, p)));
        while let Some((ni, d2)) = stack.pop() {
            if d2 > best_d2 {
                continue;
            }
            let node = self.nodes[ni as usize];
            if node.is_leaf() {
                counts.triangles += u64::from(node.count);
                for &t in self.leaf_triangles(&node) {
                    let [a, b, c] = self.tri_d(t);
                    let (q, bary) = closest_point_d(p, a, b, c);
                    let dd = q.distance_squared(p);
                    if dd < best_d2 || (best.is_none() && dd <= best_d2) {
                        best_d2 = dd;
                        best = Some((t, q, bary));
                    }
                }
                continue;
            }
            let c0 = node.first;
            let c1 = c0 + 1;
            counts.nodes += 2;
            let d0 = box_distance_squared(&self.nodes[c0 as usize].bounds, p);
            let d1 = box_distance_squared(&self.nodes[c1 as usize].bounds, p);
            let (near, far) = if d0 <= d1 {
                ((c0, d0), (c1, d1))
            } else {
                ((c1, d1), (c0, d0))
            };
            if far.1 <= best_d2 {
                stack.push(far);
            }
            if near.1 <= best_d2 {
                stack.push(near);
            }
        }
        best.map(|(t, q, bary)| ClosestPoint {
            triangle: t,
            point: q.as_vec3(),
            distance: q.distance(p) as f32,
            barycentric: bary.as_vec3(),
        })
    }

    /// Every triangle that overlaps `aabb` (touching counts; exact triangle/box test), in
    /// ascending index order.
    pub fn triangles_in_aabb(&self, aabb: &Aabb) -> Vec<u32> {
        let mut out = Vec::new();
        if aabb.is_empty() {
            return out;
        }
        let (min, max) = (aabb.min.as_dvec3(), aabb.max.as_dvec3());
        let mut stack: Stack<u32> = SmallVec::new();
        stack.push(0);
        while let Some(ni) = stack.pop() {
            let node = self.nodes[ni as usize];
            if !node.bounds.intersects(aabb) {
                continue;
            }
            if node.is_leaf() {
                for &t in self.leaf_triangles(&node) {
                    if overlaps_aabb_d(self.tri_d(t), min, max) {
                        out.push(t);
                    }
                }
            } else {
                stack.push(node.first + 1);
                stack.push(node.first);
            }
        }
        out.sort_unstable();
        out
    }

    /// Every triangle with a point within `sphere` (on the surface counts), in ascending index
    /// order.
    pub fn triangles_in_sphere(&self, sphere: &Sphere) -> Vec<u32> {
        let mut out = Vec::new();
        if !sphere.center.is_finite() || sphere.radius.is_nan() || sphere.radius < 0.0 {
            return out;
        }
        let p = sphere.center.as_dvec3();
        let r2 = f64::from(sphere.radius) * f64::from(sphere.radius);
        let mut stack: Stack<u32> = SmallVec::new();
        stack.push(0);
        while let Some(ni) = stack.pop() {
            let node = self.nodes[ni as usize];
            if box_distance_squared(&node.bounds, p) > r2 {
                continue;
            }
            if node.is_leaf() {
                for &t in self.leaf_triangles(&node) {
                    let [a, b, c] = self.tri_d(t);
                    if closest_point_d(p, a, b, c).0.distance_squared(p) <= r2 {
                        out.push(t);
                    }
                }
            } else {
                stack.push(node.first + 1);
                stack.push(node.first);
            }
        }
        out.sort_unstable();
        out
    }

    /// `true` if any triangle of this mesh intersects or touches any triangle of `other`.
    /// `other_to_self` places `other` in this tree's space (`None`: both are in the same space).
    pub fn intersects(&self, other: &TriBvh, other_to_self: Option<&Affine3A>) -> bool {
        let mut pairs = Vec::new();
        self.overlap_walk(other, other_to_self, true, &mut pairs);
        !pairs.is_empty()
    }

    /// Every pair `(triangle of self, triangle of other)` that intersects or touches, sorted.
    /// `other_to_self` as for [`TriBvh::intersects`].
    pub fn intersecting_pairs(&self, other: &TriBvh, other_to_self: Option<&Affine3A>) -> Vec<(u32, u32)> {
        let mut pairs = Vec::new();
        self.overlap_walk(other, other_to_self, false, &mut pairs);
        pairs.sort_unstable();
        pairs
    }

    fn overlap_walk(
        &self,
        other: &TriBvh,
        xf: Option<&Affine3A>,
        first_only: bool,
        out: &mut Vec<(u32, u32)>,
    ) {
        let other_bounds = |j: u32| {
            let b = other.nodes[j as usize].bounds;
            match xf {
                // Grown by a few ulps of its coordinates: the transformed box is rounded
                // differently from the transformed vertices, and a touch must not be pruned.
                Some(xf) => {
                    let t = b.transformed(xf);
                    let pad =
                        Vec3::splat(t.min.abs().max(t.max.abs()).max_element() * 4e-6 + f32::MIN_POSITIVE);
                    Aabb::new(t.min - pad, t.max + pad)
                }
                None => b,
            }
        };
        let other_tri = |t: u32| {
            let tri = other.mesh.triangle(t);
            match xf {
                Some(xf) => tri.map(|p| xf.transform_point3(p).as_dvec3()),
                None => tri.map(Vec3::as_dvec3),
            }
        };
        let mut stack: Stack<(u32, u32)> = SmallVec::new();
        stack.push((0, 0));
        while let Some((i, j)) = stack.pop() {
            let a = self.nodes[i as usize];
            let b = other.nodes[j as usize];
            let bb = other_bounds(j);
            if !a.bounds.intersects(&bb) {
                continue;
            }
            match (a.is_leaf(), b.is_leaf()) {
                (true, true) => {
                    for &tb in other.leaf_triangles(&b) {
                        let tri_b = other_tri(tb);
                        for &ta in self.leaf_triangles(&a) {
                            if triangles_intersect_d(self.tri_d(ta), tri_b) {
                                out.push((ta, tb));
                                if first_only {
                                    return;
                                }
                            }
                        }
                    }
                }
                (true, false) => {
                    stack.push((i, b.first + 1));
                    stack.push((i, b.first));
                }
                (false, true) => {
                    stack.push((a.first + 1, j));
                    stack.push((a.first, j));
                }
                (false, false) => {
                    // Descend the larger box: it is the one more likely to separate.
                    if a.bounds.size().length_squared() >= bb.size().length_squared() {
                        stack.push((a.first + 1, j));
                        stack.push((a.first, j));
                    } else {
                        stack.push((i, b.first + 1));
                        stack.push((i, b.first));
                    }
                }
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn quad_strip(n: u32) -> TriMesh {
        let mut positions = Vec::new();
        for i in 0..=n {
            positions.push(Vec3::new(i as f32, 0.0, 0.0));
            positions.push(Vec3::new(i as f32, 1.0, 0.0));
        }
        let mut tris = Vec::new();
        for i in 0..n {
            let (a, b, c, d) = (2 * i, 2 * i + 1, 2 * i + 2, 2 * i + 3);
            tris.push([a, c, b]);
            tris.push([b, c, d]);
        }
        TriMesh::new(positions, tris).expect("mesh")
    }

    #[test]
    fn leaves_cover_every_triangle_once() {
        let bvh = TriBvh::build(quad_strip(50)).expect("bvh");
        let mut seen = vec![0u32; 100];
        for node in bvh.nodes() {
            if node.is_leaf() {
                assert!(node.count as usize <= LEAF_SIZE);
                for &t in bvh.leaf_triangles(node) {
                    seen[t as usize] += 1;
                    let [a, b, c] = bvh.mesh().triangle(t);
                    for p in [a, b, c] {
                        assert!(node.bounds.contains_point(p));
                    }
                }
            } else {
                let b = node.bounds;
                for c in [node.first, node.first + 1] {
                    assert!(b.contains(&bvh.nodes()[c as usize].bounds));
                }
            }
        }
        assert!(seen.iter().all(|&s| s == 1));
    }

    #[test]
    fn counted_queries_match_the_plain_ones_and_test_few_triangles() {
        let bvh = TriBvh::build(quad_strip(64)).expect("bvh");
        let ray = Ray::new(Vec3::new(10.3, 0.4, 1.0), Vec3::NEG_Z);
        let mut counts = QueryCounts::default();
        assert_eq!(
            bvh.ray_cast_counted(&ray, 5.0, &mut counts),
            bvh.ray_cast(&ray, 5.0)
        );
        assert!(counts.nodes > 1 && counts.triangles > 0, "{counts:?}");
        assert!(counts.triangles < 16, "the tree prunes: {counts:?}");
        let before = counts;
        let p = Vec3::new(30.2, 0.5, 0.25);
        assert_eq!(
            bvh.closest_point_counted(p, 1.0, &mut counts),
            bvh.closest_point(p, 1.0)
        );
        assert!(counts.triangles > before.triangles, "counts add up over calls");
        let mut far = QueryCounts::default();
        let away = Ray::new(Vec3::new(10.0, 50.0, 1.0), Vec3::NEG_Z);
        assert!(bvh.ray_cast_counted(&away, 5.0, &mut far).is_none());
        assert_eq!(
            far,
            QueryCounts {
                nodes: 1,
                triangles: 0
            },
            "a ray off the root box tests one box"
        );
        assert_eq!(before.plus(far).nodes, before.nodes + 1);
    }

    #[test]
    fn coincident_centroids_still_split() {
        // Forty copies of one triangle: the split falls back to half and half.
        let positions = vec![Vec3::ZERO, Vec3::X, Vec3::Y];
        let tris = vec![[0, 1, 2]; 40];
        let bvh = TriBvh::build(TriMesh::new(positions, tris).expect("mesh")).expect("bvh");
        assert!(bvh.node_count() > 1);
        let hit = bvh.ray_cast(&Ray::new(Vec3::new(0.2, 0.2, 1.0), -Vec3::Z), f32::INFINITY);
        assert!(hit.is_some());
    }

    #[test]
    fn empty_mesh_is_an_error() {
        let err = TriBvh::build(TriMesh::default()).expect_err("empty");
        assert_eq!(err, MeshQueryError::EmptyMesh);
    }
}
