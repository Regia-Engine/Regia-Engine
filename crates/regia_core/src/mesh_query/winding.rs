//! Generalized winding numbers on a [`TriBvh`].
//!
//! The winding number of a closed, outward-facing mesh is 1 inside and 0 outside; for open meshes,
//! soups and meshes with flipped faces it degrades smoothly instead of failing (A. Jacobson,
//! L. Kavan, O. Sorkine-Hornung, "Robust Inside-Outside Segmentation using Generalized Winding
//! Numbers", SIGGRAPH 2013). [`winding_number_exact`] is their direct sum of triangle solid angles
//! over 4π.
//!
//! [`WindingNumberTree`] is the hierarchical approximation of G. Barill, N. Dickson, R. Schmidt,
//! D. Levin, A. Jacobson, "Fast Winding Numbers for Soups and Clouds", SIGGRAPH 2018: each tree
//! node stores a second-order (dipole plus quadrupole) expansion of its triangles about their
//! area-weighted centroid; a node whose expansion center is farther than `beta` times its radius
//! from the query point is evaluated with the expansion instead of its triangles.
//!
//! Changes from the upstream code: the expansion coefficients are accumulated bottom-up through
//! the tree from per-triangle sums (Σ area, Σ area·centroid, Σ area·normal, Σ centroid ⊗
//! area·normal), not recomputed from each node's triangle set; the node radius is the farthest
//! corner of the node's box from the expansion center (an upper bound of the farthest vertex, so
//! the approximation is used no more often than upstream); and the root node may be approximated.

use std::f64::consts::PI;

use glam::{DMat3, DVec3, Vec3};
use smallvec::SmallVec;

use super::triangle::solid_angle_d;
use super::{MeshQueryError, TriBvh, TriMesh};

const FOUR_PI: f64 = 4.0 * PI;

/// The exact generalized winding number of `mesh` at `point`: the sum of the solid angles of
/// every triangle over 4π (Jacobson et al. 2013). Costs one solid angle per triangle; use a
/// [`WindingNumberTree`] for many queries. An empty mesh gives 0.
pub fn winding_number_exact(mesh: &TriMesh, point: Vec3) -> f32 {
    let p = point.as_dvec3();
    let mut sum = 0.0;
    for t in 0..mesh.triangle_count() as u32 {
        let [a, b, c] = mesh.triangle(t).map(Vec3::as_dvec3);
        sum += solid_angle_d(p, a, b, c);
    }
    (sum / FOUR_PI) as f32
}

/// Expansion coefficients of one tree node (Barill et al. 2018, § 3.2, orders 1 and 2).
#[derive(Debug, Clone, Copy)]
struct Expansion {
    center: DVec3,
    radius: f64,
    order1: DVec3,
    order2: DMat3,
}

/// Outer product `u vᵀ`.
fn outer(u: DVec3, v: DVec3) -> DMat3 {
    DMat3::from_cols(u * v.x, u * v.y, u * v.z)
}

/// Frobenius inner product `Σ A_ij B_ij`.
fn inner(a: &DMat3, b: &DMat3) -> f64 {
    a.x_axis.dot(b.x_axis) + a.y_axis.dot(b.y_axis) + a.z_axis.dot(b.z_axis)
}

impl Expansion {
    /// The second-order far-field winding number at `q`: `order1 · ∇G + order2 : ∇²G` with
    /// `∇G(x) = x / (4π|x|³)` evaluated at `x = center − q`.
    fn evaluate(&self, q: DVec3) -> f64 {
        let x = self.center - q;
        let len2 = x.length_squared();
        let len = len2.sqrt();
        let len3 = len2 * len;
        let f = 1.0 / (FOUR_PI * len3);
        let first = f * self.order1.dot(x);
        let c = -3.0 / (FOUR_PI * len3 * len2);
        let hessian = DMat3::from_diagonal(DVec3::splat(f)) + outer(x, x) * c;
        first + inner(&self.order2, &hessian)
    }
}

/// A [`TriBvh`] with the fast winding number expansion on every node. Built once per mesh;
/// queries are read-only and cheap (about `log n` node visits for points away from the surface).
#[derive(Debug, Clone)]
pub struct WindingNumberTree {
    bvh: TriBvh,
    expansions: Vec<Expansion>,
    beta: f64,
}

impl WindingNumberTree {
    /// The accuracy parameter of Barill et al. 2018 (their default): a node is approximated when
    /// the query point is farther than `beta` times the node's radius from its expansion center.
    /// Larger is more accurate and slower.
    pub const DEFAULT_BETA: f32 = 2.0;

    /// Builds the tree and the expansions with [`WindingNumberTree::DEFAULT_BETA`]. Fails with
    /// [`MeshQueryError::EmptyMesh`] for a mesh without triangles.
    pub fn build(mesh: TriMesh) -> Result<Self, MeshQueryError> {
        Self::from_bvh(TriBvh::build(mesh)?, Self::DEFAULT_BETA)
    }

    /// Adds the expansions to an existing tree. Fails with [`MeshQueryError::InvalidBeta`] when
    /// `beta` is not finite and positive.
    pub fn from_bvh(bvh: TriBvh, beta: f32) -> Result<Self, MeshQueryError> {
        let _span = tracing::debug_span!("winding_tree_build", nodes = bvh.node_count()).entered();
        if !beta.is_finite() || beta <= 0.0 {
            return Err(MeshQueryError::InvalidBeta(beta));
        }
        let nodes = bvh.nodes();
        let n = nodes.len();
        // Per-node sums: area, area·centroid, area·normal, centroid ⊗ area·normal.
        let mut area = vec![0.0_f64; n];
        let mut area_centroid = vec![DVec3::ZERO; n];
        let mut area_normal = vec![DVec3::ZERO; n];
        let mut moment = vec![DMat3::ZERO; n];
        for i in (0..n).rev() {
            let node = nodes[i];
            if node.is_leaf() {
                for &t in bvh.leaf_triangles(&node) {
                    let [a, b, c] = bvh.mesh().triangle(t).map(Vec3::as_dvec3);
                    let an = (b - a).cross(c - a) * 0.5;
                    let ar = an.length();
                    let centroid = (a + b + c) / 3.0;
                    area[i] += ar;
                    area_centroid[i] += centroid * ar;
                    area_normal[i] += an;
                    moment[i] += outer(centroid, an);
                }
            } else {
                let (c0, c1) = (node.first as usize, node.first as usize + 1);
                area[i] = area[c0] + area[c1];
                area_centroid[i] = area_centroid[c0] + area_centroid[c1];
                area_normal[i] = area_normal[c0] + area_normal[c1];
                moment[i] = moment[c0] + moment[c1];
            }
        }
        let expansions = (0..n)
            .map(|i| {
                let (min, max) = (nodes[i].bounds.min.as_dvec3(), nodes[i].bounds.max.as_dvec3());
                let center = if area[i] > 0.0 {
                    area_centroid[i] / area[i]
                } else {
                    (min + max) * 0.5
                };
                let radius = (center - min).abs().max((max - center).abs()).length();
                Expansion {
                    center,
                    radius,
                    order1: area_normal[i],
                    // Σ (c − p) ⊗ a·n = Σ c ⊗ a·n − p ⊗ Σ a·n.
                    order2: moment[i] - outer(center, area_normal[i]),
                }
            })
            .collect();
        Ok(Self {
            bvh,
            expansions,
            beta: f64::from(beta),
        })
    }

    /// The tree the expansions belong to.
    pub fn bvh(&self) -> &TriBvh {
        &self.bvh
    }

    /// Gives the tree back.
    pub fn into_bvh(self) -> TriBvh {
        self.bvh
    }

    /// The accuracy parameter in use.
    pub fn beta(&self) -> f32 {
        self.beta as f32
    }

    /// Changes the accuracy parameter (no rebuild needed). Fails with
    /// [`MeshQueryError::InvalidBeta`] when `beta` is not finite and positive.
    pub fn set_beta(&mut self, beta: f32) -> Result<(), MeshQueryError> {
        if !beta.is_finite() || beta <= 0.0 {
            return Err(MeshQueryError::InvalidBeta(beta));
        }
        self.beta = f64::from(beta);
        Ok(())
    }

    /// The approximate generalized winding number at `point`: about 1 inside a closed,
    /// outward-facing mesh and 0 outside. NaN for a non-finite point.
    pub fn winding_number(&self, point: Vec3) -> f32 {
        if !point.is_finite() {
            return f32::NAN;
        }
        let q = point.as_dvec3();
        let nodes = self.bvh.nodes();
        let mut sum = 0.0_f64;
        let mut solid = 0.0_f64;
        let mut stack: SmallVec<[u32; 64]> = SmallVec::new();
        stack.push(0);
        while let Some(ni) = stack.pop() {
            let node = nodes[ni as usize];
            let e = &self.expansions[ni as usize];
            if !node.bounds.contains_point(point) && e.center.distance(q) > self.beta * e.radius {
                sum += e.evaluate(q);
            } else if node.is_leaf() {
                for &t in self.bvh.leaf_triangles(&node) {
                    let [a, b, c] = self.bvh.mesh().triangle(t).map(Vec3::as_dvec3);
                    solid += solid_angle_d(q, a, b, c);
                }
            } else {
                stack.push(node.first + 1);
                stack.push(node.first);
            }
        }
        (sum + solid / FOUR_PI) as f32
    }

    /// `true` if the winding number at `point` is above one half (inside).
    pub fn is_inside(&self, point: Vec3) -> bool {
        self.winding_number(point) > 0.5
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::mesh_query::TriMesh;
    use glam::Vec3;

    /// Closed outward tetrahedron around the origin.
    fn tetra() -> TriMesh {
        let p = [
            Vec3::new(1.0, 1.0, 1.0),
            Vec3::new(-1.0, -1.0, 1.0),
            Vec3::new(-1.0, 1.0, -1.0),
            Vec3::new(1.0, -1.0, -1.0),
        ];
        let idx = [[0, 2, 1], [0, 1, 3], [0, 3, 2], [1, 2, 3]];
        TriMesh::new(p.to_vec(), idx.to_vec()).expect("tetrahedron")
    }

    /// Winding bits at the points below, pinned (ADR-4773, audit G finding 6).
    const WINDING_BITS: [u32; 3] = [1_065_353_216, 0, 1_065_353_216];

    #[test]
    fn winding_number_bits_are_platform_independent() {
        let mesh = tetra();
        let tree = WindingNumberTree::build(mesh.clone()).expect("tree");
        let w = [
            tree.winding_number(Vec3::new(0.1, -0.2, 0.3)).to_bits(),
            tree.winding_number(Vec3::new(2.5, 0.0, 0.0)).to_bits(),
            winding_number_exact(&mesh, Vec3::new(0.1, -0.2, 0.3)).to_bits(),
        ];
        assert_eq!(
            w, WINDING_BITS,
            "the inside/outside boundary near 0.5 must not depend on the cook host's libm"
        );
    }
}
