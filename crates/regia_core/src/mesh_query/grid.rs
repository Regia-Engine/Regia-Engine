//! [`DenseGrid3`]: a dense 3D array, x fastest.

use std::ops::{Index, IndexMut};

use glam::UVec3;

/// A dense `dims.x × dims.y × dims.z` array stored x fastest, then y, then z.
#[derive(Debug, Clone, PartialEq)]
pub struct DenseGrid3<T> {
    dims: UVec3,
    values: Vec<T>,
}

impl<T: Clone> DenseGrid3<T> {
    /// A grid of `dims` filled with `fill`.
    pub fn new(dims: UVec3, fill: T) -> Self {
        let len = dims.x as usize * dims.y as usize * dims.z as usize;
        Self {
            dims,
            values: vec![fill; len],
        }
    }
}

impl<T> DenseGrid3<T> {
    /// Size on each axis.
    pub fn dims(&self) -> UVec3 {
        self.dims
    }

    /// Number of cells.
    pub fn len(&self) -> usize {
        self.values.len()
    }

    /// `true` if any axis has size zero.
    pub fn is_empty(&self) -> bool {
        self.values.is_empty()
    }

    /// Linear index of cell `(i, j, k)` (not range-checked).
    #[inline]
    pub fn linear(&self, i: u32, j: u32, k: u32) -> usize {
        i as usize + self.dims.x as usize * (j as usize + self.dims.y as usize * k as usize)
    }

    /// The cell at `(i, j, k)`, or `None` outside the grid.
    pub fn get(&self, i: u32, j: u32, k: u32) -> Option<&T> {
        (i < self.dims.x && j < self.dims.y && k < self.dims.z).then(|| &self.values[self.linear(i, j, k)])
    }

    /// The cell at `(i, j, k)` for writing, or `None` outside the grid.
    pub fn get_mut(&mut self, i: u32, j: u32, k: u32) -> Option<&mut T> {
        if i < self.dims.x && j < self.dims.y && k < self.dims.z {
            let at = self.linear(i, j, k);
            Some(&mut self.values[at])
        } else {
            None
        }
    }

    /// Every cell, x fastest.
    pub fn values(&self) -> &[T] {
        &self.values
    }

    /// Every cell for writing, x fastest.
    pub fn values_mut(&mut self) -> &mut [T] {
        &mut self.values
    }
}

/// `grid[[i, j, k]]`; panics outside the grid.
impl<T> Index<[u32; 3]> for DenseGrid3<T> {
    type Output = T;

    fn index(&self, [i, j, k]: [u32; 3]) -> &T {
        assert!(
            i < self.dims.x && j < self.dims.y && k < self.dims.z,
            "cell ({i}, {j}, {k}) outside {}",
            self.dims
        );
        &self.values[self.linear(i, j, k)]
    }
}

/// `grid[[i, j, k]] = v`; panics outside the grid.
impl<T> IndexMut<[u32; 3]> for DenseGrid3<T> {
    fn index_mut(&mut self, [i, j, k]: [u32; 3]) -> &mut T {
        assert!(
            i < self.dims.x && j < self.dims.y && k < self.dims.z,
            "cell ({i}, {j}, {k}) outside {}",
            self.dims
        );
        let at = self.linear(i, j, k);
        &mut self.values[at]
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn indexing_is_x_fastest() {
        let mut g = DenseGrid3::new(UVec3::new(3, 4, 5), 0u32);
        assert_eq!(g.len(), 60);
        g[[2, 1, 3]] = 7;
        assert_eq!(g.values()[2 + 3 * (1 + 4 * 3)], 7);
        assert_eq!(g.get(2, 1, 3), Some(&7));
        assert_eq!(g.get(3, 0, 0), None);
        assert!(g.get_mut(0, 4, 0).is_none());
    }
}
