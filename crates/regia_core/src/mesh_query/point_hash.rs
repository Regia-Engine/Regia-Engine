//! [`PointHash`]: points bucketed in a uniform grid of cubic cells, for radius and nearest queries.
//!
//! Changes from the upstream hash table: the occupied cells are stored as runs of one sorted index
//! array (a counting layout) behind a hash map from cell to run, instead of one list per cell; any
//! radius is supported (upstream limits the ball to one cell); and a nearest-point search over
//! growing shells of cells is added.

use std::collections::HashMap;

use glam::{I64Vec3, IVec3, Vec3};

use super::MeshQueryError;

/// Points bucketed by a uniform grid of cubic cells. Built once from a point slice (copied); the
/// indices it returns are positions in that slice.
#[derive(Debug, Clone)]
pub struct PointHash {
    cell_size: f32,
    points: Vec<Vec3>,
    /// Point indices sorted by cell, then index.
    sorted: Vec<u32>,
    /// Occupied cell → `(start, len)` in `sorted`.
    cells: HashMap<IVec3, (u32, u32)>,
    /// The box of occupied cell keys (`IVec3::MAX..MIN` when empty).
    key_min: IVec3,
    key_max: IVec3,
}

impl PointHash {
    /// Buckets `points` in cells of `cell_size`. Fails with [`MeshQueryError::InvalidCellSize`] or,
    /// for a NaN or infinite point, [`MeshQueryError::NonFinite`]. An empty slice is allowed.
    pub fn build(points: &[Vec3], cell_size: f32) -> Result<Self, MeshQueryError> {
        if !cell_size.is_finite() || cell_size <= 0.0 {
            return Err(MeshQueryError::InvalidCellSize(cell_size));
        }
        u32::try_from(points.len()).map_err(|_| MeshQueryError::TooLarge(points.len()))?;
        if let Some(bad) = points.iter().position(|p| !p.is_finite()) {
            return Err(MeshQueryError::NonFinite(bad as u32));
        }
        let inv = 1.0 / cell_size;
        let keys: Vec<IVec3> = points.iter().map(|&p| key(p, inv)).collect();
        let mut sorted: Vec<u32> = (0..points.len() as u32).collect();
        sorted.sort_unstable_by_key(|&i| (keys[i as usize].to_array(), i));
        let mut cells = HashMap::new();
        let (mut key_min, mut key_max) = (IVec3::MAX, IVec3::MIN);
        let mut start = 0;
        while start < sorted.len() {
            let k = keys[sorted[start] as usize];
            let mut end = start + 1;
            while end < sorted.len() && keys[sorted[end] as usize] == k {
                end += 1;
            }
            cells.insert(k, (start as u32, (end - start) as u32));
            key_min = key_min.min(k);
            key_max = key_max.max(k);
            start = end;
        }
        Ok(Self {
            cell_size,
            points: points.to_vec(),
            sorted,
            cells,
            key_min,
            key_max,
        })
    }

    /// Cell edge length.
    pub fn cell_size(&self) -> f32 {
        self.cell_size
    }

    /// The points, in their original order.
    pub fn points(&self) -> &[Vec3] {
        &self.points
    }

    /// Number of points.
    pub fn len(&self) -> usize {
        self.points.len()
    }

    /// `true` if there are no points.
    pub fn is_empty(&self) -> bool {
        self.points.is_empty()
    }

    /// Number of occupied cells.
    pub fn occupied_cells(&self) -> usize {
        self.cells.len()
    }

    fn cell_points(&self, k: IVec3) -> &[u32] {
        match self.cells.get(&k) {
            Some(&(start, len)) => &self.sorted[start as usize..(start + len) as usize],
            None => &[],
        }
    }

    /// A lower bound of the squared distance from `p` to any point bucketed in cell `k`.
    ///
    /// Keys are `floor(p * (1 / cell_size))` in `f32`, so a point can sit a few ulps outside the
    /// exact box `[k, k + 1) * cell_size`: the box is widened by that rounding (in `f64`), and a
    /// saturated key (`i32::MIN` or `i32::MAX`, every point beyond the `i32` range) is open on its
    /// saturated side.
    fn cell_distance_squared(&self, k: IVec3, p: Vec3) -> f32 {
        let size = f64::from(self.cell_size);
        let mut d2 = 0.0f64;
        for (key, c) in k.to_array().into_iter().zip(p.to_array()) {
            // Two roundings (the reciprocal and the product) of relative size `f32::EPSILON / 2`
            // each, on a value of magnitude `|key| + 1` cells; four ulps is a safe margin.
            let slack = 4.0 * f64::from(f32::EPSILON) * (f64::from(key).abs() + 1.0) * size;
            let lo = if key == i32::MIN {
                f64::NEG_INFINITY
            } else {
                f64::from(key) * size - slack
            };
            let hi = if key == i32::MAX {
                f64::INFINITY
            } else {
                (f64::from(key) + 1.0) * size + slack
            };
            let c = f64::from(c);
            let gap = (lo - c).max(c - hi).max(0.0);
            d2 += gap * gap;
        }
        // Round down so the cull never rejects a cell the exact test would accept.
        let d2 = d2 as f32;
        if d2 > 0.0 { d2.next_down() } else { 0.0 }
    }

    /// Indices of every point within `radius` of `center` (on the sphere counts), in ascending
    /// order. Any radius works; a negative or NaN radius finds nothing.
    pub fn within_radius(&self, center: Vec3, radius: f32) -> Vec<u32> {
        let mut out = Vec::new();
        if self.is_empty() || !center.is_finite() || radius.is_nan() || radius < 0.0 {
            return out;
        }
        let r2 = radius * radius;
        let inv = 1.0 / self.cell_size;
        let lo = key(center - Vec3::splat(radius), inv).max(self.key_min);
        let hi = key(center + Vec3::splat(radius), inv).min(self.key_max);
        if lo.cmpgt(hi).any() {
            return out;
        }
        let span = hi.as_i64vec3() - lo.as_i64vec3() + I64Vec3::ONE;
        let range_cells = span.x.saturating_mul(span.y).saturating_mul(span.z);
        let take = |k: IVec3, out: &mut Vec<u32>| {
            if self.cell_distance_squared(k, center) > r2 {
                return;
            }
            for &i in self.cell_points(k) {
                if self.points[i as usize].distance_squared(center) <= r2 {
                    out.push(i);
                }
            }
        };
        if range_cells > self.cells.len() as i64 {
            // A ball much larger than the occupied cells: visit occupied cells instead.
            for &k in self.cells.keys() {
                if k.cmpge(lo).all() && k.cmple(hi).all() {
                    take(k, &mut out);
                }
            }
        } else {
            for z in lo.z..=hi.z {
                for y in lo.y..=hi.y {
                    for x in lo.x..=hi.x {
                        take(IVec3::new(x, y, z), &mut out);
                    }
                }
            }
        }
        out.sort_unstable();
        out
    }

    /// The point nearest to `center` within `max_distance` (use `f32::INFINITY` for no limit), as
    /// its index and distance; ties go to the lower index. `None` if there is none.
    pub fn nearest(&self, center: Vec3, max_distance: f32) -> Option<(u32, f32)> {
        if self.is_empty() || !center.is_finite() || max_distance.is_nan() || max_distance < 0.0 {
            return None;
        }
        let inv = 1.0 / self.cell_size;
        let c = key(center, inv);
        // The farthest shell that can hold an occupied cell.
        let (c64, lo64, hi64) = (
            c.as_i64vec3(),
            self.key_min.as_i64vec3(),
            self.key_max.as_i64vec3(),
        );
        let reach = (c64 - lo64).abs().max((hi64 - c64).abs()).max_element();
        // Shells cost (2·ring + 1)³ cell visits; past a few times the occupied cell count, a scan
        // of every point is cheaper.
        let shell_budget = 8 * self.cells.len() as i64 + 27;
        let limit2 = max_distance * max_distance;
        let mut best: Option<(u32, f32)> = None;
        let consider = |i: u32, best: &mut Option<(u32, f32)>| {
            let d2 = self.points[i as usize].distance_squared(center);
            if d2 > limit2 {
                return;
            }
            let d = d2.sqrt();
            let better = match *best {
                None => true,
                Some((bi, bd)) => d < bd || (d == bd && i < bi),
            };
            if better {
                *best = Some((i, d));
            }
        };
        let mut ring: i64 = 0;
        while ring <= reach {
            if (2 * ring + 1).pow(3) > shell_budget {
                let mut scan = None;
                for i in 0..self.points.len() as u32 {
                    consider(i, &mut scan);
                }
                return scan;
            }
            // Every cell in this shell is at least (ring − 1) cells away.
            let shell_min = (ring - 1).max(0) as f32 * self.cell_size;
            let bound = best.map_or(max_distance, |(_, d)| d.min(max_distance));
            if shell_min > bound {
                break;
            }
            let r = ring as i32;
            for z in -r..=r {
                for y in -r..=r {
                    for x in -r..=r {
                        if x.abs().max(y.abs()).max(z.abs()) != r {
                            continue;
                        }
                        for &i in self.cell_points(c.wrapping_add(IVec3::new(x, y, z))) {
                            consider(i, &mut best);
                        }
                    }
                }
            }
            ring += 1;
        }
        best
    }
}

/// The cell holding `p` (coordinates saturate at the `i32` range).
fn key(p: Vec3, inv: f32) -> IVec3 {
    let f = (p * inv).floor();
    IVec3::new(f.x as i32, f.y as i32, f.z as i32)
}
