const WARN: egui::Color32 = egui::Color32::from_rgb(240, 180, 80);
const BAD: egui::Color32 = egui::Color32::from_rgb(255, 120, 100);
const GOOD: egui::Color32 = egui::Color32::from_rgb(120, 220, 140);
const SOCKET: egui::Color32 = egui::Color32::from_rgb(90, 200, 255);
const SOCKET_SELECTED: egui::Color32 = egui::Color32::from_rgb(255, 230, 90);

/// The Kit panel.
pub fn kit_panel(ui: &mut egui::Ui, world: &mut World, device: Option<&RenderDevice>) {
    let mut view = world.remove_resource::<KitView>().unwrap_or_default();
    if let Some(dir) = view.open_request.take() {
        let _ = open_kit_into(&mut view, world, &dir);
    }
    draw(ui, &mut view, world, device);
    world.insert_resource(view);
}

fn draw(ui: &mut egui::Ui, view: &mut KitView, world: &mut World, device: Option<&RenderDevice>) {
    ui.horizontal(|ui| {
        if ui.button("Open kit…").clicked()
            && let Some(dir) = crate::file_dialog::FileDialog::new().pick_folder()
        {
            view.open_request = Some(dir);
        }
        if let Some(kit) = view.kit.clone()
            && ui.button("Reload").clicked()
        {
            view.open_request = Some(kit.root.clone());
        }
        if let Some(kit) = &view.kit {
            ui.weak(kit.root.display().to_string());
        }
    });
    if let Some(err) = &view.error {
        ui.colored_label(BAD, format!("Kit not opened: {err}"));
    }
    let Some(kit) = view.kit.clone() else {
        if view.error.is_none() {
            ui.weak(
                "Open an exported kit folder: kit.json, <kit_id>.glb, and optionally a cockpit, \
                 rig.json, sockets.json and SHA256SUMS.",
            );
        }
        return;
    };
    ui.separator();
    ui.columns(2, |columns| {
        let left = &mut columns[0];
        egui::ScrollArea::vertical()
            .id_salt("kit-info")
            .show(left, |ui| info_column(ui, view, world, &kit));
        render_column(&mut columns[1], view, &kit, device);
    });
}

fn info_column(ui: &mut egui::Ui, view: &mut KitView, world: &mut World, kit: &Kit) {
    let m = &kit.manifest;
    ui.heading(&m.kit_id);
    egui::Grid::new("kit-manifest")
        .num_columns(2)
        .striped(true)
        .show(ui, |ui| {
            let rows = [
                ("kit_id", m.kit_id.clone()),
                ("kind", m.kind.clone()),
                ("class", m.class.clone()),
                ("faction", m.faction.clone()),
                ("replaces", m.replaces.clone()),
                ("stats_from", m.stats_from.clone()),
                ("contract", m.contract.clone()),
                ("version", m.version.to_string()),
                (
                    "character kit",
                    if kit.character_kit { "yes" } else { "no" }.to_string(),
                ),
            ];
            for (key, value) in rows {
                ui.label(key);
                if value.is_empty() {
                    ui.weak("(empty)");
                } else {
                    ui.label(value);
                }
                ui.end_row();
            }
        });

    let sums = &kit.checksums;
    let color = match sums.verdict {
        ChecksumVerdict::Verified => GOOD,
        ChecksumVerdict::Absent => ui.visuals().weak_text_color(),
        ChecksumVerdict::Failed | ChecksumVerdict::Unreadable => BAD,
    };
    ui.colored_label(
        color,
        format!(
            "SHA256SUMS: {} ({} listed)",
            sums.verdict.label(),
            sums.entries.len()
        ),
    );
    if !sums.entries.is_empty() {
        egui::CollapsingHeader::new("Checksums")
            .id_salt("kit-sums")
            .show(ui, |ui| {
                // A screenful at a time (ADR-7306): a kit lists up to MAX_ENTRIES files.
                crate::virtual_list::rows(ui, "kit-sums-rows", sums.entries.len(), 320.0, |ui, i| {
                    let entry = &sums.entries[i];
                    let (text, color) = match &entry.status {
                        ChecksumStatus::Ok => ("ok".to_string(), GOOD),
                        ChecksumStatus::Mismatch { .. } => ("mismatch".to_string(), BAD),
                        ChecksumStatus::Missing => ("missing".to_string(), BAD),
                        ChecksumStatus::Refused { reason } => (format!("not checked: {reason}"), BAD),
                    };
                    ui.colored_label(color, format!("{} · {text}", entry.file));
                });
            });
    }

    if !kit.warnings.is_empty() {
        egui::CollapsingHeader::new(format!("Warnings ({})", kit.warnings.len()))
            .id_salt("kit-warnings")
            .default_open(true)
            .show(ui, |ui| {
                for warning in &kit.warnings {
                    ui.colored_label(WARN, warning.to_string());
                }
            });
    }

    budget_section(ui, view);

    ui.separator();
    ui.strong(format!("Clips ({})", kit.clips.len()));
    if kit.clips.is_empty() {
        ui.weak("No clips.");
    }
    for clip in &kit.clips {
        let label = format!(
            "{} · {:.2} s{}",
            clip.name,
            clip.duration,
            if clip.source == ClipSource::Rig {
                " · rig.json only"
            } else {
                ""
            }
        );
        let playable = view.preview_rig && clip.source == ClipSource::Model;
        let selected = view.clip.as_deref() == Some(clip.name.as_str());
        let response = ui.add_enabled(playable, egui::Button::selectable(selected, label));
        let response = if playable {
            response.on_hover_text("Play in the Clip panel")
        } else {
            response.on_disabled_hover_text(if clip.source == ClipSource::Rig {
                "rig.json lists this clip but the model has no animation for it"
            } else {
                "the model has no skin, so the animation preview cannot play it"
            })
        };
        if response.clicked() {
            play_clip(view, world, &clip.name);
        }
    }

    ui.separator();
    ui.horizontal(|ui| {
        ui.strong(format!("Sockets ({})", kit.sockets.len()));
        ui.checkbox(&mut view.show_sockets, "Socket gizmos");
    });
    for socket in &kit.sockets {
        let position = socket.position.map_or_else(
            || "no position".to_string(),
            |p| format!("{:.2}, {:.2}, {:.2}", p[0], p[1], p[2]),
        );
        let source = match (socket.in_model, socket.in_sockets_json) {
            (true, true) => "model + sockets.json",
            (true, false) => "model",
            _ => "sockets.json only",
        };
        let selected = view.selected_socket.as_deref() == Some(socket.name.as_str());
        if ui
            .selectable_label(selected, format!("{} · {position} · {source}", socket.name))
            .clicked()
        {
            view.selected_socket = (!selected).then(|| socket.name.clone());
        }
    }
}

/// The Budget section: the summary in the worst status's color, a class picker and one meter
/// per limit plus the LOD chain.
fn budget_section(ui: &mut egui::Ui, view: &mut KitView) {
    ui.separator();
    let Some(budget) = view.budget() else {
        ui.weak("Budget: the model was not measured (see the warnings).");
        return;
    };
    let color = status_color(budget.worst(), ui.visuals());
    ui.horizontal(|ui| {
        ui.colored_label(color, format!("Budget {}", budget.summary_line()));
        let mut class = budget.class;
        if class_picker(ui, &mut class, "kit") {
            view.budget_class = Some(class);
        }
    });
    egui::CollapsingHeader::new(format!("Budget meters ({} over)", budget.over_count()))
        .id_salt("kit-budget")
        .default_open(budget.over_count() > 0)
        .show(ui, |ui| draw_budget(ui, &budget, "kit"));
}

fn render_column(ui: &mut egui::Ui, view: &mut KitView, kit: &Kit, device: Option<&RenderDevice>) {
    let Some(meshes) = view.meshes.clone() else {
        ui.weak("No meshes to show (see the warnings).");
        return;
    };
    ui.horizontal_wrapped(|ui| {
        for (index, lod) in meshes.lods.iter().enumerate() {
            ui.selectable_value(
                &mut view.lod,
                index,
                format!(
                    "LOD{} ({} tris{})",
                    lod.level,
                    lod.triangles,
                    if lod.authored { "" } else { ", generated" }
                ),
            );
        }
    });
    if let Some(cockpit) = &kit.cockpit {
        let at = if kit.cockpit_mount.is_some() {
            COCKPIT_SOCKET
        } else {
            "the origin (no socket_cockpit)"
        };
        ui.weak(format!("cockpit {} at {at}", cockpit.file));
    }
    let Some(device) = device else {
        ui.weak("No GPU device: the render is off.");
        return;
    };
    let width = ui.available_width().max(64.0);
    let side = width.min(ui.available_height().max(64.0));
    let size = [side as u32, side as u32];
    let key: RenderKey = (
        view.revision,
        view.lod,
        [view.orbit.0.to_bits(), view.orbit.1.to_bits()],
        size,
    );
    let cached = view
        .render_cache
        .as_ref()
        .filter(|(cached, _)| *cached == key)
        .map(|(_, texture)| texture.clone());
    let texture = match cached {
        Some(texture) => texture,
        None => {
            let parts = view.placed_parts(view.lod);
            let Some(image) =
                render_placed_parts(device, &parts, meshes.bounds, view.orbit.0, view.orbit.1, size)
            else {
                ui.colored_label(BAD, "The render failed.");
                return;
            };
            let texture = ui
                .ctx()
                .load_texture("kit-viewer", image, egui::TextureOptions::LINEAR);
            view.render_cache = Some((key, texture.clone()));
            texture
        }
    };
    let response = ui.add(egui::Image::new(&texture).sense(egui::Sense::drag()));
    let delta = response.drag_delta();
    view.orbit.0 -= delta.x * 0.01;
    view.orbit.1 = (view.orbit.1 + delta.y * 0.01).clamp(-1.4, 1.4);
    if view.show_sockets {
        let camera = OrbitCamera::framing(meshes.bounds, view.orbit.0, view.orbit.1);
        let rect = response.rect;
        let painter = ui.painter_at(rect);
        for (socket, at) in socket_marks(kit, &camera, [rect.width(), rect.height()]) {
            let selected = view.selected_socket.as_deref() == Some(socket.as_str());
            let color = if selected { SOCKET_SELECTED } else { SOCKET };
            let center = rect.min + egui::vec2(at[0], at[1]);
            painter.circle_stroke(
                center,
                if selected { 7.0 } else { 5.0 },
                egui::Stroke::new(2.0, color),
            );
            painter.line_segment(
                [center - egui::vec2(9.0, 0.0), center + egui::vec2(9.0, 0.0)],
                egui::Stroke::new(1.0, color),
            );
            painter.line_segment(
                [center - egui::vec2(0.0, 9.0), center + egui::vec2(0.0, 9.0)],
                egui::Stroke::new(1.0, color),
            );
            painter.text(
                center + egui::vec2(10.0, -10.0),
                egui::Align2::LEFT_BOTTOM,
                &socket,
                egui::FontId::proportional(11.0),
                color,
            );
        }
    }
}

/// Every socket with a position, projected into a `size` render.
#[must_use]
pub fn socket_marks(kit: &Kit, camera: &OrbitCamera, size: [f32; 2]) -> Vec<(String, [f32; 2])> {
    kit.sockets
        .iter()
        .filter_map(|socket| {
            let at = camera.project(Vec3::from_array(socket.position?), size)?;
            (at[0] >= 0.0 && at[1] >= 0.0 && at[0] <= size[0] && at[1] <= size[1])
                .then(|| (socket.name.clone(), at))
        })
        .collect()
}

/// Paints a cross per socket into a render (the protocol's PNG).
fn paint_sockets(image: &mut egui::ColorImage, marks: &[(String, [f32; 2])]) {
    let [width, height] = image.size;
    for (_, at) in marks {
        let (x, y) = (at[0].round() as i64, at[1].round() as i64);
        for d in -6i64..=6 {
            for (px, py) in [(x + d, y), (x, y + d)] {
                if px >= 0 && py >= 0 && (px as usize) < width && (py as usize) < height {
                    image.pixels[py as usize * width + px as usize] = SOCKET;
                }
            }
        }
    }
}

