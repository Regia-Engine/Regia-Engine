//! The kit viewer: **File ▸ Open kit…**, the Kit panel and `editor.open_kit`
//! (`book/user-guide/open-kit.md`, `book/agents/open-kit.md`).
//!
//! Opening a kit runs the pure loader ([`crate::kit::open_kit`]), then loads the model's meshes
//! through [`crate::mesh_source`]: an authored `_LOD<n>` chain when the model has one (LOD0 to
//! LOD3), otherwise the asset viewer's generated chain ([`crate::asset_viewer::build_lods`]).
//! The cockpit model, when the kit has one, is drawn at the model's `socket_cockpit` node (at
//! the origin, with a warning, when the node is missing). A skinned model becomes the animation
//! editor's preview rig, so its clips play in the Clip panel.
//!
//! State lives in the [`KitView`] world resource, so the panel and the agent protocol see the
//! same kit.

