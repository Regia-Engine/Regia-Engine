fn kit_rpc_error(err: &KitError) -> RpcError {
    let mut error = match err {
        KitError::NotAFolder(_) | KitError::MissingManifest | KitError::MissingModel(_) => {
            RpcError::not_found(
                err.to_string(),
                "pass the kit folder (the one holding kit.json and <kit_id>.glb)",
            )
        }
        _ => RpcError::new(
            regia_agent::protocol::INVALID_PARAMS,
            "F0002",
            err.to_string(),
            "the kit folder's contents are refused; fix the file named in the message",
        ),
    };
    if let Some(data) = error.data.as_mut() {
        data["kit_error"] = json!(err.code());
    }
    error
}

/// `editor.open_kit`.
fn open_kit_method(world: &mut World, params: &Value) -> Result<Value, RpcError> {
    let raw = str_param(params, "path").ok_or_else(|| RpcError::invalid_params("`path` is required"))?;
    // Kits come from Tincal output folders outside the project: like `editor.fbx_inspect`, this
    // read-only method takes any folder (ADR-1816); the kit reader confines what it reads to it.
    let path = Path::new(raw);
    let dir = if path.is_absolute() {
        path.to_path_buf()
    } else {
        crate::mesh_source::project_root(world).map_or_else(|| path.to_path_buf(), |root| root.join(path))
    };
    let mut view = world.remove_resource::<KitView>().unwrap_or_default();
    let result = open_kit_into(&mut view, world, &dir);
    let reply = match result {
        Err(err) => Err(kit_rpc_error(&err)),
        Ok(kit) => {
            let mut clip_played = Value::Null;
            if let Some(clip) = str_param(params, "clip") {
                clip_played = json!(play_clip(&mut view, world, clip));
            }
            let mut out = kit.to_json();
            out["kit_id"] = json!(kit.manifest.kit_id);
            out["lods"] = view.lods_json();
            out["preview_rig"] = json!(view.preview_rig);
            out["budget"] = view.budget().map_or(Value::Null, |budget| budget.to_json());
            out["clip_played"] = clip_played;
            if params.get("render").and_then(Value::as_bool).unwrap_or(false) {
                match render_for_agent(world, &view, &kit, params) {
                    Ok(render) => out["render"] = render,
                    Err(err) => {
                        world.insert_resource(view);
                        return Err(err);
                    }
                }
            }
            Ok(out)
        }
    };
    world.insert_resource(view);
    reply
}

fn render_for_agent(world: &mut World, view: &KitView, kit: &Kit, params: &Value) -> Result<Value, RpcError> {
    let meshes = view
        .meshes
        .clone()
        .ok_or_else(|| RpcError::internal("the kit's meshes did not load (see warnings)"))?;
    let lod = params.get("lod").and_then(Value::as_u64).unwrap_or(0) as usize;
    if lod >= meshes.lods.len() {
        return Err(RpcError::invalid_params(format!(
            "`lod` must be below {}",
            meshes.lods.len()
        )));
    }
    let (width, height) = (dim(params, "width", 320), dim(params, "height", 240));
    let yaw = params.get("yaw").and_then(Value::as_f64).unwrap_or(0.6) as f32;
    let pitch = params.get("pitch").and_then(Value::as_f64).unwrap_or(0.35) as f32;
    let device = crate::agent_ext::viewport_device(world)?;
    let parts = view.placed_parts(lod);
    let mut image = render_placed_parts(&device, &parts, meshes.bounds, yaw, pitch, [width, height])
        .ok_or_else(|| RpcError::internal("kit render failed"))?;
    let camera = OrbitCamera::framing(meshes.bounds, yaw, pitch);
    let marks = socket_marks(kit, &camera, [image.size[0] as f32, image.size[1] as f32]);
    let draw_sockets = params.get("sockets").and_then(Value::as_bool).unwrap_or(true);
    if draw_sockets {
        paint_sockets(&mut image, &marks);
    }
    let png = crate::render::viewport_png_base64(&image).map_err(RpcError::internal)?;
    Ok(json!({
        "width": image.width(),
        "height": image.height(),
        "lod": lod,
        "mime": "image/png",
        "png_base64": png,
        "socket_marks": marks
            .iter()
            .map(|(name, at)| json!({ "name": name, "x": at[0], "y": at[1] }))
            .collect::<Vec<_>>(),
    }))
}

