/// Most LOD levels shown (LOD0 to LOD3).
pub const MAX_LODS: usize = 4;

/// One LOD level of a kit model.
#[derive(Debug, Clone)]
pub struct KitLod {
    /// The level (`n` of `_LOD<n>`, or the generated chain's index).
    pub level: usize,
    /// Authored in the GLB (`_LOD<n>` nodes) rather than generated by the viewer.
    pub authored: bool,
    /// The parts drawn at this level.
    pub parts: Vec<ModelPart>,
    /// Triangles over the parts.
    pub triangles: usize,
}

/// A kit's loaded meshes.
#[derive(Debug, Clone)]
pub struct KitMeshes {
    /// The model's LOD chain (at least LOD0).
    pub lods: Vec<KitLod>,
    /// The cockpit's parts (empty without a cockpit).
    pub cockpit: Vec<ModelPart>,
    /// Where the cockpit is drawn: the `socket_cockpit` node's world matrix, or identity.
    pub cockpit_mount: Mat4,
    /// Bounds of LOD0 and the placed cockpit.
    pub bounds: (Vec3, Vec3),
}

/// The kit viewer's state (a world resource shared by the Kit panel and `editor.open_kit`).
#[derive(Resource)]
pub struct KitView {
    /// The open kit.
    pub kit: Option<Arc<Kit>>,
    /// Its meshes, when they loaded.
    pub meshes: Option<Arc<KitMeshes>>,
    /// Why the last open failed.
    pub error: Option<String>,
    /// The LOD shown.
    pub lod: usize,
    /// Orbit yaw and pitch, radians.
    pub orbit: (f32, f32),
    /// Draw socket gizmos over the render.
    pub show_sockets: bool,
    /// The socket highlighted in the list and the render.
    pub selected_socket: Option<String>,
    /// The clip last sent to the animation preview.
    pub clip: Option<String>,
    /// The model is the animation editor's preview rig.
    pub preview_rig: bool,
    /// A folder to open on the next panel frame (File ▸ Open kit…).
    pub open_request: Option<PathBuf>,
    /// Ask the shell to bring the Clip panel forward (a clip was played).
    pub focus_clip_panel: bool,
    /// Ask the shell to bring the Kit panel forward (a kit was opened from the menu).
    pub focus_kit_panel: bool,
    /// Bumped on every open; keys the render cache.
    pub revision: u64,
    /// The model's report for the budget meters (header-only, `crate::budget::report_from_file`).
    pub report: Option<Arc<ModelReport>>,
    /// The class the panel budgets the kit as (`None`: from `kit.json`, [`kit_class`]).
    pub budget_class: Option<ModelClass>,
    render_cache: Option<(RenderKey, egui::TextureHandle)>,
}

type RenderKey = (u64, usize, [u32; 2], [u32; 2]);

impl Default for KitView {
    fn default() -> Self {
        Self {
            kit: None,
            meshes: None,
            error: None,
            lod: 0,
            orbit: (0.6, 0.35),
            show_sockets: true,
            selected_socket: None,
            clip: None,
            preview_rig: false,
            open_request: None,
            focus_clip_panel: false,
            focus_kit_panel: false,
            revision: 0,
            report: None,
            budget_class: None,
            render_cache: None,
        }
    }
}

impl KitView {
    /// Whether a kit is open or about to open.
    #[must_use]
    pub fn is_open(&self) -> bool {
        self.kit.is_some() || self.open_request.is_some()
    }

    /// The LOD levels as JSON (`level`, `authored`, `triangles`).
    #[must_use]
    pub fn lods_json(&self) -> Value {
        self.meshes.as_ref().map_or_else(
            || json!([]),
            |meshes| {
                json!(
                    meshes
                        .lods
                        .iter()
                        .map(|lod| json!({
                            "level": lod.level,
                            "authored": lod.authored,
                            "triangles": lod.triangles,
                        }))
                        .collect::<Vec<_>>()
                )
            },
        )
    }

    /// The class the kit is budgeted as: the panel's pick, else [`kit_class`] of `kit.json`.
    #[must_use]
    pub fn budget_class(&self) -> ModelClass {
        self.budget_class.unwrap_or_else(|| {
            self.kit.as_ref().map_or(ModelClass::Prop, |kit| {
                kit_class(&kit.manifest.kind, kit.character_kit)
            })
        })
    }

    /// The kit's budget against `class`'s `limits` (`None` until a kit's model was measured).
    #[must_use]
    pub fn budget_with(&self, class: ModelClass, limits: BudgetLimits) -> Option<Budget> {
        let report = self.report.as_ref()?;
        let lods: Vec<(usize, bool, u64)> = self
            .meshes
            .as_ref()
            .map(|meshes| {
                meshes
                    .lods
                    .iter()
                    .map(|lod| (lod.level, lod.authored, lod.triangles as u64))
                    .collect()
            })
            .unwrap_or_default();
        Some(kit_budget(report, &lods, class, limits))
    }

    /// The kit's budget against [`Self::budget_class`]'s default limits.
    #[must_use]
    pub fn budget(&self) -> Option<Budget> {
        let class = self.budget_class();
        self.budget_with(class, class.limits())
    }

    /// The parts to draw at `lod` with their model matrices (the cockpit at its mount).
    #[must_use]
    pub fn placed_parts(&self, lod: usize) -> Vec<(&ModelPart, Mat4)> {
        let Some(meshes) = &self.meshes else {
            return Vec::new();
        };
        let Some(level) = meshes.lods.get(lod).or_else(|| meshes.lods.first()) else {
            return Vec::new();
        };
        level
            .parts
            .iter()
            .map(|part| (part, Mat4::IDENTITY))
            .chain(meshes.cockpit.iter().map(|part| (part, meshes.cockpit_mount)))
            .collect()
    }
}

/// Opens the kit at `dir` into `view` (replacing what was open). On failure the view shows the
/// error and keeps no kit.
///
/// # Errors
///
/// What [`crate::kit::open_kit`] refuses.
pub fn open_kit_into(view: &mut KitView, world: &mut World, dir: &Path) -> Result<Arc<Kit>, KitError> {
    view.revision += 1;
    view.render_cache = None;
    view.lod = 0;
    view.selected_socket = None;
    view.clip = None;
    view.preview_rig = false;
    view.report = None;
    view.budget_class = None;
    let mut kit = match crate::kit::open_kit(dir) {
        Ok(kit) => kit,
        Err(err) => {
            view.kit = None;
            view.meshes = None;
            view.error = Some(err.to_string());
            return Err(err);
        }
    };
    let library = world.get_resource_or_insert_with(MeshLibrary::default).clone();
    let mut warnings = Vec::new();
    view.meshes = match load_kit_meshes(&kit, &library.default_material(), &mut warnings) {
        Ok(meshes) => Some(Arc::new(meshes)),
        Err(err) => {
            warnings.push(KitWarning::new(
                &kit.model.file,
                format!("meshes not loaded: {err}"),
            ));
            None
        }
    };
    view.preview_rig = preview_clips(world, &kit, &mut warnings);
    view.report = match report_from_file(&kit.model.path) {
        Ok(report) => Some(Arc::new(report)),
        Err(err) => {
            warnings.push(KitWarning::new(
                &kit.model.file,
                format!("budget not measured: {err}"),
            ));
            None
        }
    };
    kit.warnings.extend(warnings);
    let kit = Arc::new(kit);
    view.kit = Some(Arc::clone(&kit));
    view.error = None;
    Ok(kit)
}

/// [`open_kit_into`] on the world's [`KitView`] (created when absent).
///
/// # Errors
///
/// What [`crate::kit::open_kit`] refuses.
pub fn open_kit_in_world(world: &mut World, dir: &Path) -> Result<Arc<Kit>, KitError> {
    let mut view = world.remove_resource::<KitView>().unwrap_or_default();
    let result = open_kit_into(&mut view, world, dir);
    world.insert_resource(view);
    result
}

/// Loads a kit's meshes: the LOD chain and the cockpit at its socket. A cockpit that does not
/// load is a warning.
///
/// # Errors
///
/// The model's meshes do not load.
pub fn load_kit_meshes(
    kit: &Kit,
    default_material: &Arc<CpuMaterial>,
    warnings: &mut Vec<KitWarning>,
) -> Result<KitMeshes, String> {
    let path = &kit.model.path;
    let authored: Vec<u32> = kit
        .model
        .summary
        .lod_levels
        .iter()
        .copied()
        .filter(|&level| (level as usize) < MAX_LODS)
        .collect();
    let (lods, lod0_bounds) = if authored.first() == Some(&0) {
        let mut lods = Vec::new();
        let mut bounds = (Vec3::ZERO, Vec3::ZERO);
        for level in authored {
            let model = load_gltf_model_filtered(path, default_material, &|name| {
                lod_suffix(name).is_none_or(|l| l == level)
            })?;
            if level == 0 {
                bounds = (model.aabb_min, model.aabb_max);
            }
            lods.push(KitLod {
                level: level as usize,
                authored: true,
                triangles: model.triangles(),
                parts: model.parts,
            });
        }
        (lods, bounds)
    } else {
        let model = load_gltf_model_filtered(path, default_material, &|_| true)?;
        let lods = build_lods(&model)
            .into_iter()
            .take(MAX_LODS)
            .enumerate()
            .map(|(level, lod)| KitLod {
                level,
                authored: false,
                triangles: lod.triangles,
                parts: lod.parts,
            })
            .collect();
        (lods, (model.aabb_min, model.aabb_max))
    };
    let cockpit_mount = kit
        .cockpit_mount
        .map_or(Mat4::IDENTITY, |m| Mat4::from_cols_array(&m));
    let mut bounds = lod0_bounds;
    let mut cockpit = Vec::new();
    if let Some(model) = &kit.cockpit {
        match load_gltf_model_filtered(&model.path, default_material, &|name| {
            lod_suffix(name).is_none_or(|l| l == 0)
        }) {
            Ok(loaded) => {
                for corner in 0..8 {
                    let pick = |bit: usize, lo: f32, hi: f32| if corner & bit == 0 { lo } else { hi };
                    let local = Vec3::new(
                        pick(1, loaded.aabb_min.x, loaded.aabb_max.x),
                        pick(2, loaded.aabb_min.y, loaded.aabb_max.y),
                        pick(4, loaded.aabb_min.z, loaded.aabb_max.z),
                    );
                    let p = cockpit_mount.transform_point3(local);
                    bounds = (bounds.0.min(p), bounds.1.max(p));
                }
                cockpit = loaded.parts;
            }
            Err(err) => warnings.push(KitWarning::new(
                &model.file,
                format!("cockpit meshes not loaded: {err}"),
            )),
        }
    }
    Ok(KitMeshes {
        lods,
        cockpit,
        cockpit_mount,
        bounds,
    })
}

/// Makes a skinned kit model the animation editor's preview rig. Returns whether it did.
fn preview_clips(world: &mut World, kit: &Kit, warnings: &mut Vec<KitWarning>) -> bool {
    let has_clips = kit.clips.iter().any(|clip| clip.source == ClipSource::Model);
    if kit.model.summary.skins == 0 {
        if has_clips {
            warnings.push(KitWarning::new(
                &kit.model.file,
                "the model has no skin: its clips are listed, but the animation preview plays skinned clips only",
            ));
        }
        return false;
    }
    let editor = world.get_resource_or_insert_with(crate::anim::AnimEditor::default);
    if editor.edits_dirty() && editor.docs.edits != Default::default() {
        warnings.push(KitWarning::new(
            &kit.model.file,
            "the animation editor has unsaved clip edits: save them, then reopen the kit to preview its clips",
        ));
        return false;
    }
    // The authoring sidecar sits beside the model; it must stay inside the kit folder too.
    let sidecar_name = format!("{}.animedit.ron", kit.model.file);
    if let Err(err) = KitFolder::new(&kit.root).and_then(|folder| folder.resolve(&sidecar_name)) {
        warnings.push(KitWarning::new(&sidecar_name, format!("clip preview off: {err}")));
        return false;
    }
    let rig = match crate::anim::PreviewRig::from_gltf(&kit.model.path) {
        Ok(rig) => rig,
        Err(err) => {
            warnings.push(KitWarning::new(
                &kit.model.file,
                format!("clip preview off: {err}"),
            ));
            return false;
        }
    };
    let mut editor = world.resource_mut::<crate::anim::AnimEditor>();
    match editor.set_rig(rig, Some(kit.root.join(&sidecar_name))) {
        Ok(()) => true,
        Err(err) => {
            warnings.push(KitWarning::new(&sidecar_name, format!("clip preview off: {err}")));
            false
        }
    }
}

/// Plays `clip` in the animation preview (the Clip panel). Returns false when the clip is not
/// one of the preview rig's.
pub fn play_clip(view: &mut KitView, world: &mut World, clip: &str) -> bool {
    if !view.preview_rig {
        return false;
    }
    let Some(mut editor) = world.get_resource_mut::<crate::anim::AnimEditor>() else {
        return false;
    };
    if editor.rig.as_ref().and_then(|rig| rig.clip(clip)).is_none() {
        return false;
    }
    editor.ui.clip = Some(clip.to_string());
    editor.ui.scrub = 0.0;
    editor.ui.clip_playing = true;
    view.clip = Some(clip.to_string());
    view.focus_clip_panel = true;
    true
}

