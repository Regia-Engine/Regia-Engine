//! Hot-reload runtime prototype (specs/20 §§ 2–3, specs/10 § 2.4).
//!
//! * [`GamePlugin`] + [`export_game!`]: the game library's entry point and ABI hash symbol.
//! * [`GameRegistrar`]: every registration the game makes is recorded with its owner, so teardown is
//!   one call ([`teardown`]).
//! * [`take_snapshot`] / [`restore`]: reflected state keyed by entity + type path, stored as RON text
//!   per field. Text holds no pointer into the old library; field-by-field restore gives "new field
//!   → default, removed field → dropped, changed type → default + warning".
//! * [`check_component_identity`]: detects the bevy_ecs hazard the spike found (a `TypeId` that
//!   survives a rebuild keeps the *old* `ComponentId` and its old layout; see ADR-015 draft).

use std::alloc::Layout;
use std::any::{Any, TypeId};
use std::collections::{HashMap, HashSet};

use bevy_ecs::prelude::*;
use bevy_ecs::reflect::AppTypeRegistry;
use bevy_ecs::schedule::{InternedScheduleLabel, ScheduleCleanupPolicy, ScheduleLabel};
use bevy_ecs::system::ScheduleSystem;
use bevy_reflect::serde::{TypedReflectDeserializer, TypedReflectSerializer};
use bevy_reflect::std_traits::ReflectDefault;
use bevy_reflect::{
    FromReflect, GetTypeRegistration, PartialReflect, Reflect, ReflectMut, ReflectRef, TypePath, TypeRegistry,
};
use regia_app::App;
use serde::de::DeserializeSeed;

const fn parse_u64(s: &str) -> u64 {
    let b = s.as_bytes();
    let mut i = 0;
    let mut v: u64 = 0;
    while i < b.len() {
        v = v.wrapping_mul(10).wrapping_add((b[i] - b'0') as u64);
        i += 1;
    }
    v
}

/// Hash of rustc version + engine version + profile + target + features (specs/20 § 2).
pub const ABI_HASH: u64 = parse_u64(env!("SPIKE_ABI_HASH"));
/// Symbol of the game entry function generated by [`export_game!`].
pub const ENTRY_SYMBOL: &[u8] = b"regia_game_entry";
/// Symbol of the `u64` ABI hash static generated by [`export_game!`].
pub const ABI_SYMBOL: &[u8] = b"REGIA_ABI_HASH";
/// Signature of the entry function.
pub type GameEntryFn = fn() -> Box<dyn GamePlugin>;

/// The game's plugin, as seen by the host.
pub trait GamePlugin: Send + Sync + 'static {
    /// Display name.
    fn name(&self) -> &'static str;
    /// Registers types, resources and systems. Everything goes through `reg` so it is owner-tagged.
    fn register(&self, reg: &mut GameRegistrar<'_>);
    /// Called after `register` and after the snapshot was restored (first load: after `register`).
    /// Start threads here, from restored state.
    fn on_load(&self, _world: &mut World) {}
    /// Called before the snapshot is taken: stop and join threads, flush their state into reflected
    /// resources so the snapshot carries it.
    fn on_unload(&self, _world: &mut World) {}
}

/// Generates the game library's entry point and `REGIA_ABI_HASH` (specs/20 § 2).
#[macro_export]
macro_rules! export_game {
    ($plugin:expr) => {
        /// Hot-reload entry point (specs/20 § 2).
        #[allow(unsafe_code)]
        // SAFETY: the host's lookup key; a second definition in one library is a link error.
        #[unsafe(no_mangle)]
        pub fn regia_game_entry() -> ::std::boxed::Box<dyn $crate::hot::GamePlugin> {
            ::std::boxed::Box::new($plugin)
        }
        /// ABI hash of the engine this library was built against.
        #[allow(unsafe_code)]
        // SAFETY: as for `regia_game_entry`; the host reads it as a `u64`, which it is.
        #[unsafe(no_mangle)]
        pub static REGIA_ABI_HASH: u64 = $crate::hot::ABI_HASH;
    };
}

/// System set every game system is placed in; removing the set removes the game's systems.
#[derive(SystemSet, Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct OwnerSet(pub u32);

/// A component or resource type registered by the game.
#[derive(Debug, Clone)]
pub struct OwnedType {
    /// `TypeId` in the library that registered it.
    pub type_id: TypeId,
    /// Stable key across rebuilds.
    pub type_path: String,
    /// Layout in the library that registered it.
    pub layout: Layout,
    /// Resource (true) or component (false).
    pub is_resource: bool,
}

/// Everything one game plugin instance registered.
#[derive(Debug, Clone, Default)]
pub struct Owned {
    /// Owner id (a new one per load).
    pub owner: u32,
    /// Components and resources.
    pub types: Vec<OwnedType>,
    /// Every reflect registration the plugin added (including nested field types).
    pub reflect_types: Vec<TypeId>,
    /// Schedules the plugin added systems to.
    pub schedules: Vec<InternedScheduleLabel>,
    /// Number of registered bevy components when the plugin started registering.
    pub components_before: usize,
}

/// Records every registration of one game plugin (specs/10 § 2.4 ownership tags).
pub struct GameRegistrar<'a> {
    app: &'a mut App,
    owned: Owned,
    before: HashSet<TypeId>,
}

impl<'a> GameRegistrar<'a> {
    /// Starts recording registrations for `owner`.
    pub fn new(app: &'a mut App, owner: u32) -> Self {
        let registry = app.world_mut().get_resource_or_init::<AppTypeRegistry>().clone();
        let before = registry.read().iter().map(|r| r.type_id()).collect();
        let components_before = app.world().components().len();
        Self {
            app,
            owned: Owned {
                owner,
                components_before,
                ..Default::default()
            },
            before,
        }
    }

    fn register_reflect<T: GetTypeRegistration>(&mut self) {
        let registry = self.app.world_mut().resource::<AppTypeRegistry>().clone();
        registry.write().register::<T>();
    }

    /// Registers a reflected component (`#[reflect(Component, Default)]` required).
    pub fn component<T>(&mut self) -> &mut Self
    where
        T: Component + Reflect + TypePath + GetTypeRegistration + FromReflect + Default,
    {
        self.register_reflect::<T>();
        self.owned.types.push(OwnedType {
            type_id: TypeId::of::<T>(),
            type_path: T::type_path().to_string(),
            layout: Layout::new::<T>(),
            is_resource: false,
        });
        self
    }

    /// Registers a reflected resource (`#[reflect(Resource, Default)]` required) and inserts its
    /// default value.
    pub fn resource<R>(&mut self) -> &mut Self
    where
        R: Resource + Reflect + TypePath + GetTypeRegistration + FromReflect + Default,
    {
        self.register_reflect::<R>();
        self.app.init_resource::<R>();
        self.owned.types.push(OwnedType {
            type_id: TypeId::of::<R>(),
            type_path: R::type_path().to_string(),
            layout: Layout::new::<R>(),
            is_resource: true,
        });
        self
    }

    /// Adds systems, tagged with the owner set.
    pub fn add_systems<M>(
        &mut self,
        schedule: impl ScheduleLabel,
        systems: impl IntoScheduleConfigs<ScheduleSystem, M>,
    ) -> &mut Self {
        let label = schedule.intern();
        if !self.owned.schedules.contains(&label) {
            self.owned.schedules.push(label);
        }
        self.app
            .add_systems(label, systems.in_set(OwnerSet(self.owned.owner)));
        self
    }

    /// The world (for one-off setup).
    pub fn world_mut(&mut self) -> &mut World {
        self.app.world_mut()
    }

    /// Ends recording and returns what the plugin owns.
    pub fn finish(mut self) -> Owned {
        let registry = self.app.world_mut().resource::<AppTypeRegistry>().clone();
        self.owned.reflect_types = registry
            .read()
            .iter()
            .map(|r| r.type_id())
            .filter(|id| !self.before.contains(id))
            .collect();
        self.owned
    }
}

/// Values that outlive game reloads (option (b) for external simulations: the value's type lives in
/// a library that is never reloaded). Keyed by name; values are type-checked on access.
#[derive(Resource, Default)]
pub struct PersistentStore(HashMap<String, Box<dyn Any + Send + Sync>>);

impl PersistentStore {
    /// The stored value, creating it with `init` the first time. `None` if a value of another type
    /// is stored under `key` (for example because its library was rebuilt — restart required).
    pub fn get_or_insert_with<T: Any + Send + Sync>(
        &mut self,
        key: &str,
        init: impl FnOnce() -> T,
    ) -> Option<&mut T> {
        self.0
            .entry(key.to_string())
            .or_insert_with(|| Box::new(init()))
            .downcast_mut::<T>()
    }

    /// The stored value, if present and of type `T`.
    pub fn get_mut<T: Any + Send + Sync>(&mut self, key: &str) -> Option<&mut T> {
        self.0.get_mut(key).and_then(|v| v.downcast_mut::<T>())
    }
}

/// One value's reflected fields, as RON text per field.
#[derive(Debug, Clone)]
pub enum Fields {
    /// Struct: `(field name, RON)`.
    Struct(Vec<(String, String)>),
    /// Anything else: the whole value as RON.
    Whole(String),
}

/// Reflected state of every game-owned component and resource (specs/20 § 3 step 4).
#[derive(Debug, Clone, Default)]
pub struct Snapshot {
    /// `(entity, type path, fields)`.
    pub components: Vec<(Entity, String, Fields)>,
    /// `(type path, fields)`.
    pub resources: Vec<(String, Fields)>,
}

impl Snapshot {
    /// Total RON bytes (for the report).
    pub fn bytes(&self) -> usize {
        let f = |fields: &Fields| match fields {
            Fields::Struct(v) => v.iter().map(|(a, b)| a.len() + b.len()).sum(),
            Fields::Whole(s) => s.len(),
        };
        self.components
            .iter()
            .map(|(_, p, x)| p.len() + f(x))
            .sum::<usize>()
            + self.resources.iter().map(|(p, x)| p.len() + f(x)).sum::<usize>()
    }
}

fn to_ron(value: &dyn PartialReflect, registry: &TypeRegistry) -> String {
    ron::to_string(&TypedReflectSerializer::new(value, registry)).unwrap_or_default()
}

fn fields_of(value: &dyn PartialReflect, registry: &TypeRegistry) -> Fields {
    match value.reflect_ref() {
        ReflectRef::Struct(s) => Fields::Struct(
            (0..s.field_len())
                .filter_map(|i| Some((s.name_at(i)?.to_string(), to_ron(s.field_at(i)?, registry))))
                .collect(),
        ),
        _ => Fields::Whole(to_ron(value, registry)),
    }
}

fn entities_with(world: &World, id: bevy_ecs::component::ComponentId) -> Vec<Entity> {
    world
        .archetypes()
        .iter()
        .filter(|a| a.contains(id))
        .flat_map(|a| a.entities().iter().map(|e| e.id()))
        .collect()
}

/// Snapshots every component/resource in `owned` (specs/20 § 3 step 4).
pub fn take_snapshot(world: &World, owned: &Owned) -> Snapshot {
    let registry = world.resource::<AppTypeRegistry>().clone();
    let registry = registry.read();
    let mut snap = Snapshot::default();
    for t in &owned.types {
        let (Some(reg), Some(cid)) = (registry.get(t.type_id), world.components().get_id(t.type_id)) else {
            continue;
        };
        let Some(rc) = reg.data::<ReflectComponent>() else {
            continue;
        };
        if t.is_resource {
            if let Some(e) = world.resource_entities().get(cid)
                && let Some(v) = rc.reflect(world.entity(e))
            {
                snap.resources
                    .push((t.type_path.clone(), fields_of(v.as_partial_reflect(), &registry)));
            }
        } else {
            for e in entities_with(world, cid) {
                if let Some(v) = rc.reflect(world.entity(e)) {
                    snap.components.push((
                        e,
                        t.type_path.clone(),
                        fields_of(v.as_partial_reflect(), &registry),
                    ));
                }
            }
        }
    }
    snap
}

/// Counts left behind by [`teardown`] (must be zero, specs/20 § 3 step 5).
#[derive(Debug, Default, Clone, Copy)]
pub struct TeardownReport {
    /// Systems removed.
    pub systems_removed: usize,
    /// Component instances removed.
    pub components_removed: usize,
    /// Reflect registrations removed.
    pub registrations_removed: usize,
    /// Owned component instances still in the world afterwards.
    pub leftover_instances: usize,
}

/// Removes everything `owned` registered (specs/20 § 3 step 5: `app.remove_owned(owner)`).
pub fn teardown(world: &mut World, owned: &Owned) -> TeardownReport {
    let mut report = TeardownReport::default();
    for t in &owned.types {
        let Some(cid) = world.components().get_id(t.type_id) else {
            continue;
        };
        if t.is_resource {
            world.remove_resource_by_id(cid);
        } else {
            for e in entities_with(world, cid) {
                world.entity_mut(e).remove_by_id(cid);
                report.components_removed += 1;
            }
        }
    }
    world.flush();
    // Take `Schedules` out of the world: initializing a schedule may insert resources, which
    // `World::resource_scope` forbids.
    if let Some(mut schedules) = world.remove_resource::<Schedules>() {
        for label in &owned.schedules {
            if let Ok(n) = schedules.remove_systems_in_set(
                *label,
                OwnerSet(owned.owner),
                world,
                ScheduleCleanupPolicy::RemoveSetAndSystems,
            ) {
                report.systems_removed += n;
            }
        }
        world.insert_resource(schedules);
    }
    // Rebuild the reflect registry without the plugin's registrations (bevy_reflect has no removal).
    let registry = world.resource::<AppTypeRegistry>().clone();
    {
        let mut reg = registry.write();
        let drop: HashSet<TypeId> = owned.reflect_types.iter().copied().collect();
        let mut fresh = TypeRegistry::empty();
        for r in reg.iter() {
            if drop.contains(&r.type_id()) {
                report.registrations_removed += 1;
            } else {
                fresh.add_registration(r.clone());
            }
        }
        *reg = fresh;
    }
    for t in owned.types.iter().filter(|t| !t.is_resource) {
        if let Some(cid) = world.components().get_id(t.type_id) {
            report.leftover_instances += entities_with(world, cid).len();
        }
    }
    report
}

/// A newly registered type whose `TypeId` already had a `ComponentId` from an earlier load.
#[derive(Debug, Clone)]
pub struct IdentityClash {
    /// Type path.
    pub type_path: String,
    /// Layout bevy_ecs still has on file (from the old library).
    pub registered: Layout,
    /// Layout of the newly loaded type.
    pub new: Layout,
}

/// Checks the newly loaded plugin's types against bevy_ecs' component registry. A `TypeId` that
/// already has a `ComponentId` reuses the old component's layout, drop and hooks — unsound when the
/// layout changed. Returns all reuses; callers must refuse to restore if any layout differs.
pub fn check_component_identity(world: &World, owned: &Owned) -> Vec<IdentityClash> {
    owned
        .types
        .iter()
        .filter_map(|t| {
            let cid = world.components().get_id(t.type_id)?;
            if cid.index() >= owned.components_before {
                return None; // registered by this plugin instance
            }
            let info = world.components().get_info(cid)?;
            Some(IdentityClash {
                type_path: t.type_path.clone(),
                registered: info.layout(),
                new: t.layout,
            })
        })
        .collect()
}

/// What [`restore`] did.
#[derive(Debug, Default, Clone, Copy)]
pub struct RestoreReport {
    /// Component instances inserted.
    pub components: usize,
    /// Resources restored.
    pub resources: usize,
    /// Fields that kept their default (new fields, or failed to deserialize).
    pub defaulted_fields: usize,
    /// Snapshot fields the new type no longer has.
    pub dropped_fields: usize,
    /// Fields whose type changed (default + warning).
    pub retyped_fields: usize,
    /// Snapshot entries whose type no longer exists.
    pub dropped_values: usize,
}

fn deserialize(ron_text: &str, type_id: TypeId, registry: &TypeRegistry) -> Option<Box<dyn PartialReflect>> {
    let reg = registry.get(type_id)?;
    let mut de = ron::de::Deserializer::from_str(ron_text).ok()?;
    TypedReflectDeserializer::new(reg, registry)
        .deserialize(&mut de)
        .ok()
}

fn apply_fields(
    target: &mut dyn PartialReflect,
    fields: &Fields,
    registry: &TypeRegistry,
    rep: &mut RestoreReport,
) {
    match fields {
        Fields::Struct(list) => {
            let ReflectMut::Struct(s) = target.reflect_mut() else {
                rep.dropped_fields += list.len();
                return;
            };
            let names: HashSet<&str> = list.iter().map(|(n, _)| n.as_str()).collect();
            rep.defaulted_fields += (0..s.field_len())
                .filter_map(|i| s.name_at(i))
                .filter(|n| !names.contains(n))
                .count();
            for (name, text) in list {
                let Some(field) = s.field_mut(name) else {
                    rep.dropped_fields += 1;
                    continue;
                };
                let Some(info) = field.get_represented_type_info() else {
                    rep.retyped_fields += 1;
                    continue;
                };
                match deserialize(text, info.type_id(), registry) {
                    Some(v) if field.try_apply(v.as_ref()).is_ok() => {}
                    _ => {
                        tracing::warn!("hot reload: field `{name}` changed type; using the default");
                        rep.retyped_fields += 1;
                    }
                }
            }
        }
        Fields::Whole(text) => {
            let ok = target
                .get_represented_type_info()
                .and_then(|info| deserialize(text, info.type_id(), registry))
                .is_some_and(|v| target.try_apply(v.as_ref()).is_ok());
            if !ok {
                rep.retyped_fields += 1;
            }
        }
    }
}

/// Restores a snapshot through the *new* registry (specs/20 § 3 step 7).
pub fn restore(world: &mut World, snap: &Snapshot) -> RestoreReport {
    let registry = world.resource::<AppTypeRegistry>().clone();
    let registry = registry.read();
    let mut rep = RestoreReport::default();
    for (entity, path, fields) in &snap.components {
        let Some(reg) = registry.get_with_type_path(path) else {
            rep.dropped_values += 1;
            continue;
        };
        let (Some(rc), Some(def)) = (reg.data::<ReflectComponent>(), reg.data::<ReflectDefault>()) else {
            rep.dropped_values += 1;
            continue;
        };
        let mut value = def.default();
        apply_fields(value.as_partial_reflect_mut(), fields, &registry, &mut rep);
        if let Ok(mut e) = world.get_entity_mut(*entity) {
            rc.insert(&mut e, value.as_partial_reflect(), &registry);
            rep.components += 1;
        }
    }
    for (path, fields) in &snap.resources {
        let Some(reg) = registry.get_with_type_path(path) else {
            rep.dropped_values += 1;
            continue;
        };
        let Some(rc) = reg.data::<ReflectComponent>() else {
            continue;
        };
        let Some(cid) = world.components().get_id(reg.type_id()) else {
            continue;
        };
        let Some(e) = world.resource_entities().get(cid) else {
            continue;
        };
        let mut entity = world.entity_mut(e);
        if let Some(mut v) = rc.reflect_mut(&mut entity) {
            apply_fields(v.as_partial_reflect_mut(), fields, &registry, &mut rep);
            rep.resources += 1;
        }
    }
    rep
}
